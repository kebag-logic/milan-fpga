"""Generate the end-station configuration key reference from the builder.

The reference is the "Key reference" section of README-parameters.md, between
its two markers. It is written from four inputs, and only the last is kept by
hand (#797):

- the key set: every key `load_config` reads, recorded the way
  test_builder.py gate 32 records it (`_loader_key_paths`);
- the behaviour: whether a key is required, its default, its limits and the
  check that refuses a bad value, each PROBED by loading the reference
  configuration with the key removed, set or broken;
- the contract: each key's clause and row in docs/ENDSTATION_BUILDER.md
  section 3, the per-key table gate 32 holds in step with the loaders;
- key_reference.yaml: a one-line meaning and the probe values.

So a number in the table is either a builder constant, rendered by name, or a
value the builder was just seen to accept or refuse. The hand-kept file may
not spell a digit in its prose; a key the loaders do not read, a key they read
with no entry, a probe the builder does not honour and a stale section are
all refusals.

Usage:
    python3 sw/builder/gen_key_reference.py             # rewrite the section
    python3 sw/builder/gen_key_reference.py --check     # fail on a stale section
    python3 sw/builder/gen_key_reference.py --selftest  # prove each refusal bites
"""

from __future__ import annotations

import argparse
import contextlib
import copy
import difflib
import hashlib
import json
import os
import re
import sys
import traceback
import types
from collections.abc import Iterator
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE))
import endstation_builder as eb  # noqa: E402
import test_builder as tb  # noqa: E402

PAGE = HERE / "README-parameters.md"
SOURCE = HERE / "key_reference.yaml"
CONTRACT = ROOT / "docs" / "ENDSTATION_BUILDER.md"
CONTRACT_LINK = "../../docs/ENDSTATION_BUILDER.md#3-config-schema--aem-descriptor-mapping"
#: The configuration every probe starts from unless an entry names another:
#: the shipping 1x1 TDM8 shape the guide's worked example edits.
BASE = "endstation_ax7101_1x1_tdm8"
START = "<!-- key-reference:start (generated by sw/builder/gen_key_reference.py; do not edit) -->"
END = "<!-- key-reference:end -->"
PROBE_KEY = "zz_unknown_probe"
#: A refusal message is cut here, at a word boundary, so a row stays a row.
MESSAGE_CHARS = 110
FIELDS = {"meaning", "need", "allowed", "range", "length", "default", "default_text",
          "bad", "ok", "unchecked", "base"}
#: A repository page a builder message names; the table links it.
DOC_PATH = re.compile(r"(?<![\w/.\[])((?:docs|sw|hdl|tb|scripts|configs)/[\w./-]+\.md)\b")
#: A number in hand-kept prose: a digit run not part of a name such as I2S or e1.
NUMBER = re.compile(r"(?<![A-Za-z0-9])\d+(?![A-Za-z0-9])")
PLACEHOLDER = re.compile(r"\{([A-Z_][A-Z0-9_]*)((?:\[[^\]]+\])*)(?:\|([a-z0-9]+))?\}")


class KeyReferenceError(Exception):
    """The source, the builder and the contract disagree; the page is not written."""


@dataclass(frozen=True)
class Outcome:
    """One probe load: the normalized config, or what stopped it."""
    ok: bool
    config: str = ""
    kind: str = ""
    function: str = ""
    message: str = ""
    loaded: Any = field(default=None, compare=False, repr=False)


def _segments(key: str) -> list[Any]:
    """`streams.talkers[].channels` as ['streams', 'talkers', 0, 'channels']."""
    out: list[Any] = []
    for part in key.split("."):
        if part.endswith("[]"):
            out.extend([part[:-2], 0])
        else:
            out.append(part)
    return out


def _parent(doc: dict, key: str, create: bool) -> tuple[Any, Any] | None:
    """The container holding `key` and the last segment, or None when absent."""
    segs = _segments(key)
    node: Any = doc
    for seg in segs[:-1]:
        if isinstance(seg, int):
            if not isinstance(node, list) or len(node) <= seg:
                return None
            node = node[seg]
            continue
        if not isinstance(node, dict):
            return None
        if seg not in node or node[seg] is None:
            if not create:
                return None
            node[seg] = {}
        node = node[seg]
    return node, segs[-1]


def with_key(doc: dict, key: str, value: Any) -> dict:
    """A copy of `doc` declaring `key: value`."""
    out = copy.deepcopy(doc)
    found = _parent(out, key, create=True)
    if found is None:
        raise KeyReferenceError(f"{key}: the probe configuration has no place for it")
    found[0][found[1]] = copy.deepcopy(value)
    return out


def without_key(doc: dict, key: str) -> dict:
    """A copy of `doc` that does not declare `key`."""
    out = copy.deepcopy(doc)
    found = _parent(out, key, create=False)
    if found is not None and isinstance(found[0], dict):
        found[0].pop(found[1], None)
    return out


def declares(doc: dict, key: str) -> bool:
    """Does `doc` state `key`?"""
    found = _parent(copy.deepcopy(doc), key, create=False)
    return found is not None and isinstance(found[0], dict) and found[1] in found[0]


def _scrub(text: str) -> str:
    """Builder text with this checkout's location removed; refuse any left."""
    text = text.replace(str(ROOT) + os.sep, "").replace(str(ROOT), ".")
    if re.search(r"(?<![\w.])/(?:home|tmp|data|Users)/", text):
        raise KeyReferenceError(f"a probe message names a host path: {text[:60]}")
    return text


def load(config: str, doc: dict) -> Outcome:
    """`load_config` over `doc`, read as if it were the file `config`.

    The document is handed to the builder through its own `yaml` binding, the
    method gate 32 uses, so nothing is written and the probe sees exactly the
    loaders a build runs. `config` is repository-relative, so no refusal text
    can carry this checkout's location into the page."""
    real = eb.yaml
    eb.yaml = types.SimpleNamespace(safe_load=lambda _fh: copy.deepcopy(doc))
    try:
        cfg = eb.load_config(config)
    except Exception as exc:  # noqa: BLE001 - the kind of failure is the finding
        frames = [f for f in traceback.extract_tb(exc.__traceback__)
                  if Path(f.filename).resolve() == Path(eb.__file__).resolve()]
        where = frames[-1].name if frames else "(outside the builder)"
        return Outcome(False, kind=type(exc).__name__, function=where,
                       message=_scrub(" ".join(str(exc).split())))
    finally:
        eb.yaml = real
    return Outcome(True, config=json.dumps(cfg, sort_keys=True, default=repr), loaded=cfg)


def product(outcome: Outcome) -> str:
    """What a loaded config builds: the SoC argv, the descriptor image and the
    generated headers and tables, without writing any of them. Two configs
    whose normalized forms differ only in what is carried when declared (a
    name stated at its default) build the same product."""
    cfg = outcome.loaded
    overlay = eb.emit_aem_overlay(cfg)
    image = eb._entity_model_image(cfg, overlay)["aem_desc.bin"]
    lwsrp = eb.emit_lwsrp_table(cfg)
    lwsrp.pop("_source_config", None)
    return json.dumps(dict(
        argv=eb.emit_soc_argv(cfg), image=hashlib.sha256(image).hexdigest(),
        adp=eb.emit_adp_shape_svh(cfg, overlay), csr=eb.emit_csr_defaults_svh(cfg),
        lwsrp=lwsrp, platform=eb.emit_platform_shape(cfg)), sort_keys=True, default=repr)


def same_build(a: Outcome, b: Outcome) -> bool:
    """Do two probe loads end the same way: one refusal, or one product?"""
    if a == b:
        return True
    return a.ok and b.ok and product(a) == product(b)


@contextlib.contextmanager
def at_root() -> Iterator[None]:
    """Run with the repository as the working directory."""
    here = Path.cwd()
    os.chdir(ROOT)
    try:
        yield
    finally:
        os.chdir(here)


def base_document(stem: str) -> tuple[str, dict]:
    """(repository-relative path, parsed document) of one tracked config."""
    rel = f"configs/{stem}.yaml"
    if not (ROOT / rel).is_file():
        raise KeyReferenceError(f"base {stem!r}: no tracked configs/{stem}.yaml")
    return rel, yaml.safe_load((ROOT / rel).read_text(encoding="utf-8"))


def _expand(name: str) -> list[str]:
    """`a.{b,c}` as ['a.b', 'a.c']; any other name as itself."""
    m = re.search(r"\{([a-z0-9_,]+)\}", name)
    if not m:
        return [name]
    return [name.replace(m.group(0), part) for part in m.group(1).split(",")]


def read_source(text: str) -> dict[str, dict]:
    """{key: entry} from key_reference.yaml, groups expanded, fields checked."""
    raw = yaml.safe_load(text) or {}
    if not isinstance(raw, dict):
        raise KeyReferenceError(f"{SOURCE.name}: must be a mapping of key to entry")
    out: dict[str, dict] = {}
    for name, entry in raw.items():
        if not isinstance(entry, dict) or "meaning" not in entry:
            raise KeyReferenceError(f"{SOURCE.name}: {name}: needs a mapping with a meaning")
        unknown = set(entry) - FIELDS
        if unknown:
            raise KeyReferenceError(f"{SOURCE.name}: {name}: unknown field(s) {sorted(unknown)}")
        for field in ("meaning", "allowed", "default_text", "unchecked"):
            prose = PLACEHOLDER.sub("", str(entry.get(field, "")))
            if NUMBER.search(prose):
                raise KeyReferenceError(
                    f"{SOURCE.name}: {name}.{field} spells a number; numbers come from "
                    f"a builder constant ({{NAME}}) or a probed range, never from this file")
        for key in _expand(name):
            if key in out:
                raise KeyReferenceError(f"{SOURCE.name}: {key} has two entries")
            out[key] = entry
    return out


def _constant(name: str, subscripts: str, flt: str | None, leaf: str) -> Any:
    """One `{NAME[k]|filter}` placeholder's value, read off the builder module.
    A subscript `@` stands for the key's own last name, so one grouped entry
    renders each member's value from the builder's table."""
    if not hasattr(eb, name):
        raise KeyReferenceError(f"{{{name}}}: endstation_builder has no such constant")
    value = getattr(eb, name)
    for sub in re.findall(r"\[([^\]]+)\]", subscripts):
        sub = leaf if sub == "@" else sub
        value = value[int(sub)] if isinstance(value, (list, tuple)) else value[sub]
    if flt == "keys":
        value = list(value)
    elif flt == "bits":
        value = int(value).bit_length()
    elif flt is not None and re.fullmatch(r"hex\d+", flt):
        value = f"0x{int(value):0{int(flt[3:])}X}"
    elif flt is not None:
        raise KeyReferenceError(f"{{{name}|{flt}}}: unknown filter")
    return value


def _code(value: Any) -> str:
    """A value as the table prints it."""
    if isinstance(value, bool):
        return f"`{str(value).lower()}`"
    if isinstance(value, (list, tuple, set, frozenset)):
        items = sorted(value, key=str) if isinstance(value, (set, frozenset)) else value
        return ", ".join(_code(v) for v in items) if items else "`[]`"
    if isinstance(value, dict):
        return _code(list(value))
    if value == "":
        return '`""`'
    return f"`{value}`"


def render_text(text: str, key: str = "") -> str:
    """Hand-kept prose with each builder constant rendered in place."""
    return PLACEHOLDER.sub(lambda m: _code(_constant(m[1], m[2], m[3], leaf_of(key))), text)


def leaf_of(key: str) -> str:
    """The last name of a key path, without a list marker."""
    return key.rsplit(".", 1)[-1].removesuffix("[]")


def _value(spec: Any) -> Any:
    """A probe value; `{repeat: s, times: n}` spells a long string."""
    if isinstance(spec, dict) and set(spec) == {"repeat", "times"}:
        return str(spec["repeat"]) * int(spec["times"])
    return spec


def _short(message: str) -> str:
    """A refusal cut to one table cell, a page it names made a link."""
    if len(message) > MESSAGE_CHARS:
        message = message[:MESSAGE_CHARS].rsplit(" ", 1)[0] + " ..."
    message = message.replace("|", "\\|").replace("`", "'")
    return DOC_PATH.sub(lambda m: f"[{m[1]}](../../{m[1]})"
                        if (ROOT / m[1]).is_file() else m[1], message)


@dataclass(frozen=True)
class Row:
    """One generated key row."""
    key: str
    meaning: str
    need: str
    default: str
    allowed: str
    refused: str
    clause: str
    rows: str


def contract() -> tuple[dict[str, list[str]], dict[str, str]]:
    """({key: section 3 row numbers}, {row number: clause cell}).

    The key column is read by gate 32's own parser, so this page and the gate
    cannot disagree about which row carries a key."""
    doc = CONTRACT.read_text(encoding="utf-8")
    rows = tb._key_map_rows(doc)
    start = doc.index(tb.KEY_MAP_HEADING)
    end = doc.find("\n## ", start + 1)
    clauses: dict[str, str] = {}
    for line in doc[start:end].splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if line.startswith("|") and len(cells) >= 5 and cells[0] not in ("#", "") \
                and not set(cells[0]) <= set("-"):
            clauses[cells[0]] = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", cells[3])
    return rows, clauses


def probe_key(key: str, entry: dict, cache: dict[str, tuple[str, dict, Outcome]]) -> Row:
    """Probe one key against the builder and return its row, or refuse."""
    stem = entry.get("base", BASE)
    if stem not in cache:
        rel, doc = base_document(stem)
        cache[stem] = (rel, doc, load(rel, doc))
    rel, doc, plain = cache[stem]
    if not plain.ok:
        raise KeyReferenceError(f"base {stem}: does not load ({plain.message})")
    removed = load(rel, without_key(doc, key))
    need = entry.get("need", "optional")
    if need not in ("optional", "required"):
        raise KeyReferenceError(f"{key}: need is required or optional, not {need!r}")
    if need == "required":
        # Removal must be refused, and by a check about THIS key: a removal
        # refused because the default contradicts a sibling is an optional key.
        if removed.ok or leaf_of(key) not in removed.message:
            raise KeyReferenceError(f"{key}: declared required, but omitting it is "
                                 + ("accepted" if removed.ok else f"refused for another reason "
                                    f"({removed.function}: {removed.message[:80]})"))
        if "default" in entry or "default_text" in entry:
            raise KeyReferenceError(f"{key}: the builder requires it, so it has no default")
        default = "-"
    elif "default" in entry:
        # Omitting the key and stating the default must load to the same
        # outcome: the same config, or the same refusal where the base's
        # other keys contradict the default. A default written as one
        # placeholder is the builder constant itself, probed raw.
        spec = entry["default"]
        whole = PLACEHOLDER.fullmatch(spec) if isinstance(spec, str) else None
        value = _constant(whole[1], whole[2], None, leaf_of(key)) if whole else _value(spec)
        stated = load(rel, with_key(doc, key, value))
        if not same_build(stated, removed):
            raise KeyReferenceError(
                f"{key}: default {spec!r} is not what omitting the key builds")
        default = render_text(spec, key) if whole else _code(spec)
    elif "default_text" in entry:
        default = render_text(entry["default_text"], key)
    else:
        raise KeyReferenceError(f"{key}: optional, so its entry needs default or default_text")
    limits: list[str] = []
    if "range" in entry:
        lo, hi = entry["range"]
        for value, want in ((lo, True), (hi, True), (lo - 1, False), (hi + 1, False)):
            got = load(rel, with_key(doc, key, value))
            if got.ok != want:
                raise KeyReferenceError(
                    f"{key}: range {lo} to {hi} says {value} is "
                    f"{'accepted' if want else 'refused'}, the builder disagrees"
                    + ("" if got.ok else f" ({got.kind}: {got.message[:80]})"))
        limits.append(f"`{lo}` to `{hi}`")
    if "length" in entry:
        most = int(entry["length"])
        for size, want in ((most, True), (most + 1, False)):
            got = load(rel, with_key(doc, key, "x" * size))
            if got.ok != want:
                raise KeyReferenceError(
                    f"{key}: length {most} says {size} octets are "
                    f"{'accepted' if want else 'refused'}, the builder disagrees")
        limits.append(f"at most `{most}` octets")
    allowed = "; ".join(limits + ([render_text(entry["allowed"], key)]
                                  if entry.get("allowed") else []))
    bad = entry.get("bad", [])
    if not isinstance(bad, list):
        raise KeyReferenceError(f"{key}: bad must be a list of probe values")
    if not bad and "unchecked" not in entry:
        raise KeyReferenceError(f"{key}: needs a bad probe, or unchecked: <why nothing refuses>")
    refused = ""
    for spec in bad:
        got = load(rel, with_key(doc, key, _value(spec)))
        if got.ok:
            raise KeyReferenceError(f"{key}: bad value {spec!r} is accepted by the builder")
        if not refused:
            refused = (f"`{got.function}`: {_short(got.message)}" if got.kind == "ConfigError"
                       else f"no named refusal: `{got.kind}` in `{got.function}`")
    for spec in entry.get("ok", []):
        got = load(rel, with_key(doc, key, _value(spec)))
        if not got.ok:
            raise KeyReferenceError(f"{key}: ok value {spec!r} is refused ({got.message[:80]})")
    if not bad:
        refused = "- (" + render_text(entry["unchecked"], key) + ")"
    if stem != BASE:
        need += f"; probed on `{stem}`"
    return Row(key=key, meaning=render_text(entry["meaning"], key), need=need, default=default,
               allowed=allowed or "-", refused=refused, clause="", rows="")


def unknown_key_table(keys: set[str]) -> list[tuple[str, str]]:
    """[(section, what an unknown key there does)] for every mapping the keys sit in."""
    rel, doc = base_document(BASE)
    sections = {""}
    for key in keys:
        parts = key.split(".")
        for n in range(1, len(parts)):
            sections.add(".".join(parts[:n]))
    out = []
    for section in sorted(sections):
        probe = f"{section}.{PROBE_KEY}" if section else PROBE_KEY
        got = load(rel, with_key(doc, probe, 1))
        if got.ok:
            verdict = "ignored: the key is dropped silently"
        elif got.kind == "ConfigError":
            verdict = f"refused by `{got.function}`"
        else:
            verdict = f"no named refusal: `{got.kind}` in `{got.function}`"
        out.append((f"`{section}`" if section else "top level", verdict))
    return out


def generate(source_text: str | None = None) -> str:
    """The section body between the markers, or KeyReferenceError."""
    with at_root():
        keys = tb._loader_key_paths()
        source = read_source(SOURCE.read_text(encoding="utf-8")
                             if source_text is None else source_text)
        missing = sorted(keys - set(source))
        extra = sorted(set(source) - keys)
        if missing or extra:
            raise KeyReferenceError(
                f"{SOURCE.name} disagrees with the loaders: keys with no entry "
                f"{missing}; entries naming no key the loaders read {extra}")
        key_rows, clauses = contract()
        cache: dict[str, tuple[str, dict, Outcome]] = {}
        rows = []
        for key in sorted(keys):
            row = probe_key(key, source[key], cache)
            numbers = key_rows.get(key, [])
            if not numbers:
                raise KeyReferenceError(f"{key}: no row in {CONTRACT.name} section 3")
            clause = "; ".join(dict.fromkeys(clauses.get(n, "-") for n in numbers))
            rows.append(Row(**{**row.__dict__, "clause": clause.replace("|", "\\|"),
                               "rows": ", ".join(numbers)}))
        unknown = unknown_key_table(keys)
    return render(rows, unknown)


def render(rows: list[Row], unknown: list[tuple[str, str]]) -> str:
    """The generated Markdown: the unknown-key table, then one table per section."""
    out = [
        f"Every key `load_config` reads, {len(rows)} in all, probed against "
        f"`configs/{BASE}.yaml` unless the row says otherwise.",
        "The contract row is the key's row in",
        f"[`docs/ENDSTATION_BUILDER.md` section 3]({CONTRACT_LINK}).",
        "",
        "### Unknown keys",
        "",
        "| Mapping | An undeclared key there is |",
        "|---|---|",
    ]
    out += [f"| {section} | {verdict} |" for section, verdict in unknown]
    groups: dict[str, list[Row]] = {}
    for row in rows:
        groups.setdefault(row.key.split(".")[0], []).append(row)
    for group in sorted(groups):
        out += ["", f"### `{group}`", "",
                "| Key | Meaning | Need | Default | Allowed and limits | Refused by | Clause | Row |",
                "|---|---|---|---|---|---|---|---|"]
        for r in groups[group]:
            out.append(f"| `{r.key}` | {r.meaning} | {r.need} | {r.default} | {r.allowed} "
                       f"| {r.refused} | {r.clause} | {r.rows} |")
    return "\n".join(out) + "\n"


def splice(page: str, body: str) -> str:
    """`page` with the text between the markers replaced by `body`."""
    if page.count(START) != 1 or page.count(END) != 1:
        raise KeyReferenceError(f"{PAGE.name}: needs exactly one start and one end marker")
    head, rest = page.split(START, 1)
    _old, tail = rest.split(END, 1)
    return f"{head}{START}\n{body}{END}{tail}"


def check(page: str, body: str) -> list[str]:
    """The diff between the page and a fresh generation; empty when fresh."""
    fresh = splice(page, body)
    return list(difflib.unified_diff(page.splitlines(), fresh.splitlines(),
                                     "README-parameters.md (tracked)",
                                     "README-parameters.md (generated)", lineterm="", n=0))


def selftest() -> int:
    """Each refusal must bite: a stale page, a key the loaders lack, a key with
    no entry, a bad probe the builder accepts, a wrong default, a digit in
    hand-kept prose and an unknown constant."""
    page = PAGE.read_text(encoding="utf-8")
    source = SOURCE.read_text(encoding="utf-8")
    body = generate(source)
    failures = []
    if check(page, body):
        failures.append("the tracked page is not fresh, so the stale-page arm proves nothing")
    # The stale-page mutant: one need cell inside the generated block flipped.
    cell = page.index("| optional |", page.index(START))
    stale = page[:cell] + "| required |" + page[cell + len("| optional |"):]
    if not check(stale, body):
        failures.append("a planted stale cell was not reported")
    planted = {
        "a key the loaders do not read": source + "\nplanted.key:\n  meaning: Planted.\n  unchecked: planted\n",
        "a key with no entry": re.sub(r"(?m)^schema_version:\n(?:  .*\n)+", "", source, count=1),
        "a bad probe the builder accepts": source.replace(
            "board.constraints.floorplan:\n", "board.constraints.floorplan:\n  bad: [true]\n", 1),
        "a wrong default": re.sub(r"(?m)^(board\.constraints\.uart_baudrate:\n(?:  .*\n)*?  default: )\d+",
                                  r"\g<1>9600", source, count=1),
        "a digit in prose": source.replace("meaning: ", "meaning: 7 ", 1),
        "an unknown constant": source.replace("{BOARDS|keys}", "{NO_SUCH_TABLE|keys}", 1),
    }
    for name, text in planted.items():
        if text == source:
            failures.append(f"{name}: the mutation did not apply to {SOURCE.name}")
            continue
        try:
            generate(text)
        except KeyReferenceError:
            continue
        failures.append(f"{name}: was not refused")
    for failure in failures:
        print(f"selftest: {failure}")
    if failures:
        return 1
    print(f"key reference selftest: OK (stale page and {len(planted)} planted source defects refused)")
    return 0


def main() -> int:
    """Rewrite the section, check it, or prove the checks bite."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="fail when the section is stale")
    mode.add_argument("--selftest", action="store_true", help="prove each refusal bites")
    args = parser.parse_args()
    try:
        if args.selftest:
            return selftest()
        page = PAGE.read_text(encoding="utf-8")
        body = generate()
        if args.check:
            diff = check(page, body)
            if diff:
                print("\n".join(diff[:40]))
                print(f"{PAGE.name}: key reference is stale; run "
                      "python3 sw/builder/gen_key_reference.py")
                return 1
            print(f"{PAGE.name}: key reference is fresh")
            return 0
        PAGE.write_text(splice(page, body), encoding="utf-8")
        print(f"wrote {PAGE.relative_to(ROOT)}")
        return 0
    except KeyReferenceError as exc:
        print(f"REFUSED: {exc}")
        return 2


