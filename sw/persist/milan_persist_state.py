#: Items whose obligation is "do not keep this", separated so no reader has to
#: parse prose to tell an unmet SHALL from a met SHALL-NOT.
MUST_NOT_PERSIST = {"locked", "registered_ctlrs"}


def restorable(item):
    """True when a saved value can actually be put back after a power cycle."""
    return item["restore"] is not None


def open_gaps():
    """Items Milan requires to survive that this build cannot restore."""
    return [i for i in PERSIST_ITEMS
            if i["key"] not in MUST_NOT_PERSIST and not restorable(i)]


def emit_sh():
    """The board-side include: tags, order and per-item restore verdict.

    Deliberately data-only - no logic - so ``milan-persist`` owns the
    behaviour and this file owns the facts.
    """
    res = _flash_reserved()
    jnl = res["journal"]
    lines = [
        "# SPDX-License-Identifier: (GPL-2.0 OR MIT)",
        "# GENERATED by sw/persist/milan_persist_state.py - DO NOT EDIT BY HAND.",
        "# Regenerate, and let `milan_persist_state.py --check` prove the two",
        "# agree.  The Milan clause text this is derived from is quoted in the",
        "# generator; nothing here restates a clause number that is not also",
        "# there.",
        "#",
        "# MILAN_PERSIST_ITEMS   record tags, in image order",
        "# MILAN_PERSIST_RESTORE_<tag>   fabric-journal | csr | none",
        "# MILAN_PERSIST_CLAUSE_<tag>    the clause that demands it",
        "#",
        "# The flash geometry below is READ OUT OF FLASHBOOT_RESERVED in",
        "# sw/litex/milan_soc.py, the single source of truth the mtd partition",
        "# node is also generated from.  A board tool that hardcodes an offset",
        "# instead is how the shipping acmp-persist ended up journalling into",
        "# the `user` slot.",
        "",
        f"MILAN_PERSIST_MAGIC=0x{KLS1_MAGIC:08X}",
        f"MILAN_PERSIST_FMT=0x{(KLS1_FMT_MAJOR << 16) | KLS1_FMT_MINOR:08X}",
        "",
        f"MILAN_JOURNAL_OFF=0x{jnl['offset']:X}",
        f"MILAN_JOURNAL_SIZE=0x{jnl['size']:X}",
        f"MILAN_USER_OFF=0x{res['user']['offset']:X}",
        f"MILAN_USER_SIZE=0x{res['user']['size']:X}",
        "",
        "MILAN_PERSIST_ITEMS=\"" + " ".join(
            i["key"] for i in PERSIST_ITEMS
            if i["key"] not in MUST_NOT_PERSIST) + "\"",
        "MILAN_PERSIST_MUST_NOT=\"" + " ".join(sorted(MUST_NOT_PERSIST)) + "\"",
        "",
    ]
    for i in PERSIST_ITEMS:
        tag = i["key"]
        lines.append(f"MILAN_PERSIST_CLAUSE_{tag}=\"{i['clause']}\"")
        lines.append(f"MILAN_PERSIST_RESTORE_{tag}=\"{i['restore'] or 'none'}\"")
        lines.append(f"MILAN_PERSIST_TITLE_{tag}=\"{i['title']}\"")
        if i["gap"]:
            lines.append(f"MILAN_PERSIST_GAP_{tag}=\"{i['gap']}\"")
        lines.append("")
    return "\n".join(lines)


def emit_md():
    rows = ["| Clause | State | Scope | Restore path | Status |",
            "|---|---|---|---|---|"]
    for i in PERSIST_ITEMS:
        if i["key"] in MUST_NOT_PERSIST:
            status = "**must NOT persist** (satisfied: nothing saves it)"
            path = "n/a"
        elif restorable(i):
            status = "**restorable today**"
            path = i["restore"]
        else:
            status = f"**OPEN** - {i['gap']}"
            path = "none"
        rows.append(f"| {i['clause']} | {i['title']} | {i['scope']} "
                    f"| {path} | {status} |")
    return "\n".join(rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--emit-sh", action="store_true")
    ap.add_argument("--emit-json", action="store_true")
    ap.add_argument("--emit-md", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--gaps", action="store_true")
    a = ap.parse_args()
    if a.emit_json:
        print(json.dumps(PERSIST_ITEMS, indent=2))
        return
    if a.emit_md:
        print(emit_md())
        return
    if a.gaps:
        for i in open_gaps():
            print(f"{i['clause']:10s} {i['title']}\n           GAP: {i['gap']}")
        return
    text = emit_sh()
    if a.check:
        try:
            have = open(SH_OUT, encoding="utf-8").read()
        except OSError:
            sys.exit(f"milan_persist_state: {SH_OUT} is missing - regenerate it")
        if have != text:
            sys.exit("milan_persist_state: milan-persist-state.sh is STALE vs "
                     "PERSIST_ITEMS - regenerate it")
        print("milan_persist_state: OK - milan-persist-state.sh matches "
              "PERSIST_ITEMS")
        return
    with open(SH_OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"milan_persist_state: wrote {SH_OUT}")
    #: and the copy the flashed image actually reads.  Written here rather
    #: than checked in twice by hand for the same reason the entity conf is:
    #: two copies of a generated fact rot independently and agree on day one.
    if os.path.isdir(ROOTFS_OVERLAY_ETC):
        dst = os.path.join(ROOTFS_OVERLAY_ETC, "milan-persist-state.sh")
        with open(dst, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"milan_persist_state: wrote {dst}")
    else:
        print("milan_persist_state: rootfs overlay not on this disk "
              f"({ROOTFS_OVERLAY_ETC}) - board copy SKIPPED")


if __name__ == "__main__":
    main()
