"""Generate the static entity shape from the authoritative builder counts: the streams ADP advertises, which size
the SRP tables and pool, the AEM descriptors that bear AECP's change notices, from which aecp.h derives the
most notices a datapath reset can leave pending (AECP_NOTICES_MOST; #894's ruling issuecomment-6871343905, item
(b)(iv)), and the key domain of an AUDIO_MAP edit, which sizes the map edits' direct index (aecp_maps.c;
aecp_shape.key_domain of the image's own descriptors; #894's ruling issuecomment-6870437042, item 1, with the
shape header its single source, issuecomment-6871343905, item (c))."""
from __future__ import annotations
import argparse
import sys
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parents[1]/"adp"))
sys.path.insert(0,str(Path(__file__).resolve().parents[1]/"aecp"))
import adp_entity
import aecp_shape
import endstation_builder

#: The AEM descriptors a change notice is kept for (aecp.c, aecp_changed), each the shape header's name.
NOTICE_DESCRIPTORS = {"STREAM_INPUT": "CTRL_AEM_STREAM_INPUTS", "STREAM_OUTPUT": "CTRL_AEM_STREAM_OUTPUTS",
                      "AVB_INTERFACE": "CTRL_AEM_AVB_INTERFACES", "CLOCK_DOMAIN": "CTRL_AEM_CLOCK_DOMAINS"}


def emit(config: Path) -> str:
    """The same stream counts advertised by ADP size the SRP tables and pool; the AEM model's own descriptor counts
    (the builder's overlay, the image's descriptors) state those that bear notices; and the image's descriptors, as
    aecp_entity.py renders them, the map edits' key domain."""
    fields=adp_entity.entity_fields(config)
    cfg=endstation_builder.load_config(str(config))
    overlay=endstation_builder.emit_aem_overlay(cfg)
    counts=overlay["descriptor_counts"]
    blob=endstation_builder._entity_model_image(cfg,overlay)["aem_desc.bin"]
    return "\n".join([
        "// SPDX-License-Identifier: CERN-OHL-W-2.0",
        "// Generated by srp_entity.py; do not edit.",
        "#ifndef CTRL_SRP_ENTITY_H",
        "#define CTRL_SRP_ENTITY_H",
        f"#define CTRL_SRP_SOURCES {fields['talker_stream_sources']}u",
        f"#define CTRL_SRP_SINKS {fields['listener_stream_sinks']}u",
        *(f"#define {name} {int(counts.get(kind, 0))}u" for kind, name in NOTICE_DESCRIPTORS.items()),
        *aecp_shape.key_domain(blob),
        "#endif", "",
    ])


def main() -> int:
    """Generate a shape header, or report a refused input."""
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("config",type=Path)
    parser.add_argument("-o","--output",type=Path,required=True)
    args=parser.parse_args()
    try:
        args.output.write_text(emit(args.config),encoding="utf-8")
    except (OSError,ValueError,KeyError) as error:
        print(f"srp_entity: {error}",file=sys.stderr)
        return 2
    return 0

if __name__=="__main__":
    raise SystemExit(main())
