"""ship8_params.py SOC_PARAMS --overlay JSON --header HPP: the 8x8 shipping leg's -G flags (#584).

The builder emits soc_params.json for a config: the milan_soc.py argv that config's SoC is built from. This reads
that argv and prints the milan_datapath parameters it sets on the render path, by the same rules milan_soc.py
add_milan_datapath() applies, so sim_ship8_render elaborates the lane the product builds and not a restatement of
it. It also writes HPP: the leg's stated geometry, which sim_ship8_render.cpp static_asserts against its own, so a
config that moved the geometry fails the compile by name, and the listener format the builder's entity overlay
declares for every STREAM_INPUT, which the leg provisions the way the firmware does. An argv it cannot map, or
stream inputs that disagree on their format, is refused, never guessed.
"""
import argparse
import json
import sys
from pathlib import Path

#: milan_soc.py's --audio-interface choices with a TDM bus, and their slot counts
TDM_SLOTS = {"tdm8": 8, "tdm16": 16, "tdm32": 32}
#: the SV defaults AUDIO_IF_CLK_HZ_P is derived from when no fs or word-width flag is given
FS_HZ, WORD_BITS = 48000, 32
#: the argv flags this leg reads; any other flag naming the audio interface or the render path is refused
READ = ("--num-streams", "--audio-interface", "--audio-interface-master", "--audio-interface-render",
        "--talker-wire-chans", "--loopback-lane", "--no-i2s-playback", "--no-render-lpf")
REFUSED_PREFIXES = ("--audio-", "--render-", "--i2s")


def option(argv: list[str], name: str) -> str | None:
    """The value after `name`, or None when absent; a repeated option is refused."""
    hits = [i for i, a in enumerate(argv) if a == name]
    if len(hits) > 1:
        raise SystemExit(f"ship8_params: {name} is given twice")
    if not hits:
        return None
    if hits[0] + 1 >= len(argv):
        raise SystemExit(f"ship8_params: {name} has no value")
    return argv[hits[0] + 1]


def derive(argv: list[str]) -> dict[str, int]:
    """The render-path parameters milan_soc.py passes milan_datapath for this argv."""
    unknown = [a for a in argv if a.startswith(REFUSED_PREFIXES) and a not in READ]
    if unknown:
        raise SystemExit(f"ship8_params: unmapped render-path flags {unknown}")
    interface = option(argv, "--audio-interface")
    if interface not in TDM_SLOTS:
        raise SystemExit(f"ship8_params: --audio-interface {interface} is not a TDM bus")
    if "--audio-interface-master" not in argv:
        raise SystemExit("ship8_params: the leg decodes a MASTER bus; the argv names no --audio-interface-master")
    render = int(option(argv, "--audio-interface-render") or 0)
    if render <= 0:
        raise SystemExit("ship8_params: --audio-interface-render is 0: the build has no render lane to decode")
    slots = TDM_SLOTS[interface]
    return {
        "N_STREAMS": int(option(argv, "--num-streams") or 1),
        "TALKER_WIRE_CHANS_P": int(option(argv, "--talker-wire-chans") or 2),
        "AUDIO_IF_SLOTS_P": slots,
        "AUDIO_IF_MASTER_P": 1,
        "AUDIO_IF_CLK_HZ_P": 2 * slots * WORD_BITS * FS_HZ,
        "AUDIO_IF_RENDER_SLOTS_P": render,
        "LOOPBACK_P": int("--loopback-lane" in argv),
        "I2SPB_P": int("--no-i2s-playback" not in argv),
        "LPF_P": int("--no-render-lpf" not in argv),
    }


def listener_format(overlay: dict) -> int:
    """The one current format every AAF STREAM_INPUT of the entity declares first (the CRF input is not a listener)."""
    formats = {int(str(s["formats"][0]), 16) for s in overlay["stream_inputs"] if s["kind"] == "aaf"}
    if len(formats) != 1:
        raise SystemExit(f"ship8_params: the stream inputs declare {len(formats)} different formats")
    return formats.pop()


def header(params: dict[str, int], fmt: int) -> str:
    """The leg's geometry and listener format as constexpr values; the bench asserts against them."""
    rows = [("kCfgStreams", "N_STREAMS"), ("kCfgWireChans", "TALKER_WIRE_CHANS_P"),
            ("kCfgBusSlots", "AUDIO_IF_SLOTS_P"), ("kCfgRenderSlots", "AUDIO_IF_RENDER_SLOTS_P"),
            ("kCfgLoopback", "LOOPBACK_P"), ("kCfgDacLane", "I2SPB_P")]
    lines = ["// generated by ship8_params.py from the builder's soc_params.json and entity overlay; do not edit",
             "#pragma once", "#include <cstdint>"]
    lines += [f"constexpr int {name} = {params[key]};" for name, key in rows]
    lines.append(f"constexpr uint64_t kCfgListenerFormat = 0x{fmt:016X}ull;")
    return "\n".join(lines) + "\n"


def main() -> int:
    """Print the -G flags for SOC_PARAMS and write the geometry header."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("soc_params", type=Path)
    parser.add_argument("--overlay", type=Path, required=True)
    parser.add_argument("--header", type=Path, required=True)
    args = parser.parse_args()
    argv = json.loads(args.soc_params.read_text())["argv"]
    params = derive(argv)
    args.header.write_text(header(params, listener_format(json.loads(args.overlay.read_text()))))
    print(" ".join(f"-G{key}={value}" for key, value in params.items()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
