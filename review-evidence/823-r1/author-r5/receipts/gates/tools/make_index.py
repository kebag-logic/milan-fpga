#!/usr/bin/env python3
"""Write receipts/INDEX.md from the files present under receipts/: path, bytes and sha256 of each, sorted."""
import hashlib, sys
from pathlib import Path
root = Path(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).resolve().parents[2])
rows = []
for p in sorted(x for x in root.rglob("*") if x.is_file() and x.name != "INDEX.md"):
    rows.append(f"| `{p.relative_to(root)}` | {p.stat().st_size:,} | `{hashlib.sha256(p.read_bytes()).hexdigest()[:16]}` |")
(root / "INDEX.md").write_text("# Receipts index\n\nGenerated by `gates/tools/make_index.py` from the files present.\n\n"
                               "| File | Bytes | sha256 (first 16) |\n|---|---:|---|\n" + "\n".join(rows) + "\n")
print(f"{len(rows)} files")
