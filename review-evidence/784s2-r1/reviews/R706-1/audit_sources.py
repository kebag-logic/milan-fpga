#!/usr/bin/env python3
"""Independent workflow comparison and regeneration, without executing the runner."""
import ast
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

root = Path(sys.argv[1]).resolve()
packet = Path(__file__).resolve().parent
base = 'a8594bb95631fa5c49d18fa0bbc9530e31ad59aa'
head = '847eb4dd031eb3891b61773f4a8324cb2ed6cdc0'
env = dict(os.environ, GIT_NO_REPLACE_OBJECTS='1', PYTHONDONTWRITEBYTECODE='1', TMPDIR=str(packet/'scratch'))
def git(*args):
    return subprocess.check_output(['git', *args], cwd=root, env=env)
assert git('rev-parse', 'HEAD').decode().strip() == head
names = git('diff', '--name-only', base, head).decode().splitlines()
assert len(names) == 20
assert not any(n.startswith('hdl/') or n.endswith(('.sv','.v','.xdc')) for n in names)
counts = {}
for path in sorted((root/'.github/workflows').glob('*.yml')):
    rel = path.relative_to(root).as_posix()
    before = git('show', base+':'+rel)
    after = path.read_bytes()
    assert before.replace(b'runs-on: ubuntu-latest', b'runs-on: ubuntu-24.04') == after, rel
    counts[rel] = after.count(b'runs-on: ubuntu-24.04')
    print('PASS exact byte substitution only:', rel, counts[rel], 'jobs')
assert sum(counts.values()) == 46
for folder in ('.github/workflows', '.github/ci-templates'):
    for path in (root/folder).glob('*'):
        if path.is_file():
            assert b'ubuntu-latest' not in path.read_bytes(), path
for name in ('ci_gate_workflows.py','ci_runtime_workflows.py','ci_suite_workflows.py','ci_install_workflows.py','yosys_shards.py'):
    assert 'ubuntu-latest' not in (root/'scripts'/name).read_text(), name
    print('PASS generator/template floating-label absence:', name)
source = (root/'scripts/act_ci.py').read_text()
tree = ast.parse(source)
labels = [n for n in tree.body if isinstance(n, ast.Assign) and any(isinstance(t,ast.Name) and t.id=='RUNS_ON_LABELS' for t in n.targets)]
assert len(labels)==1 and ast.literal_eval(labels[0].value)==('ubuntu-24.04',)
print('PASS runner accepted labels AST literal:', ast.literal_eval(labels[0].value))
print('Runner executable tests deliberately not invoked by this audit.')
regen = packet/'scratch/regenerated'
regen.mkdir(exist_ok=True)
shutil.copytree(root/'.github',regen/'.github',dirs_exist_ok=True)
command = ['python3','scripts/ci_gate_workflows.py','--root',str(regen)]
subprocess.run(command,cwd=root,env=env,check=True)
subprocess.run(command+['--check'],cwd=root,env=env,check=True)
for name in counts:
    assert (regen/name).read_bytes()==(root/name).read_bytes(), name
    print('PASS regenerated bytes:',name,hashlib.sha256((root/name).read_bytes()).hexdigest())
victim = regen/'.github/workflows/docs.yml'
victim.write_text(victim.read_text().replace('runs-on: ubuntu-24.04','runs-on: ubuntu-latest',1))
rc = subprocess.run(command+['--check'],cwd=root,env=env,check=False).returncode
assert rc==1
print('PASS own generated-workflow drift mutation killed, rc=1')
manifest = json.loads((packet/'public-evidence-manifest.json').read_text())
expected = {row['file']:row['published_sha256'] for row in manifest}
for path in sorted((packet/'public-author').rglob('*')):
    if path.is_file():
        rel='author/'+path.relative_to(packet/'public-author').as_posix()
        digest=hashlib.sha256(path.read_bytes()).hexdigest()
        assert digest==expected[rel], rel
        print('PASS public receipt SHA256:',rel,digest)
print('PASS source audit')
