#!/usr/bin/env python3
"""Write receipts/INDEX.md from the files actually present: path, size, sha256, what it is."""

import hashlib
import pathlib
import sys

ROLES = {
    "taken-comment.md": "the TAKEN comment as posted on #784",
    "review-ready-comment.md": "the REVIEW READY comment as posted on #784",
    "census.md": "every runs-on writer, the generated label counts, every ubuntu-latest left in the tree",
    "hosted-image-evidence.md": "Image: lines (and the #784 pip failure) from three hosted job logs, with log sha256",
    "imageos-readers.md": "ImageOS in setup-python@v5 and the pinned act source; act's built-in platform table",
    "INDEX.md": "this index",
}
DIRS = {
    "gates": "head gates under the pinned renderer venv (CPython 3.14.8, PyYAML 6.0.3): <gate>.log, <gate>.rc, table.md",
    "gates-py312": "head gates on the hosted pair (CPython 3.12.3, PyYAML 6.0.2): <gate>.log, <gate>.rc, table.md",
    "bootstrap": "dev's trusted act_ci.py (blob 904d4fda) over the head's workflows, offline",
    "mutants": "planted mutants and demonstrations: <name>.json (edit, rc, failing checks) and <name>.log",
    "scripts": "the drivers that produced these receipts",
}


def main() -> int:
    root = pathlib.Path(sys.argv[1])
    rows = []
    for path in sorted(p for p in root.rglob("*") if p.is_file() and p.name != "INDEX.md"):
        rel = path.relative_to(root).as_posix()
        data = path.read_bytes()
        role = ROLES.get(rel) or DIRS.get(rel.split("/", 1)[0], "")
        rows.append(f"| `{rel}` | {len(data)} | `{hashlib.sha256(data).hexdigest()[:16]}` | {role} |")
    text = ["# Receipts index", "",
            "Generated by `scripts/index.py` from the files present; sha256 shown to 16 hex digits.", "",
            "| File | Bytes | sha256 | What |", "|---|---:|---|---|", *rows, ""]
    (root / "INDEX.md").write_text("\n".join(text), encoding="utf-8")
    print(f"{len(rows)} files indexed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
