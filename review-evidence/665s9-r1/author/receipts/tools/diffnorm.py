import difflib, re, sys
from pathlib import Path
TIME = re.compile(rb"(Auto-generated by LiteX \([0-9a-f]+\) on |// Date       : |^)\d{4}-\d\d-\d\d \d\d:\d\d:\d\d", re.M)
TREE_LINE = re.compile(rb"^.*[\xe2][\x94\x95][\x80-\xbf].*\n", re.M)
def norm(data, tree, out):
    data = data.replace(str(out).encode(), b"@OUT@").replace(str(tree).encode(), b"@TREE@")
    return TREE_LINE.sub(b"", TIME.sub(rb"\1@TIME@", data))
bt, bo, ht, ho, f = sys.argv[1:6]
x = norm(Path(bo, f).read_bytes(), bt, bo).decode(errors="replace").splitlines()
y = norm(Path(ho, f).read_bytes(), ht, ho).decode(errors="replace").splitlines()
d = list(difflib.unified_diff(x, y, lineterm="", n=0))
print(f, len(d)); print("\n".join(d[:24]))
