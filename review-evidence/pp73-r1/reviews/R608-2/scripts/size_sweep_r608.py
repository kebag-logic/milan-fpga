#!/usr/bin/env python3
"""Reviewer re-check (R608-2) of the size claims at the exact head.

For every served command: response cdl +4, then command cdl +4 (an echo row
moves both, so the echo rule alone cannot be what fails), each with F06.14
regenerated by the gate's --write; GET_AUDIO_MAP response cdl 20, 24, 28;
STREAM_IS_RUNNING 12 -> 13; a documented row without a name. Records the
gate's rc and first finding per variant.

usage: python3 -I size_sweep_r608.py --src DIR --out FILE [--jobs N]
"""
import argparse
import json
import shutil
import subprocess
import sys
import tempfile
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

TABLE = "hdl/aecp/ucode/aecp_commands.json"


def variant(args):
    src, label, fn = args
    with tempfile.TemporaryDirectory(prefix="r608-2-size-") as tmp:
        root = Path(tmp)
        for d in ("hdl", "scripts", "tb/aecp_cmds", "docs"):
            shutil.copytree(src / d, root / d, ignore=shutil.ignore_patterns(
                "obj_dir", "*.hex", "image.bin", "__pycache__"))
        p = root / TABLE
        t = json.loads(p.read_text(encoding="utf-8"))
        fn(t)
        p.write_text(json.dumps(t, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        gate = [sys.executable, "-B", str(root / "scripts/check_aecp_commands.py")]
        w = subprocess.run(gate + ["--write"], capture_output=True, text=True)
        r = subprocess.run(gate, capture_output=True, text=True)
    lines = [x.strip() for x in (r.stdout + r.stderr).splitlines() if x.strip()]
    first = next((x for x in lines if not x.startswith("AECP COMMAND GATE")), "")
    return label, w.returncode, r.returncode, first


def by(t, name):
    return next(c for c in t["commands"] if c["name"] == name)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--jobs", type=int, default=14)
    a = ap.parse_args()
    src = a.src.resolve()
    names = [c["name"] for c in json.loads((src / TABLE).read_text(encoding="utf-8"))["commands"]]
    todo = []
    for n in names:
        def rsp(t, n=n):
            c = by(t, n)
            c["response"]["cdl"] += 4
            if c["response"].get("echo"):
                c["command"]["cdl"] += 4
                if "floor" in c["command"] and c["command"]["floor"] >= c["command"]["cdl"]:
                    c["command"].pop("floor")

        def cmd(t, n=n):
            c = by(t, n)
            c["command"]["cdl"] += 4
            if c["response"].get("echo"):
                c["response"]["cdl"] += 4

        todo.append((src, f"response+4 {n}", rsp))
        todo.append((src, f"command+4 {n}", cmd))
    for v in (20, 24, 28):
        todo.append((src, f"GET_AUDIO_MAP response cdl {v}",
                     lambda t, v=v: by(t, "GET_AUDIO_MAP")["response"].__setitem__("cdl", v)))
    todo.append((src, "STREAM_IS_RUNNING 12->13",
                  lambda t: t["status_codes"]["STREAM_IS_RUNNING"].__setitem__("code", 13)))
    todo.append((src, "documented row without name", lambda t: t["documented"][0].pop("name")))
    with ThreadPoolExecutor(a.jobs) as ex:
        res = list(ex.map(variant, todo))
    out = [f"{label}: --write rc {w}, gate rc {g}: {first[:200]}" for label, w, g, first in res]
    held = {k: sum(1 for label, _, g, _ in res if label.startswith(k) and g != 0) for k in ("response+4", "command+4")}
    out.append(f"response+4: {held['response+4']} of {len(names)} fail the gate; "
               f"command+4: {held['command+4']} of {len(names)} fail the gate")
    a.out.write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out[-8:]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
