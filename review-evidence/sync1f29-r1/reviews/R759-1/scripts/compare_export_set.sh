#!/bin/bash
# usage: compare_export_set.sh <root-a> <root-b>: the five configs' generated Verilog, then every other file with the run-stamp and log rules.
a=$1; b=$2
for c in ax7101_1x1_tdm8 ax7101_8x8 arty_4x4 arty_8ch arty_current; do
  t=alinx_ax7101; case $c in arty*) t=digilent_arty;; esac
  echo "== $c"; python3 "$(dirname "$0")/verilog_body_compare.py" "$a/$c/gateware/$t.v" "$b/$c/gateware/$t.v"; echo "verilog rc $?"
  (cd "$a/$c" && find . -type f ! -name "$t.v" ! -name litex.log | sort | xargs sha256sum) > /tmp/.r759a.$$
  (cd "$b/$c" && find . -type f ! -name "$t.v" ! -name litex.log | sort | xargs sha256sum) > /tmp/.r759b.$$
  diff /tmp/.r759a.$$ /tmp/.r759b.$$ | grep '^>' | awk '{print $3}' | while read f; do
    if diff <(grep -vE 'Auto-generated by LiteX|on 20[0-9-]+ [0-9:]+|LITEX_GIT|MIGEN_GIT' "$a/$c/$f") <(grep -vE 'Auto-generated by LiteX|on 20[0-9-]+ [0-9:]+|LITEX_GIT|MIGEN_GIT' "$b/$c/$f") >/dev/null 2>&1; then echo " stamp-only $f"; else echo " DIFFERS $f"; diff "$a/$c/$f" "$b/$c/$f" | head -8 | cut -c1-180; fi
  done
  diff <(sed -E 's/\(20[0-9-]+ [0-9:]+\)//; s/ on 20[0-9-]+ [0-9:]+//; s/[0-9]+\.[0-9]+s//' "$a/$c/litex.log" | sort) <(sed -E 's/\(20[0-9-]+ [0-9:]+\)//; s/ on 20[0-9-]+ [0-9:]+//; s/[0-9]+\.[0-9]+s//' "$b/$c/litex.log" | sort) | grep -c '^[<>]' | sed 's/^/ litex.log sorted differing lines: /'
done
rm -f /tmp/.r759a.$$ /tmp/.r759b.$$
