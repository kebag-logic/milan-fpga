#!/usr/bin/env python3
"""Compare two generated Verilog files as MAILBOX_SPLIT.md "Default build" does: every line outside the date lines and LiteX's comment-only hierarchy tree byte for byte, that tree as a multiset, and print any line that differs. usage: <a.v> <b.v>"""
import difflib, re, sys
from collections import Counter
TREE = re.compile(r"^\s*(?:[│├└─ ]|\* *$)")
def split(p):
    tree, body, dates, inc = [], [], [], False
    for l in open(p, errors="surrogateescape"):
        if re.search(r"Date  |Auto-Generated by LiteX", l): dates.append(l); continue
        if l.startswith("/*"): inc = True
        if inc:
            tree.append(l)
            if "*/" in l: inc = False
            continue
        body.append(l)
    return tree, body, dates
a, b = (split(p) for p in sys.argv[1:3])
d = sum((Counter(a[0]) - Counter(b[0])).values()) + sum((Counter(b[0]) - Counter(a[0])).values())
print(f"body {'EQUAL' if a[1]==b[1] else 'DIFFER'} ({len(a[1])}/{len(b[1])} lines); hierarchy tree {len(a[0])}/{len(b[0])} lines, multiset difference {d}; date lines {len(a[2])}/{len(b[2])}")
if a[1] != b[1]:
    for i, l in enumerate(difflib.unified_diff(a[1], b[1], lineterm="", n=0)):
        if i > 40: break
        print(l.rstrip()[:200])
sys.exit(a[1] != b[1] or d != 0)
