#!/usr/bin/env python3
"""Write receipts/INDEX.md from the files present: one row per file with its size and sha256.
usage: make_index.py RECEIPTS_DIR"""
import hashlib
import sys
from pathlib import Path

root = Path(sys.argv[1])
rows = ['# Receipts index', '', 'Generated by `scripts/make_index.py` from the files present.', '',
        '| File | Bytes | sha256 |', '|---|---:|---|']
for p in sorted(q for q in root.rglob('*') if q.is_file() and q.name != 'INDEX.md'):
    data = p.read_bytes()
    rows.append(f'| `{p.relative_to(root)}` | {len(data):,} | `{hashlib.sha256(data).hexdigest()}` |')
rows += ['', f'{len(rows) - 6} files.']
(root / 'INDEX.md').write_text('\n'.join(rows) + '\n')
print(rows[-1])
