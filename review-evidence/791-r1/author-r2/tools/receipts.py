#!/usr/bin/env python3
"""receipts.py [index]: copy each cited log into receipts/ with host paths replaced, then write receipts/INDEX.md.

A log over 200 KB is not copied: its sha256 and size are recorded in receipts/LARGE.txt, with its first and last
lines copied as <name>.head-tail.txt. `index` only rewrites INDEX.md from the files present.
"""
