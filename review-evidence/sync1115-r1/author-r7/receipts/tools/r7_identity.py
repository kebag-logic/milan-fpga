#!/usr/bin/env python3
"""r7_identity.py OUT.json: each round-7 measurement build against round 4's build of the same leg, file by file
(image/, gateware/, runtime/, split-soc/: the firmware, the generated SoC, its ROM files, the runtime and the flash
map), with budget_config.hpp and native/Vsim. Round 7 changes the simulation's testbench alone (sim_main.cpp,
observers.py's hooks), so every other file must be identical, or differ only in what a rebuild stamps: the build and
clone paths, LiteX's generation date and generated comments (its hierarchy tree's order), the order LiteX emits the
same constraint lines in, an archive's member timestamps (its members' contents identical), and the digests a file
records of such a stamped file; a builder's own run log is listed and not compared. Each differing file is
checked against exactly that, and any other difference is listed unexplained."""
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

S = Path('<scratch>')
SEEDS = ('10092', '10592', '11102', '11602', '12102', '12602', '13102', '13602', '14602', '15032')
PAIRS = {**{f's{t}': (S / f'seeds/b7-sync-{t}', S / f'seeds/b4-sync-{t}', S / f'seeds/c-sync-{t}', None)
            for t in SEEDS},
         'p81': (S / 'r7/b81', S / 'r4/b81', S / 'r7/c-head', S / 'r4/c-head'),
         'v1': (S / 'r7/b1x1-V', S / 'r4/b1x1-V', S / 'r7/c-head', S / 'r4/c-head'),
         'v81': (S / 'r7/b81-V', S / 'r4/b81-V', S / 'r7/c-head', S / 'r4/c-head')}
DATE = re.compile(r'(Auto-generated by LiteX \([0-9a-f]+\) on |Auto-Generated by LiteX on |// Date       : )\S+ \S+',
                  re.I)
HEX = re.compile(r'"[0-9a-f]{64}"')
SUBS = ('image', 'gateware', 'runtime', 'split-soc')


def digest(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def text(p: Path, roots: list[Path]) -> str:
    t = p.read_text(errors='replace')
    for r in roots:
        t = t.replace(str(r), '<root>')
    return DATE.sub(r'\1<date>', t)


def code(t: str) -> list[str]:
    """Verilog without its comments, block and line."""
    t = re.sub(r'/\*.*?\*/', '', t, flags=re.S)
    return [line for line in t.splitlines() if not line.lstrip().startswith('//')]


def constraints(t: str) -> list[str]:
    """Constraint lines as a set: an asynchronous clock-group constraint's groups in either order are one constraint."""
    out = []
    for line in t.splitlines():
        if line.startswith('set_clock_groups ') and line.endswith(' -asynchronous'):
            groups = sorted(re.findall(r'-group (\[get_clocks -of \[get_nets \w+\]\])', line))
            line = 'set_clock_groups ' + ' '.join(f'-group {g}' for g in groups) + ' -asynchronous'
        out.append(line)
    return sorted(out)


def members(p: Path) -> str:
    return hashlib.sha256(subprocess.run(['ar', 'p', str(p)], capture_output=True, check=True).stdout).hexdigest()


def explain(rel: str, a: Path, b: Path, roots: list[Path]) -> str | None:
    """Why the two copies of rel differ, or None where the difference is not a rebuild's stamp."""
    if rel.endswith('.log'):
        return "a builder's own run log, its times: not compared"
    if rel.endswith('.a'):
        return 'archive member timestamps; members identical' if members(a) == members(b) else None
    try:
        ta, tb = text(a, roots), text(b, roots)
    except UnicodeDecodeError:
        return None
    if ta == tb:
        return 'build paths and LiteX generation date'
    if rel.endswith('.v') and code(ta) == code(tb):
        return "LiteX's generated comments (date, the hierarchy tree's order); the Verilog identical"
    if rel.endswith(('.xdc', '.tcl')) and constraints(ta) == constraints(tb):
        return "the order LiteX emits the same constraints in (an asynchronous clock group's two groups either way)"
    if rel.endswith('.json') and HEX.sub('"<sha256>"', ta) == HEX.sub('"<sha256>"', tb):
        return 'the digests it records of stamped files'
    return None


out = {}
for leg, (new, old, clone, old_clone) in PAIRS.items():
    roots = [new, old, clone] + ([old_clone] if old_clone else [])
    e = dict(identical=0, explained={}, unexplained=[])
    for sub in SUBS:
        for p in sorted((old / sub).rglob('*')):
            if not p.is_file():
                continue
            rel = str(p.relative_to(old))
            q = new / rel
            if not q.is_file():
                e['unexplained'].append(f'{rel}: absent from the new build')
            elif digest(p) == digest(q):
                e['identical'] += 1
            else:
                why = explain(rel, p, q, roots)
                (e['explained'].__setitem__(rel, why) if why else e['unexplained'].append(rel))
    e['ctrl_app_elf'] = dict(sha256=digest(new / 'image/ctrl_app.elf'),
                             identical=digest(new / 'image/ctrl_app.elf') == digest(old / 'image/ctrl_app.elf'))
    for f in ('budget_config.hpp', 'native/Vsim'):
        e[f] = 'identical' if digest(new / f) == digest(old / f) else 'differs (the testbench)'
    out[leg] = e
    print(leg, 'identical', e['identical'], 'explained', len(e['explained']), 'unexplained', e['unexplained'],
          'elf', e['ctrl_app_elf']['identical'], flush=True)
Path(sys.argv[1]).write_text(json.dumps(out, indent=1) + '\n')
