"""index.py <receipts-dir>: write INDEX.md listing every file present, with size and sha256."""
import hashlib, os, sys
root = sys.argv[1]
rows = []
for d, _, fs in os.walk(root):
    for f in fs:
        p = os.path.join(d, f)
        rel = os.path.relpath(p, root)
        if rel == "INDEX.md":
            continue
        h = hashlib.sha256(open(p, "rb").read()).hexdigest()
        rows.append((rel, os.path.getsize(p), h))
rows.sort()
with open(os.path.join(root, "INDEX.md"), "w") as o:
    o.write("# Receipts index (generated by tools/index.py from the files present)\n\n")
    o.write("| File | Bytes | sha256 |\n|---|---|---|\n")
    for rel, n, h in rows:
        o.write(f"| `{rel}` | {n} | `{h}` |\n")
print(len(rows), "files")
