#!/usr/bin/env python3
"""export_cmp.py A B: two LiteX export trees compared file by file, byte for byte, after dropping only the lines
that carry the generation time (LiteX's "Auto-generated ... on <date> <time>" and "// Date :" headers, litex.log's start
time, command and working-directory lines). Prints each file that differs, with the differing lines."""
import difflib, re, sys
from pathlib import Path
a, b = Path(sys.argv[1]), Path(sys.argv[2])
stamp = re.compile(r'(Auto-generated by LiteX \([0-9a-f]+\) on \d{4}-\d\d-\d\d \d\d:\d\d:\d\d|'
                   r'Auto-Generated by LiteX on \d{4}-\d\d-\d\d \d\d:\d\d:\d\d|^// Date\s+: \d{4}-|'
                   r'^# Started: \d{4}-|Creating SoC\.\.\. \(\d{4}-|'
                   r'^# (Command|Working directory): |^#define (GIT|MIGEN_GIT|LITEX_GIT)_)')
fa = sorted(p.relative_to(a) for p in a.rglob('*') if p.is_file())
fb = sorted(p.relative_to(b) for p in b.rglob('*') if p.is_file())
only = sorted(set(fa) ^ set(fb))
for p in only:
    print(f'ONLY IN ONE: {p}')
same = differ = 0
for p in sorted(set(fa) & set(fb)):
    x, y = (a / p).read_bytes(), (b / p).read_bytes()
    if x == y:
        same += 1
        continue
    lx = [l for l in x.decode(errors='replace').splitlines() if not stamp.search(l)]
    ly = [l for l in y.decode(errors='replace').splitlines() if not stamp.search(l)]
    if lx == ly:
        print(f'TIMESTAMP ONLY: {p}')
        same += 1
        continue
    # the hierarchy comment's lines, each without its box-drawing branch glyphs: LiteX orders a module's black
    # boxes from a set, so the same tree prints in another order (and another leaf takes the last-branch glyph)
    tree = lambda ls: [re.sub('[\u2500-\u257f ]', '', l) for l in ls if any(c in l for c in '\u2502\u251c\u2514')]
    rest = lambda ls: [l for l in ls if not any(c in l for c in '\u2502\u251c\u2514')]
    if rest(lx) == rest(ly) and sorted(tree(lx)) == sorted(tree(ly)):
        print(f'TIMESTAMP AND HIERARCHY-COMMENT ORDER ONLY: {p} (the same {len(tree(lx))} tree lines, another order)')
        same += 1
        continue
    if p.name == 'litex.log' and sorted(rest(lx) + tree(lx)) == sorted(rest(ly) + tree(ly)):
        print(f'LOG LINE ORDER ONLY: {p} (the same lines, interleaved differently)')
        same += 1
        continue
    differ += 1
    d = [l for l in difflib.unified_diff(lx, ly, lineterm='', n=0) if l[:1] in '+-' and l[:3] not in ('+++', '---')]
    print(f'DIFFERS: {p} ({len(d)} lines)')
    for l in d[:12]:
        print('   ', l[:200])
print(f'files {len(set(fa) | set(fb))}: identical as above {same}, differing {differ}, in one only {len(only)}')
