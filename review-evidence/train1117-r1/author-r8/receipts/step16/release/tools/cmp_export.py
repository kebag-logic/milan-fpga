#!/usr/bin/env python3
"""cmp_export.py A_DIR A_ROOTS B_DIR B_ROOTS: two gateware exports compared file for file, each file's text with its own
export's absolute roots (comma-separated: its repo and its output directory) replaced by placeholders first. Prints
the counts, every file that differs or is only on one side, and, for each Verilog file that differs, whether it is
equal outside its comments."""
import re
import sys
from pathlib import Path


def norm(path: Path, roots: list[str]) -> bytes:
    data = path.read_bytes()
    # roots: the export's repo, then its output directory; the longer is replaced first so neither eats the other
    for name, r in sorted(zip(('<REPO>', '<WORK>'), roots), key=lambda x: -len(x[1])):
        data = data.replace(r.encode(), name.encode())
    # LiteX's generation stamp in its generated headers (`# Auto-generated by LiteX (<rev>) on <date>`)
    return re.sub(rb'(Auto-generated by LiteX \([0-9a-f]+\)) on [0-9: -]+', rb'\1', data)


def strip_comments(text: str) -> str:
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    return '\n'.join(line.split('//', 1)[0].rstrip() for line in text.splitlines() if line.split('//', 1)[0].strip())


a, ar, b, br = Path(sys.argv[1]), sys.argv[2].split(','), Path(sys.argv[3]), sys.argv[4].split(',')
fa = {p.relative_to(a) for p in a.rglob('*') if p.is_file()}
fb = {p.relative_to(b) for p in b.rglob('*') if p.is_file()}
both = sorted(fa & fb)
differ = [f for f in both if norm(a / f, ar) != norm(b / f, br)]
print(f'files: A {len(fa)} B {len(fb)} only A {len(fa - fb)} only B {len(fb - fa)}')
print(f'equal after normalisation: {len(both) - len(differ)} differ: {len(differ)}')
gate = [f for f in differ if f.parts[0] == 'gateware']
for f in differ:
    if f.parts[0] == 'software':
        continue
    note = ''
    if f.suffix in ('.v', '.sv'):
        same = strip_comments(norm(a / f, ar).decode(errors='replace')) == strip_comments(norm(b / f, br).decode(errors='replace'))
        note = ' (equal outside its comments)' if same else ' (differs outside its comments)'
    print(f'  differs: {f}{note}')
print(f'software/ files differing: {sum(1 for f in differ if f.parts[0] == "software")}')
print(f'gateware/ files differing: {len(gate)}')
for f in sorted(fa - fb)[:10]:
    print(f'  only A: {f}')
for f in sorted(fb - fa)[:10]:
    print(f'  only B: {f}')
