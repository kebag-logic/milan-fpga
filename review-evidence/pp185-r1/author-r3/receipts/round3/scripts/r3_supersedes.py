"""usage: r3_supersedes.py <receipts-dir>
Write receipts/round3/SUPERSEDES.md: each kept failure-set comparison (round 1c, round 2)
beside the round-3 comparison that supersedes it, with the old closing line and the
corrected mutant and baseline populations read from the round-3 JSON summaries."""
import json
import sys
from pathlib import Path

PAIRS = [(f"round2/compare/failsets-{c}-base-vs-head.txt", f"round3/compare/round2/{c}-base-vs-head")
         for c in ("notify", "aecp_dispatch", "d3", "acmp", "name_state")]
PAIRS += [(None, "round3/compare/round2/notify-base-vs-head-final2"),
          (None, "round3/compare/round2/notify-head-vs-head-final2")]
PAIRS += [(f"r1c/compare/failsets-{c}-base-vs-head.txt", f"round3/compare/r1c/{c}-base-vs-head")
          for c in ("notify", "aecp_dispatch", "d3", "acmp", "name_state")]
PAIRS += [(f"r1c/compare/failsets-{c}-r1b-head-vs-r1c-head.txt",
           f"round3/compare/r1c/{c}-r1b-head-vs-r1c-head") for c in ("notify", "aecp_dispatch", "d3", "acmp")]


def main() -> int:
    root = Path(sys.argv[1])
    out = ["# Round 3: which comparison supersedes which", "",
           "The kept round-1c and round-2 failure-set comparisons (`r1c_failsets.py`) counted every",
           "top-level `*.log` as a mutant, so passing goldens and controls entered their closing",
           "totals; name_state, whose runs log in subdirectories, gave 0. They stay as they were.",
           "Each is superseded by the round-3 comparison beside it (`r3_failsets.py`, rosters from",
           "results.json, mutants and baselines apart), run on the same records, whose sha256 are",
           "in `inputs.sha256`. Generated by `scripts/r3_supersedes.py` from the files present.", "",
           "| Kept comparison | Its closing line | Superseded by | Mutants base / head | Mutants unchanged, changed, added, removed | Baselines base / head (not mutants) |",
           "|---|---|---|---|---|---|"]
    for old, new in PAIRS:
        s = json.loads((root / f"{new}.json").read_text())
        m = s["mutants"]
        last = (root / old).read_text().splitlines()[-1] if old else "(new: no earlier comparison)"
        out.append(f"| {f'`{old}`' if old else '—'} | {last} | `{new}.txt` | {s['base_mutants']} / "
                   f"{s['head_mutants']} | {m['unchanged']}, {len(m['changed'])}, {len(m['added'])}, "
                   f"{len(m['removed'])} | {s['base_baselines']} / {s['head_baselines']} |")
    out.append("")
    (root / "round3" / "SUPERSEDES.md").write_text("\n".join(out))
    print(f"SUPERSEDES.md: {len(PAIRS)} rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())
