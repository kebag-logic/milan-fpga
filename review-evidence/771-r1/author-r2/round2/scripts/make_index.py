#!/usr/bin/env python3
"""make_index.py ROUND2_DIR: regenerate round2/MANIFEST.sha256 and round2/INDEX.md.

Every file under ROUND2_DIR (but the two outputs) is hashed and listed with its
size and the one-line description DESCRIPTIONS gives its directory. A file over
200 KB is refused: such a file is recorded by digest and size, not kept.
"""
import hashlib
import sys
from pathlib import Path

LIMIT = 200 * 1024
DESCRIPTIONS = {
    "case-a": "Item 1: case (a) or (b) decided on the production path; the walk and its controls",
    "firmware-gates": "Item 1: the local firmware gate set at the final head",
    "quick-gates": "RTL, record and documentation gates at the final head",
    "docs-steps": "Hosted docs-check steps run literally under GNU Make 4.3 at the final head",
    "sweep": "Full parent sweep (default inventory) at the final head",
    "physical": "Physical gPTP leg (milan_dp_gptp) at the final head",
    "rtl-gates": "Yosys, xvlog and behave at the final head",
    "sdk": "The verified RV32 SDK the firmware gates ran with",
    "scripts": "The scripts that produced these receipts",
    "large-files": "Digests and sizes of outputs too large to keep",
}
root = Path(sys.argv[1]).resolve()
outputs = {"MANIFEST.sha256", "INDEX.md"}
rows, manifest, refused = [], [], []
for path in sorted(p for p in root.rglob("*") if p.is_file()):
    rel = path.relative_to(root).as_posix()
    if rel in outputs:
        continue
    data = path.read_bytes()
    if len(data) > LIMIT:
        refused.append(rel)
        continue
    digest = hashlib.sha256(data).hexdigest()
    manifest.append(f"{digest}  {rel}")
    rows.append((rel, len(data), digest))
if refused:
    sys.exit(f"refused, over 200 KB: {refused}")
(root / "MANIFEST.sha256").write_text("\n".join(manifest) + "\n")
lines = ["# Round 2 receipts index", "",
         "Generated by `make_index.py` (in `scripts/`); `sha256sum -c MANIFEST.sha256` from this directory "
         "verifies every file listed.", ""]
for top in sorted({r[0].split("/")[0] for r in rows}):
    lines += [f"## {top}", "", DESCRIPTIONS.get(top, ""), "", "| File | Bytes | SHA-256 |", "|---|---:|---|"]
    lines += [f"| `{rel}` | {size:,} | `{digest}` |" for rel, size, digest in rows if rel.split("/")[0] == top]
    lines.append("")
(root / "INDEX.md").write_text("\n".join(lines))
print(f"{len(rows)} files indexed under {root}")
