def apply(tree: Path, edits: list[tuple[str, str, str]]) -> None:
    for rel, old, new in edits:
        path = tree / rel
        text = path.read_text(encoding="utf-8")
        count = text.count(old)
        if count != 1:
            raise SystemExit(f"anchor matched {count} times in {rel}: {old[:60]!r}")
        path.write_text(text.replace(old, new), encoding="utf-8")


def run_one(head: Path, work: Path, mid: str) -> dict:
    desc, edits = MUTANTS[mid]
    tree = work / mid
    if tree.exists():
        shutil.rmtree(tree)
    shutil.copytree(head, tree, symlinks=True)
    apply(tree, edits)
    result = {"id": mid, "description": desc}
    for label, cmd in (("unit", ["python3", RC, "--selftest"]),
                       ("integration", ["python3", "syn/yosys/cache_selftest.py", "--logs", str(work / f"{mid}.logs")])):
        start = time.monotonic()
        proc = subprocess.run(cmd, cwd=tree, capture_output=True, text=True)
        out = (proc.stdout + proc.stderr).replace(str(work), "<work>")
        result[label] = {"exit": proc.returncode, "seconds": round(time.monotonic() - start, 1),
                         "tail": [l[:300] for l in out.splitlines() if "FAIL" in l or "OK" in l][:6]}
        (work / f"{mid}.{label}.log").write_text(out, encoding="utf-8")
    result["killed"] = result["unit"]["exit"] != 0 or result["integration"]["exit"] != 0
    shutil.rmtree(tree)
    return result


def main(argv: list[str]) -> int:
    head, work, out, *ids = argv
    head, work = Path(head), Path(work)
    work.mkdir(parents=True, exist_ok=True)
    ids = ids or list(MUTANTS)
    with ThreadPoolExecutor(max_workers=6) as pool:
        results = list(pool.map(lambda m: run_one(head, work, m), ids))
    Path(out).write_text(json.dumps(results, indent=2) + "\n", encoding="utf-8")
    for r in results:
        print(f"{r['id']:34s} unit={r['unit']['exit']} integ={r['integration']['exit']} "
              f"{'KILLED' if r['killed'] else 'SURVIVED'}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
