"""Disposable mutation campaign for the #520 cache controls.

Each mutant is applied to a private copy of the exact-head tree (never to the
review clone), then the two named self-tests run in that copy:

  python3 syn/yosys/result_cache.py --selftest      (unit)
  python3 syn/yosys/cache_selftest.py               (unit + original live arms + ROM bank)

A mutant is KILLED when either exits non-zero. Each substitution must match
its anchor exactly once, so a mutant cannot silently become a no-op.

usage: mutate.py HEAD_COPY WORK_DIR OUT_JSON [MUTANT_ID...]   (default: all)
"""
