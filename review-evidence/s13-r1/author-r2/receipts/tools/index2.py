#!/usr/bin/env python3
"""index2.py RECEIPTS: write RECEIPTS/INDEX.md from the files present. One row per file (path, bytes, sha256 prefix),
grouped by directory with each directory's role; identity/ (the hash-bound operand packet, up to 20 MiB a file by
the round-2 assignment) is listed per directory with its own MANIFEST.sha256 named. Refuses a file over 200 KB
outside identity/ and over 20 MiB inside it."""
import hashlib
import sys
from pathlib import Path

ROLES = {
    "f1": "R880-1-F1: the resource sweep at base, at round 1's head (the reproduction), and at the fixing heads: clean "
          "exports with no platform image, the refusal cases, the missing-image control, the base comparison",
    "s1": "R879-S1: the CPU-budget harness's SoC export argv, measured against round 1 and this round",
    "gates": "the gates rerun at this round's heads, and the planted defects of the round's new checks",
    "public": "the public comments this lane posted this round",
    "tools": "the scripts and check lists that produced these receipts (host paths replaced)",
    "identity": "R880-1-F2/F3: the identity packet; replay with `python3 -I tools/replay.py .` inside it; its "
                "MANIFEST.sha256 lists every file below it",
}
root = Path(sys.argv[1])
rows, bad = {}, []
for p in sorted(root.rglob("*")):
    if not p.is_file() or p.name == "INDEX.md":
        continue
    rel = p.relative_to(root)
    size = p.stat().st_size
    limit = 20 * 2 ** 20 if rel.parts[0] == "identity" else 200_000
    if size > limit:
        bad.append(f"{rel} ({size} B)")
    top = rel.parts[0] if len(rel.parts) > 1 else "."
    d = str(rel.parent)
    rows.setdefault((top, d), []).append((rel.name, size, hashlib.sha256(p.read_bytes()).hexdigest()[:16]))
if bad:
    sys.exit("files over the limit: " + ", ".join(bad))
n = sum(len(v) for v in rows.values())
out = ["# Receipts index, round 2", "", f"Generated by `tools/index2.py` from the {n} files present "
       f"({sum(s for v in rows.values() for _, s, _ in v):,} B).", ""]
for top in sorted({t for t, _ in rows}):
    out += [f"## `{top}/`", "", ROLES.get(top, ""), ""]
    for (t, d) in sorted(k for k in rows if k[0] == top):
        files = rows[(t, d)]
        if t == "identity" and len(files) > 12:
            out += [f"- `{d}/`: {len(files)} files, {sum(s for _, s, _ in files):,} B (hashes in "
                    f"`identity/MANIFEST.sha256`)"]
            continue
        out += ["", f"### `{d}/`", "", "| File | Bytes | sha256 |", "|---|---:|---|"]
        out += [f"| `{f}` | {s:,} | `{h}` |" for f, s, h in files] + [""]
    out.append("")
(root / "INDEX.md").write_text("\n".join(out))
print(f"INDEX.md: {n} files")
