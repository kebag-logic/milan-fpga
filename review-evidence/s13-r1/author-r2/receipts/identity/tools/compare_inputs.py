#!/usr/bin/env python3
"""compare_inputs.py BUILT_WORK BUILT_CLONE HEAD_WORK HEAD_CLONE STEM: one image's inputs at a later head against the
built image's (the gating recipe's work and clone directories at each head).

Compared, each file's text with its own tree's roots (clone, work directory) replaced by placeholders and LiteX's
generation date stamps removed:
  * the recipe argv (argv.txt);
  * the platform image: the loaded sections of sw/builder/out/<stem>/ctrl_app.elf (elfdiff.py's reading);
  * every file the head's milan_soc.py export (no --build) wrote under export/ except its software/ build tree and
    the log, against the built image's build_ExtraPostPlacementOpt/ file of the same path: the top Verilog outside
    its comments (its header comment carries a run-ordered hierarchy tree), the Vivado Tcl, the XDC with its
    asynchronous clock-group pairs as an unordered set (LiteX writes the same pairs in a run-dependent order and
    orientation; the bench build and the 822e3af0 build differ so and their Vivado checksums are equal), every memory
    init file, csr.csv/json, the AEM blob, the flash layout and the manifest without the bitstream binding only a
    Vivado build adds, and the manifest without the platform image's whole-file hash, whose loaded sections are
    compared above.
Exit 0 when every input is equal."""
import json
import re
import subprocess
import sys
from pathlib import Path

built_work, built_clone, head_work, head_clone, stem = map(Path, sys.argv[1:6])
stem = str(stem)
bad = 0


def norm(path, roots):
    data = path.read_bytes()
    for name, root in sorted(roots.items(), key=lambda kv: -len(kv[1])):
        data = data.replace(root.encode(), name.encode())
    data = re.sub(rb"(Auto-generated by LiteX \([0-9a-f]+\)) on [0-9: -]+", rb"\1", data)
    data = re.sub(rb"(Auto-Generated by LiteX) on [0-9: -]+\.", rb"\1.", data)
    return re.sub(rb"(// Date       : )[0-9: -]+", rb"\1", data)


def verdict(what, equal):
    global bad
    print(f"{'EQUAL  ' if equal else 'DIFFERS'} {what}")
    bad += not equal


verdict("argv.txt", (built_work / "argv.txt").read_bytes() == (head_work / "argv.txt").read_bytes())
elf = f"sw/builder/out/{stem}/ctrl_app.elf"
r = subprocess.run([sys.executable, "-I", str(Path(__file__).with_name("elfdiff.py")), str(built_clone / elf),
                    str(head_clone / elf)], capture_output=True, text=True)
verdict(f"{elf}: loaded sections ({r.stdout.strip().splitlines()[-1]})", r.returncode == 0)
build = built_work / "build_ExtraPostPlacementOpt"
export = head_work / "export"
ra = {"<CLONE>": str(built_clone), "<WORK>": str(built_work), "<OUT>": str(build)}
rb = {"<CLONE>": str(head_clone), "<WORK>": str(head_work), "<OUT>": str(export)}
files = sorted(p.relative_to(export) for p in export.rglob("*") if p.is_file()
               and p.relative_to(export).parts[0] != "software" and p.name != "litex.log")
for rel in files:
    a, b = build / rel, export / rel
    if not a.is_file():
        verdict(f"{rel}: not in the built image's directory", False)
        continue
    na, nb = norm(a, ra), norm(b, rb)
    if rel.name in ("image_manifest.json", "flashboot_layout.json"):
        ja, jb = json.loads(na), json.loads(nb)
        for j in (ja, jb):
            j.pop("bitstream", None), j.pop("bitstream_payload_sha256", None), j.pop("bitstream_fpga_part", None)
            j.get("ctrl_firmware", {}).pop("sha256", None)
        verdict(f"{rel} (without the binding a Vivado build adds and the ELF's whole-file hash)", ja == jb)
    elif rel.suffix == ".v":
        strip = lambda d: "\n".join(l.split("//", 1)[0].rstrip() for l in re.sub(r"/\*.*?\*/", "", d.decode(),
                                     flags=re.S).splitlines() if l.split("//", 1)[0].strip())  # noqa: E731
        verdict(f"{rel} (outside its comments)", strip(na) == strip(nb))
    elif rel.suffix == ".xdc":
        pair = re.compile(r"^set_clock_groups -group (.+?) -group (.+?) -asynchronous$")
        def split(d):
            lines = [l for l in d.decode().splitlines() if l.strip()]
            pairs = sorted(tuple(sorted(m.groups())) for m in map(pair.match, lines) if m)
            return [l for l in lines if not pair.match(l)], pairs
        (la, pa), (lb, pb) = split(na), split(nb)
        verdict(f"{rel} (its {len(pa)} clock-group pairs as a set, every other line in order)", la == lb and pa == pb)
    else:
        verdict(str(rel), na == nb)
print(f"{len(files) + 2} inputs compared, {bad} differ")
sys.exit(1 if bad else 0)
