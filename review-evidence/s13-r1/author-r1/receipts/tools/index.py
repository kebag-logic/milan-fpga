#!/usr/bin/env python3
"""index.py RECEIPTS: write RECEIPTS/INDEX.md from the files present: one row per file (path, bytes, sha256 prefix),
grouped by directory with each directory's role; refuses a file over 200 KB."""
import hashlib
import sys
from pathlib import Path

ROLES = {
    "identity/1x1": "1x1/1if image identity against the bench image c7189218: bitstream, firmware, checkpoint and input-carry diffs, signoff",
    "identity/8x8": "8x8/1if image identity against the bench image 7d903412: the same",
    "release": "the release (all-fabric) export at base and head",
    "flip": "the flip check and load grade at the owner's bounds",
    "budget": "the CPU-budget harness: arm images against the measured ones; the re-measured descriptor groups",
    "sweep": "the sharded sweep, its spec, shard summaries and the wall-clock kills rerun alone",
    "gates": "the other gates' logs: firmware, builder, docs workflow, quick list, split boot, twin, boundary, BDD, xvlog, Yosys, split jobs, carry",
    "checks": "the new checks' planted defects and their failing words",
    "public": "the public comments this lane posted",
    "tools": "the scripts that produced these receipts (scratch paths replaced)",
}
root = Path(sys.argv[1])
rows, big = {}, []
for p in sorted(root.rglob("*")):
    if not p.is_file() or p.name == "INDEX.md":
        continue
    rel = p.relative_to(root)
    size = p.stat().st_size
    if size > 200_000:
        big.append(f"{rel} ({size} B)")
    d = str(rel.parent)
    rows.setdefault(d, []).append((rel.name, size, hashlib.sha256(p.read_bytes()).hexdigest()[:16]))
if big:
    sys.exit("files over 200 KB: " + ", ".join(big))
out = ["# Receipts index", "", f"Generated by `tools/index.py` from the {sum(len(v) for v in rows.values())} files "
       f"present ({sum(s for v in rows.values() for _, s, _ in v):,} B).", ""]
for d in sorted(rows):
    out += [f"## `{d}/`", "", ROLES.get(d, ""), "", "| File | Bytes | sha256 |", "|---|---:|---|"]
    out += [f"| `{n}` | {s:,} | `{h}` |" for n, s, h in rows[d]] + [""]
(root / "INDEX.md").write_text("\n".join(out))
print(f"INDEX.md: {sum(len(v) for v in rows.values())} files")
