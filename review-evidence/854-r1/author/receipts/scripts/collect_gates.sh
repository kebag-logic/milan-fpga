#!/usr/bin/env bash
# collect_gates.sh: copy the gate logs and rc files into receipts/gates (lane, docsyml-*, sweep); a file over 200 KB
# is not copied, its sha256 and size go to LARGE-FILES.sha256 in that directory. Then write receipts/INDEX.md from the
# files present.
set -u
S=$VALIDATION_STORAGE/scratch/854-a756
O=$(cd "$(dirname "$0")/.." && pwd)
put() {  # put <src file> <dest dir>
  mkdir -p "$2"
  if [ "$(stat -c %s "$1")" -gt 204800 ]; then
    (cd "$(dirname "$1")" && sha256sum "$(basename "$1")" | tr '\n' ' ' && stat -c '%s bytes' "$(basename "$1")") >> "$2/LARGE-FILES.sha256"
  else
    cp "$1" "$2/"
  fi
}
rm -rf "$O/gates"
for f in "$S"/gates/lane/*; do put "$f" "$O/gates/lane"; done
for d in "$S"/docsyml-e87f2179*; do
  n=$(basename "$d")
  for f in "$d"/progress.txt "$d"/verify.txt "$d"/verify.rc "$d"/*.runner.log "$d"/logs/*; do [ -f "$f" ] && put "$f" "$O/gates/$n"; done
done
for r in run1 run2 run3; do
  case $r in run3) src=$S/sweep-serial/spec; logs=$S/sweep-serial/logs; out=$S/sweep-serial/runner.out ;;
              *) src=$S/sweep-serial/spec-$r; logs=$S/sweep-serial/logs-$r; out=$S/sweep-serial/runner-$r.out ;; esac
  [ -d "$src" ] || continue
  for f in "$src"/* "$out"; do [ -f "$f" ] && put "$f" "$O/gates/sweep-$r"; done
  [ -d "$logs" ] && find "$logs" -maxdepth 1 -type f | sort | while read -r f; do put "$f" "$O/gates/sweep-$r/logs"; done
  [ -d "$logs/preflight" ] && for f in "$logs"/preflight/*; do put "$f" "$O/gates/sweep-$r/logs/preflight"; done
done
[ -f "$S/sigign-nohup-launch.txt" ] && put "$S/sigign-nohup-launch.txt" "$O/gates/sweep-run1"
# run 4: the full sweep as four native-shards units (shard-k/spec.json, the runner's files, shard-k/logs/*)
for d in "$S"/shards/shard-*; do
  [ -d "$d" ] || continue
  k=$(basename "$d")
  for f in "$d"/spec.json "$d"/spec/*; do [ -f "$f" ] && put "$f" "$O/gates/sweep-shards/$k"; done
  [ -d "$d/logs" ] && find "$d/logs" -maxdepth 1 -type f | sort | while read -r f; do put "$f" "$O/gates/sweep-shards/$k/logs"; done
  [ -d "$d/logs/preflight" ] && for f in "$d"/logs/preflight/*; do put "$f" "$O/gates/sweep-shards/$k/logs/preflight"; done
done
[ -f "$S/shards-launch.txt" ] && put "$S/shards-launch.txt" "$O/gates/sweep-shards"
[ -f "$S/shards-spec.json" ] && put "$S/shards-spec.json" "$O/gates/sweep-shards"
[ -f "$S/shards/tree-after.txt" ] && put "$S/shards/tree-after.txt" "$O/gates/sweep-shards"
cd "$O" || exit 1
{
  echo "# Receipts index (generated by scripts/collect_gates.sh from the files present)"
  echo
  echo "| File | Bytes | sha256 |"
  echo "|---|---:|---|"
  find . -type f ! -name INDEX.md | sort | while read -r f; do
    echo "| \`${f#./}\` | $(stat -c %s "$f") | \`$(sha256sum "$f" | cut -c1-16)\` |"
  done
} > INDEX.md
echo "index: $(grep -c '^| `' INDEX.md) files"
