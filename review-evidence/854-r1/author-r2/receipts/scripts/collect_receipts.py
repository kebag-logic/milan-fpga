"""collect_receipts.py <scratch> <receipts>: copy this round's gate and chain logs into <receipts>, each text file with
host paths masked (mask.py); a file over 200 KB is not copied, and its SHA-256 and size (of the original) go to that
directory's LARGE-FILES.sha256. Then writes <receipts>/INDEX.md from the files present (path, bytes, SHA-256 prefix).
The area receipts (receipts/area) are written by collect_area.py, collect_paths.py and route_figures.py beforehand."""
import hashlib
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from mask import mask  # noqa: E402

S, R = Path(sys.argv[1]), Path(sys.argv[2])
LIMIT = 200 * 1024


def put(src: Path, dest_dir: Path) -> None:
    dest_dir.mkdir(parents=True, exist_ok=True)
    data = src.read_bytes()
    if len(data) > LIMIT:
        with open(dest_dir / "LARGE-FILES.sha256", "a") as large:
            large.write(f"{hashlib.sha256(data).hexdigest()}  {len(data)}  {src.name}\n")
        return
    try:
        text = data.decode()
    except UnicodeDecodeError:
        shutil.copyfile(src, dest_dir / src.name)
        return
    (dest_dir / src.name).write_text(mask(text))


def tree(src: Path, dest: Path, depth: int = 1) -> None:
    if not src.is_dir():
        return
    for path in sorted(src.iterdir()):
        if path.is_file():
            put(path, dest)
        elif path.is_dir() and depth > 0:
            tree(path, dest / path.name, depth - 1)


for name in ("gates", "chain"):
    shutil.rmtree(R / name, ignore_errors=True)
G = R / "gates"
tree(S / "final-gates", G / "final")
for f in ("final-gates.out", "final-launch.txt", "fclone.txt"):
    if (S / f).exists():
        put(S / f, G / "final")
for d in sorted(S.glob("docsyml-*")):
    dest = G / d.name
    for f in ("progress.txt", "verify.txt", "verify.rc"):
        if (d / f).exists():
            put(d / f, dest)
    for f in sorted(d.glob("*.runner.log")):
        put(f, dest)
    tree(d / "logs", dest / "logs", 0)
tree(S / "pre-gates", G / "pre-4d6a165c")
for f in ("pre-gates.out", "pclone.txt"):
    if (S / f).exists():
        put(S / f, G / "pre-4d6a165c")
tree(S / "dev", G / "dev-lane", 0)
C = R / "chain"
tree(S / "alogs", C, 0)
for f in ("aclone.txt", "aclone8.txt", "collect-area.log", "precheck-ooc-1x1.log", "precheck-ooc-8x8.log"):
    if (S / f).exists():
        put(S / f, C)
for f in sorted(S.glob("collect-paths-*.log")):
    put(f, C)
rows = ["# Receipts index (generated by scripts/collect_receipts.py from the files present)", "",
        "| File | Bytes | sha256 |", "|---|---:|---|"]
for path in sorted(p for p in R.rglob("*") if p.is_file() and p.name != "INDEX.md" and "__pycache__" not in p.parts):
    rows.append(f"| `{path.relative_to(R).as_posix()}` | {path.stat().st_size} | "
                f"`{hashlib.sha256(path.read_bytes()).hexdigest()[:16]}` |")
(R / "INDEX.md").write_text("\n".join(rows) + "\n")
print(f"index: {len(rows) - 4} files")
