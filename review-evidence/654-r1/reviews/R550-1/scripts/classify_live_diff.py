#!/usr/bin/env python3
"""Classify every raw difference between two unfixed (live) export snapshots.

Usage: classify_live_diff.py BASE_SNAPSHOT HEAD_SNAPSHOT
A changed line is ACCEPTED only if it is (a) a generation timestamp banner
("Auto-generated by LiteX ... on <date>", "Auto-Generated by LiteX on <date>",
"// Date : <date>") or (b) a line of
the diagnostic hierarchy drawing (box-drawing tree characters) whose multiset
over the file is identical between the two sides (pure reordering). All other
lines must be identical in order.
Everything else is UNEXPLAINED and makes the exit status 1.
*.log files are excluded (diagnostic).
"""
import collections, difflib, re, sys
from pathlib import Path

a, b = Path(sys.argv[1]), Path(sys.argv[2])
TS = re.compile(r"(Auto-Generated by LiteX on \d{4}-\d\d-\d\d \d\d:\d\d:\d\d|Auto-generated by LiteX \([0-9a-f]+\) on \d{4}-\d\d-\d\d \d\d:\d\d:\d\d|Date\s*:\s*\d{4}-\d\d-\d\d \d\d:\d\d:\d\d)")
TREE = re.compile(r"[\u2500-\u257f]")
bad = 0
fa = {p.relative_to(a) for p in a.rglob("*") if p.is_file() and p.suffix != ".log"}
fb = {p.relative_to(b) for p in b.rglob("*") if p.is_file() and p.suffix != ".log"}
if fa != fb:
    print("POPULATION DIFFERS", sorted(fa ^ fb)); bad = 1
for rel in sorted(fa & fb):
    x, y = (a / rel).read_bytes(), (b / rel).read_bytes()
    if x == y:
        continue
    lx, ly = x.decode().splitlines(), y.decode().splitlines()
    # Changed lines = symmetric multiset difference (a line moved but present on
    # both sides counts as reordering, judged by the tree-multiset test below).
    cx, cy = collections.Counter(lx), collections.Counter(ly)
    changed = list(((cx - cy) + (cy - cx)).elements())
    changed += [l for l in set(lx) & set(ly) if TREE.search(l) and lx.index(l) != ly.index(l)]
    tree_x = collections.Counter(l for l in lx if TREE.search(l))
    tree_y = collections.Counter(l for l in ly if TREE.search(l))
    ts = sum(1 for l in changed if TS.search(l))
    tr = sum(1 for l in changed if not TS.search(l) and TREE.search(l))
    other = [l for l in changed if not TS.search(l) and not TREE.search(l)]
    reorder_ok = tree_x == tree_y
    # Everything that is neither a timestamp nor a hierarchy-drawing line must be
    # identical IN ORDER, so no reordering of real content can hide in a multiset.
    rest_x = [l for l in lx if not TS.search(l) and not TREE.search(l)]
    rest_y = [l for l in ly if not TS.search(l) and not TREE.search(l)]
    order_ok = rest_x == rest_y
    ok = not other and reorder_ok and order_ok
    bad |= not ok
    print(f"{'EXPLAINED  ' if ok else 'UNEXPLAINED'} {rel}: {ts} timestamp lines, "
          f"{tr} hierarchy-drawing lines (same multiset: {reorder_ok}), {len(other)} other, "
          f"remaining {len(rest_x)} lines identical in order: {order_ok}")
    for l in other[:5]:
        print("    other:", l[:160])
print("RESULT", "all live differences explained" if not bad else "UNEXPLAINED differences")
sys.exit(bad)
