#!/usr/bin/env python3
"""Reviewer check of the issue 117 headless-enumeration evidence packet.

usage: verify_packet.py <packet_author_dir> <aem_desc.bin> <aem_desc.map>

The AEM image and map are regenerated by the reviewer from the product-image
source (see run_regen.sh); nothing here reads the author's build artifacts.

Checks, each printed as CHECK <name> OK|FAIL <detail>:
  aem_sha        regenerated image SHA-256 and CRC32 equal the assigned values
  aecp_<desc>    AECP READ_DESCRIPTOR payload minus the 4-byte
                 configuration_index/reserved prefix equals the image bytes,
                 and control_data_length = payload + 12 (IEEE 1722.1 AEM header)
  map_inventory  descriptor types/counts in the image map equal each run's
                 inventory recomputed here from the entity JSON
  flags          each entity JSON carries the library's own flags
                 IEEE17221+MILAN, no compatibility events, no diagnostics
  logs           each log carries flags=IEEE17221|Milan, complaints=0,
                 query-errors 0, rc=0, and distinct START/END windows
  static_tree    canonical static tree SHA-256 equal across runs and equal
                 to the value on the findings page
"""
import hashlib
import json
import re
import sys
import zlib
from collections import defaultdict
from pathlib import Path

AEM_SHA = "9b077636b1d42aca660b16dce8eafa06f1e3cac842134e51ba65930d16214404"
AEM_CRC = "93742dd2"
STATIC_TREE = "460b15ac38dc05adac991bbd7f23f48640ee589703ae8d15b5eea4e5c4f0ec3b"
TYPES = {0x0000: "ENTITY", 0x0001: "CONFIGURATION", 0x0002: "AUDIO_UNIT",
         0x0005: "STREAM_INPUT", 0x0006: "STREAM_OUTPUT", 0x0009: "AVB_INTERFACE",
         0x000A: "CLOCK_SOURCE", 0x000C: "LOCALE", 0x000D: "STRINGS",
         0x000E: "STREAM_PORT_INPUT", 0x000F: "STREAM_PORT_OUTPUT",
         0x0014: "AUDIO_CLUSTER", 0x001A: "CONTROL", 0x0024: "CLOCK_DOMAIN"}
fails = 0


def check(name, ok, detail=""):
    global fails
    fails += 0 if ok else 1
    print(f"CHECK {name} {'OK' if ok else 'FAIL'} {detail}")


def main():
    pkt, img_path, map_path = map(Path, sys.argv[1:4])
    img = img_path.read_bytes()
    sha = hashlib.sha256(img).hexdigest()
    crc = f"{zlib.crc32(img) & 0xffffffff:08x}"
    check("aem_sha", sha == AEM_SHA and crc == AEM_CRC and len(img) == 7352,
          f"len={len(img)} sha256={sha} crc32={crc}")

    rows = []
    for line in map_path.read_text().splitlines():
        m = re.match(r"\s*0\s+0x([0-9A-F]{4})\s+(\d+)\s+(\d+)\s+(\d+)\s+(\d+)\s+0x([0-9A-F]+)", line)
        if m:
            t, first, count, elen, stride, off = m.groups()
            rows.append((int(t, 16), int(first), int(count), int(elen), int(stride), int(off, 16)))
    img_inv = defaultdict(list)
    for t, first, count, *_ in rows:
        img_inv[TYPES[t]] += list(range(first, first + count))
    img_inv = {k: sorted(v) for k, v in img_inv.items()}

    loc = {(t, first): (elen, off) for t, first, _, elen, _, off in rows}
    for rec in map(json.loads, (pkt / "identity-aecp.jsonl").read_text().splitlines()):
        if rec.get("cmd") != "READ_DESCRIPTOR":
            continue
        p = bytes.fromhex(rec["payload"])
        dtype, didx = int.from_bytes(p[4:6], "big"), int.from_bytes(p[6:8], "big")
        elen, off = loc[(dtype, didx)]
        body = p[4:]
        ok = rec["status"] == "SUCCESS" and body == img[off:off + elen] and rec["cdl"] == len(p) + 12
        check(f"aecp_{TYPES[dtype]}", ok,
              f"bytes={len(body)} image_off=0x{off:X} image_len={elen} cdl={rec['cdl']}")

    def walk(o, found):
        if isinstance(o, dict):
            for k, v in o.items():
                if k.endswith("_descriptors") and isinstance(v, list):
                    for d in v:
                        found[k[:-len("_descriptors")].upper()].append(d["_index (informative)"])
                walk(v, found)
        elif isinstance(o, list):
            for v in o:
                walk(v, found)

    def static(o):
        if isinstance(o, dict):
            return {k: static(v) for k, v in o.items() if k != "dynamic"}
        if isinstance(o, list):
            return [static(v) for v in o]
        return o

    trees, windows = [], []
    for n in (1, 2, 3):
        j = json.loads((pkt / f"run-{n}.entity.json").read_text())
        log = (pkt / f"run-{n}.log").read_text()
        found = defaultdict(list, ENTITY=[0])
        walk(j["entity_model"], found)
        inv = {k: sorted(v) for k, v in found.items()}
        check(f"map_inventory_run{n}", inv == img_inv,
              f"types={len(inv)} descriptors={sum(map(len, inv.values()))}")
        pub_inv = json.loads((pkt / f"run-{n}.inventory.json").read_text())
        check(f"published_inventory_run{n}", pub_inv == inv)
        check(f"flags_run{n}",
              j["compatibility_flags"] == ["IEEE17221", "MILAN"] and j["compatibility_events"] == []
              and j["diagnostics"] == {"redundancy_warning": False, "stream_input_latency_errors": []}
              and j["adp_information"]["common"]["entity_id"] == "0x020000FFFE000001"
              and j["entity_model_id"] == "0x001BC5C40236BA0E",
              f"flags={j['compatibility_flags']} events={len(j['compatibility_events'])}")
        st = j["statistics"]
        check(f"statistics_run{n}",
              st["aecp_retry_counter"] == 0 and st["aecp_timeout_counter"] == 0
              and st["aecp_unexpected_response_counter"] == 0,
              f"enumeration_time={st['enumeration_time']} avg={st['aecp_response_average_time']}")
        ent = [l for l in log.splitlines() if l.startswith("ENTITY 0x020000fffe000001 model=")]
        ok = (len(ent) == 1 and "flags=IEEE17221|Milan " in ent[0]
              and re.search(r"^SUMMARY online=\d+ complaints=0$", log, re.M)
              and re.search(r"^ENTITY 0x020000fffe000001 query-errors 0$", log, re.M)
              and re.search(r"diagnostics redundancyWarning=0 controlsOutOfBounds=0 streamInputOverLatency=0$", log, re.M)
              and re.search(r" rc=0$", log, re.M)
              and "COMPLAINT" not in log and "EVENT compatibility" not in log
              and "EVENT query-error" not in log and "compat-change" not in log)
        check(f"log_run{n}", bool(ok), ent[0] if ent else "no ENTITY line")
        windows.append(tuple(l for l in log.splitlines() if l.startswith(("START ", "END "))))
        trees.append(hashlib.sha256(json.dumps(static(j["entity_model"]), sort_keys=True,
                                               separators=(",", ":")).encode()).hexdigest())
    check("distinct_windows", len(set(windows)) == 3 and all(len(w) == 2 for w in windows),
          "; ".join(w[0][6:25] for w in windows))
    check("static_tree", len(set(trees)) == 1 and trees[0] == STATIC_TREE, trees[0])
    print(f"RESULT {'PASS' if fails == 0 else 'FAIL'} failures={fails}")
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
