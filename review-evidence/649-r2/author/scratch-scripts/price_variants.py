#!/usr/bin/env python3
"""Scratch only (never committed): price the SoC's CPU, cache and L2 variants that the
recipe refuses under its one software profile (issue #649, round-2 ruling).

The tracked recipe sw/litex/milan_soc.py is never written. A scratch export of HEAD
(syn/resmap/yosys_sweep.py export_tree) gets a SECOND copy of the recipe,
milan_soc_pricing.py, with exactly the two baremetal-profile refusals removed. Every
variant (shipping included) is exported through that copy without --build; the
shipping variant is also exported through the unmodified tracked copy, and the two
gateware tops must be byte-identical (the bypass changes nothing an accepted shape
elaborates). CPU netlists are generated by the CPU generators in scratch copies of
the two pythondata packages (PYTHONPATH first), never in the shared LiteX tree.

Each export is then synthesized out of context by Vivado (soc_ooc.tcl, one run at a
time under the shared lock): the LiteX top with the CPU netlist, and every other
non-LiteX module (milan_datapath and the parent's own SystemVerilog blocks) replaced by
a black box with 1024-bit ports, exactly the round-1 Yosys stubbing. Every variant
reads the shipping variant's BIOS ROM image, so ROM content is held constant.

    price_variants.py prepare
    price_variants.py export [NAME..]
    price_variants.py vivado-prep [NAME..]
    price_variants.py collect
"""

