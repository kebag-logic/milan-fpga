def sha256(path: Path) -> str:
    return yosys_sweep.sha256(path)


def env() -> dict:
    return {**os.environ, "PYTHONHASHSEED": "0", "LITEX_ENV_CC_TRIPLE": soc_sweep.compiler_triple(),
            "PYTHONPATH": f"{CPU / 'pythondata-cpu-vexiiriscv'}:{CPU / 'pythondata-cpu-naxriscv'}",
            "PATH": f"{SDK / 'bin'}:{Path(LITEX_PYTHON).parent}:{os.environ['PATH']}"}


def command_prepare() -> int:
    tree = yosys_sweep.export_tree(WORK)
    base = soc_sweep.prepare(WORK)
    recipe = tree / "sw" / "litex" / "milan_soc.py"
    text = recipe.read_text()
    for block in REFUSALS:
        if text.count(block) != 1:
            print(f"prepare: refusal block not found exactly once: {block[:60]!a}")
            return 1
        text = text.replace(block, "    pass  # pricing copy (#649 round 2): the profile refusal is removed\n")
    pricing = recipe.with_name("milan_soc_pricing.py")
    pricing.write_text(text)
    diff = subprocess.run(["diff", "-u", str(recipe), str(pricing)], capture_output=True, text=True).stdout
    (WORK / "pricing-copy.diff").write_text(diff)
    record = {"head": (tree / ".resmap-export").read_text().split()[0], "base_argv": base,
              "tracked_recipe_sha256": sha256(recipe), "pricing_copy_sha256": sha256(pricing),
              "pricing_diff_sha256": sha256(WORK / "pricing-copy.diff"),
              "vexii_patch": subprocess.run(["git", "-C", str(CPU / "pythondata-cpu-vexiiriscv/pythondata_cpu_vexiiriscv/verilog/ext/VexiiRiscv"),
                                             "diff", "--stat"], capture_output=True, text=True).stdout.strip()}
    (WORK / "prepare.json").write_text(json.dumps(record, indent=1, sort_keys=True) + "\n")
    print(f"prepare: export of {record['head']}, pricing copy {record['pricing_copy_sha256'][:16]}")
    return 0


def export_one(name: str, recipe: str, spec: dict, base: list[str]) -> dict:
    directory = WORK / "soc" / name
    if directory.exists():
        shutil.rmtree(directory)
    directory.mkdir(parents=True)
    argv = soc_sweep.variant_argv(base, spec) + ["--output-dir", str(directory / "export")]
    log = directory / "export.log"
    began = time.time()
    with log.open("w") as handle:
        rc = subprocess.run([LITEX_PYTHON, recipe, *argv], cwd=WORK / "tree/sw/litex", env=env(),
                            stdout=handle, stderr=subprocess.STDOUT, check=False).returncode
    text = log.read_text(errors="replace")
    netlist = re.search(r"(?:VexiiRiscv|NaxRiscv) netlist ?: ?(\S+)", text)
    top = directory / "export" / "gateware" / "alinx_ax7101.v"
    record = {"recipe": recipe, "argv": argv, "rc": rc, "seconds": round(time.time() - began, 1),
              "log_sha256": sha256(log), "log_bytes": log.stat().st_size,
              "cpu_netlist": netlist.group(1) if netlist else "",
              "top_sha256": sha256(top) if top.is_file() else "",
              "error_tail": [line for line in text.splitlines() if re.search(r"error|Error|ERROR|Traceback", line)][-6:]}
    print(f"export {name}: rc={rc} {record['seconds']} s {record['cpu_netlist'] or record['error_tail'][-1:]}",
          flush=True)
    return record


def command_export(names: list[str]) -> int:
    prep = json.loads((WORK / "prepare.json").read_text())
    path = WORK / "exports.json"
    records = json.loads(path.read_text()) if path.is_file() else {}
    chosen = [n for n in VARIANTS if not names or n in names]
    if not names or "ship" in names:
        chosen.append("ship-tracked")
    failures = 0
    for name in chosen:
        if name == "ship-tracked":
            record = export_one(name, "milan_soc.py", {}, prep["base_argv"])
        else:
            parameter, value, spec = VARIANTS[name]
            record = export_one(name, "milan_soc_pricing.py", spec, prep["base_argv"])
            record.update(parameter=parameter, value=value)
        records[name] = record
        path.write_text(json.dumps(records, indent=1, sort_keys=True) + "\n")
        failures += record["rc"] != 0
    return 1 if failures else 0


OOC_TCL = r"""# Scratch only: Vivado out-of-context synthesis of one exported SoC top (issue #649 round 2).
set dir [file normalize [lindex $argv 0]]
cd $dir
set fh [open sources.txt r]; set sources [split [string trim [read $fh]] "\n"]; close $fh
foreach source $sources { read_verilog $source }
synth_design -directive default -mode out_of_context -top alinx_ax7101 -part PART_NAME
report_utilization -hierarchical -hierarchical_depth 2 -file synth_hierarchy.rpt
report_utilization -file synth_utilization.rpt
# No opt_design: it refuses primitives that a black box drives (Opt 31-30), and the black boxes are the
# point of this run. Every variant is therefore compared after synthesis.
puts "SOC_OOC_DONE"
""".replace("PART_NAME", PART)


def command_vivado_prep(names: list[str]) -> int:
    exports = json.loads((WORK / "exports.json").read_text())
    ship_rom = WORK / "soc" / "ship" / "export" / "gateware" / "alinx_ax7101_rom.init"
    failures = 0
    for name, record in exports.items():
        if record["rc"] or (names and name not in names) or name == "ship-tracked":
            continue
        gateware = WORK / "soc" / name / "export" / "gateware"
        directory = WORK / "vivado" / name
        if directory.exists():
            shutil.rmtree(directory)
        directory.mkdir(parents=True)
        top_text = (gateware / "alinx_ax7101.v").read_text()
        foreign = soc_sweep.foreign_modules(top_text)
        cpu_module = record["cpu_netlist"]
        if cpu_module not in foreign:
            print(f"vivado-prep {name}: CPU module {cpu_module} is not instantiated by the top")
            failures += 1
            continue
        stubbed = sorted(foreign - {cpu_module})
        (directory / "stubs.v").write_text(soc_sweep.stubs(top_text, set(stubbed)).replace("(* blackbox *)",
                                                                                            "(* black_box *)"))
        tcl_text = (gateware / "alinx_ax7101.tcl").read_text()
        cpu_srcs = soc_sweep.cpu_sources(tcl_text, cpu_module)
        shutil.copyfile(gateware / "alinx_ax7101.v", directory / "alinx_ax7101.v")
        for init in gateware.glob("*.init"):
            shutil.copyfile(init, directory / init.name)
        shutil.copyfile(ship_rom, directory / "alinx_ax7101_rom.init")
        sources = [*map(str, cpu_srcs), str(directory / "alinx_ax7101.v"), str(directory / "stubs.v")]
        (directory / "sources.txt").write_text("\n".join(sources) + "\n")
        (directory / "soc_ooc.tcl").write_text(OOC_TCL)
        meta = {"stubbed": stubbed, "cpu_module": cpu_module,
                "cpu_sources_sha256": {p.name: sha256(p) for p in cpu_srcs},
                "top_sha256": sha256(directory / "alinx_ax7101.v"),
                "own_rom_sha256": sha256(gateware / "alinx_ax7101_rom.init")
                if (gateware / "alinx_ax7101_rom.init").is_file() else "",
                "read_rom_sha256": sha256(ship_rom), "tcl_sha256": sha256(directory / "soc_ooc.tcl")}
        (directory / "meta.json").write_text(json.dumps(meta, indent=1, sort_keys=True) + "\n")
        print(f"vivado-prep {name}: stubbed {stubbed}; cpu {cpu_module}")
    return 1 if failures else 0


def hierarchy_rows(path: Path) -> dict:
    sys.path.insert(0, str(REPO / "syn" / "ooc"))
    from pp_baseline_rank import hierarchy  # noqa: E402,PLC0415
    return hierarchy(path)


def command_collect() -> int:
    exports = json.loads((WORK / "exports.json").read_text())
    out = {}
    for name, record in exports.items():
        directory = WORK / "vivado" / name
        parameter, value, _spec = VARIANTS.get(name, ("shipping", "-", {}))
        entry = {"export": record, "parameter": parameter, "value": value, "x": X.get(name)}
        if record["rc"]:
            text = (WORK / "soc" / name / "export.log").read_text(errors="replace").splitlines()
            first = next((line for line in text if "Exception in thread" in line), "")
            record["reason"] = first.replace("[error] ", "").strip() or (record["error_tail"] or ["?"])[-1]
        if (directory / "meta.json").is_file():
            entry["meta"] = json.loads((directory / "meta.json").read_text())
        for stage in ("synth", "opt"):
            report = directory / f"{stage}_hierarchy.rpt"
            if report.is_file():
                rows = hierarchy_rows(report)
                root = next(k for k in rows if "/" not in k)
                cpu = f"{root}/{entry['meta']['cpu_module']}" if "meta" in entry else None
                cpu = cpu if cpu in rows else None
                entry[stage] = {"total": rows[root], "cpu_row": cpu, "cpu": rows[cpu] if cpu else None,
                                "report_sha256": sha256(report)}
        log = directory / "ooc.log"
        if log.is_file():
            entry["vivado"] = {"rc": int((directory / "ooc.log.rc").read_text()) if (directory / "ooc.log.rc").is_file() else None,
                               "log_sha256": sha256(log), "log_bytes": log.stat().st_size,
                               "start": (directory / "ooc.log.start").read_text().strip() if (directory / "ooc.log.start").is_file() else "",
                               "end": (directory / "ooc.log.end").read_text().strip() if (directory / "ooc.log.end").is_file() else ""}
        out[name] = entry
    (WORK / "soc_prices.json").write_text(json.dumps(out, indent=1, sort_keys=True) + "\n")
    print(f"collect: {len(out)} variants")
    return 0


def main() -> int:
    command, names = sys.argv[1], sys.argv[2:]
    if command == "prepare":
        return command_prepare()
    if command == "export":
        return command_export(names)
    if command == "vivado-prep":
        return command_vivado_prep(names)
    if command == "collect":
        return command_collect()
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main())
