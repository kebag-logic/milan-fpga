#!/usr/bin/env python3
"""Scrub host paths from round 5's receipts, then write receipts/INDEX.md from the files present (lane 895 round 5):
each file's size and sha256, grouped by directory, with what each directory holds. The index is written after the
scrub, so every listed hash is the file's final bytes. Refuses a receipt over 200 KB."""
import hashlib
import sys
from pathlib import Path

R = Path('$MANAGEMENT/2026-09-23/895-a775/round5/receipts')
SUBS = [('/data-2/milan/tmp/895-a775/r5', '<scratch>'), ('$LANES/895r5sweep', '<sweep-clone>'), ('/data-2/milan/tmp/895-a775', '<scratch>'),
        ('/data-2/milan/tmp/895hw-a779', '<bench-scratch>'), ('$LANES/895-talker', '<tree>'),
        ('$MANAGEMENT', '<mgmt>'), ('$VALIDATION_TOOLS', '<tools>'),
        ('$VALIDATION_STORAGE/scratch', '<tools>'), ('$WORKSPACE_HOME/litex-milan', '<litex>'), ('$WORKSPACE_HOME/br-milan-rv32', '<sdk>'),
        ('$WORKSPACE_HOME', '<home>')]
WHAT = {
    'graders': "the analytic graders: head = flip_grade.py --check at both points, --selftest, load_grade.py --check and "
               "--selftest, tier_grid.py --point 1x1/1if, the pace table (pace.py) and the slice rule at the final head "
               "62298ab5; explore = the same at 91c3fc0e (round 4's head), at pace 9 with #894's AECP slot and TICK "
               "(the slice rule's 950 us), and on the scratch clone at the final analytic state",
    'ledger': "the ROM ledger on the worktree at b3a5ed99 with the 60.5 entry (committed as 8238156d): plat_ledger.py "
              "at every point and the fixture and both 8x8/2if harness arms (ledger.sh)",
    'fw': "commit 3's and commit 5's checks on the worktree: the Talker and SRP-composition arms, the 34 Talker plants "
          "at both interface counts, test_ctrl_memory.py with the 60.5 entry",
    'legs': "the CPU budget harness legs R5-* on a clean clone of b3a5ed99 (the final head's firmware): every arm at "
            "1x1/1if and 8x8/2if, arm A in five parts a point, merged and regraded as one leg; each build's "
            "executable sha256; summary.txt from legs_summary.py (verdicts, STATED lines, join intervals)",
    'costs': "the legs' measured costs by round 1's parsers (parts.py, eventcost.py, costs24.py) at both points, and "
             "at 1x1/1if without the largest legal command's group (the ordinary AECP record)",
    'gates': "the gate pass at 62298ab5: every run step of rtl-fast, rtl, docs and elaborate, each job on its own "
             "clean clone (run_wf.py; workflows/), verify_wf.py's table (verify-table.md), the lane gates (lane/), the "
             "harness at the head against the legs (harness/), the units' logs (units/), the docs-gates-1 run that "
             "failed on the lost SDK link (incident/), excerpts of the logs over 200 KB (excerpts/; large.txt)",
    'sweep': "the full Verilator sweep at 62298ab5 as four shard units (native-shards.py): each shard's spec, result "
             "and suite summary, the shard clones' trees after, and tsn_fuzz again with the pinned tsn-gen",
}
over = []
for f in sorted(R.rglob('*')):
    if not f.is_file() or f.name == 'INDEX.md':
        continue
    if f.stat().st_size > 200_000:
        over.append(f)
        continue
    try:
        t = f.read_text()
    except UnicodeDecodeError:
        continue
    u = t
    for a, b in SUBS:
        u = u.replace(a, b)
    if u != t:
        f.write_text(u)
if over:
    sys.exit('REFUSED: over 200 KB: ' + ', '.join(str(p.relative_to(R)) for p in over))
lines = ['# Receipts, lane 895 round 5 ([A775])', '',
         'Generated by round5/scripts/index.py from the files present, after the host-path scrub '
         '(placeholders: ' + ', '.join(sorted({b for _, b in SUBS})) + ').', '']
for d in sorted({p.parent for p in R.rglob('*') if p.is_file() and p.name != 'INDEX.md'}):
    rel = d.relative_to(R).as_posix() if d != R else '.'
    lines += [f'## {rel}', '', WHAT.get(rel, WHAT.get(rel.split('/')[0], '')), '', '| File | Bytes | sha256 |', '|---|---:|---|']
    for f in sorted(p for p in d.iterdir() if p.is_file() and p.name != 'INDEX.md'):
        lines.append(f'| {f.name} | {f.stat().st_size} | `{hashlib.sha256(f.read_bytes()).hexdigest()}` |')
    lines.append('')
(R / 'INDEX.md').write_text('\n'.join(lines))
print(f"INDEX.md: {sum(1 for p in R.rglob('*') if p.is_file() and p.name != 'INDEX.md')} files")
