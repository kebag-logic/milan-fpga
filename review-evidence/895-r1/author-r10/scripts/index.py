#!/usr/bin/env python3
"""Scrub host paths from round 10's receipts, then write receipts/INDEX.md from the files present (lane 895 round 10):
each file's size and sha256, grouped by directory, with what each directory holds. The index is written after the
scrub, and then checked: a second scrub changes no file, and every listed hash is the file's bytes. Refuses a receipt
over 200 KB."""
import hashlib
import sys
from pathlib import Path

R = Path('$MANAGEMENT/2026-09-23/895-a775/round10/receipts')
SUBS = [('/data-2/milan/tmp/895-a775/r10', '<scratch>'), ('/data-2/milan/tmp/895-a775', '<scratch>'),
        ('$LANES/895-talker', '<tree>'), ('$MANAGEMENT', '<mgmt>'),
        ('$VALIDATION_TOOLS', '<tools>'), ('$VALIDATION_STORAGE/scratch', '<tools>'), ('$WORKSPACE_HOME/litex-milan', '<litex>'),
        ('$WORKSPACE_HOME/br-milan-rv32', '<sdk>'), ('$LANES', '<lanes>'), ('$VALIDATION_STORAGE', '<data>'),
        ('/data-2/milan', '<data2>'), ('$WORKSPACE_HOME', '<home>')]
WHAT = {
    '.': "flip-226.log: flip_grade.py --check at 1x1/1if on an export of the head with the polls' base at 226 us in both "
         "tables (R835-4-S1): CTRL_LOOP_TX_MS 34 refused against the tx row's 34.02",
    'classes': "R836-4-F2: record_classes.py's CLI at the head over every preserved leg of rounds 8 and 9 at both points "
               "(record_classes-real.log, RESULT PASS, the dearest record of each class); survey-final = the corrected "
               "survey on those legs at each point (UNDER 0, every class measured); plants = class_evidence.py: arm B's "
               "aecp-fanout records by class with held with and without the command, and each planted control (an "
               "over-cost accepted SET_CONFIGURATION, an over-cost SET_STREAM_INFO) and the unplanted copies on the "
               "class grader, the corrected survey and round 8's survey (summary.md)",
    'talker': "R835-4-F1 on the worktree before its commit: the Talker arms (wt-arms.log, srp_talker.cpp 12 tests at each "
              "count) and plants.py talker-hold-off and the both-terms plant at 8x8/2if and 1x1/1if",
    'docs': "R836-4-F1 and R835-4-F2: superseded-hits-before.txt, every hit of each superseded figure before the "
            "documentation pass; superseded-inventory.md, every hit after it with its disposition",
    'identity': "image_sha.py lists at 056d619d and the head 1215bd82, and their comparison (552 of 552 identical)",
    'ledger-final': "the ROM ledger at the head 1215bd82 (ledger.sh on its clean clone): plat_ledger.py rc 0",
    'gates': "the gates at the head, each job on its own fresh clean clone: verify-raw.md (verify_wf.py), verify-table.md "
             "(verify_r10.py: the steps of jobs reading no changed path carried from round 9's table), campaigns.txt, "
             "every job's driver log, step rcs and tree after (workflows), the lane gates part a (lane)",
    'units': "each unit's log and rc (head and range first) and the dispatcher's record",
}


def scrub() -> list[Path]:
    """Scrub every text receipt; the files it changed."""
    changed = []
    for f in sorted(R.rglob('*')):
        if not f.is_file() or f.name == 'INDEX.md' or f.stat().st_size > 200_000:
            continue
        try:
            t = f.read_text()
        except UnicodeDecodeError:
            continue
        u = t
        for a, b in SUBS:
            u = u.replace(a, b)
        if u != t:
            f.write_text(u)
            changed.append(f)
    return changed


over = [f for f in R.rglob('*') if f.is_file() and f.stat().st_size > 200_000]
if over:
    sys.exit('REFUSED: over 200 KB: ' + ', '.join(str(p.relative_to(R)) for p in over))
scrub()
lines = ['# Receipts, lane 895 round 10 ([A775])', '',
         'Generated by round10/scripts/index.py from the files present, after the host-path scrub '
         '(placeholders: ' + ', '.join(sorted({b for _, b in SUBS})) + '), and checked after it: a second scrub '
         'changes no file and every hash below is its file\'s bytes.', '']
listed = {}
for d in sorted({p.parent for p in R.rglob('*') if p.is_file() and p.name != 'INDEX.md'}):
    rel = d.relative_to(R).as_posix() if d != R else '.'
    lines += [f'## {rel}', '', WHAT.get(rel, WHAT.get(rel.split('/')[0], '')), '', '| File | Bytes | sha256 |',
              '|---|---:|---|']
    for f in sorted(p for p in d.iterdir() if p.is_file() and p.name != 'INDEX.md'):
        h = hashlib.sha256(f.read_bytes()).hexdigest()
        listed[f] = h
        lines.append(f'| {f.name} | {f.stat().st_size} | `{h}` |')
    lines.append('')
(R / 'INDEX.md').write_text('\n'.join(lines))
again = scrub()
bad = [f for f, h in listed.items() if hashlib.sha256(f.read_bytes()).hexdigest() != h]
if again or bad:
    sys.exit(f'INDEX check FAILED: a second scrub changed {len(again)}, {len(bad)} hash(es) differ')
print(f'INDEX.md: {len(listed)} files, the scrub idempotent, every hash its file\'s bytes')
