#!/usr/bin/env python3
"""What differs between the final head's harness build and the measurement leg's (lane 895).

usage: compare_builds.py NEW_BUILD MEASURED_BUILD

The executables differ by LiteX's generation stamps, so this compares what the simulation runs: the linked image's
loadable bytes (objcopy -O binary), the generated SoC Verilog with its comments set aside (its date stamps and the
module-hierarchy listing LiteX prints in a block comment, whose order of siblings varies), the CSR map with its date
stamp set aside,
and every recorded build input. Exit 0 when the image bytes are identical and the Verilog and the CSR map differ in
no other line.
"""
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

new, old = (Path(p) for p in sys.argv[1:3])
STAMPS = ('// Date', '//  Auto-Generated by LiteX on', '# Auto-generated by LiteX')


def loadable(build: Path, out: Path) -> bytes:
    """The image's loadable bytes."""
    elf = next((build / 'image').glob('*.elf'))
    subprocess.run(['riscv32-buildroot-linux-gnu-objcopy', '-O', 'binary', str(elf), str(out)], check=True)
    return out.read_bytes()


def lines(path: Path) -> list[str]:
    """A generated file's lines but its date stamps."""
    return [line for line in path.read_text(errors='replace').splitlines() if not line.lstrip().startswith(STAMPS)]


ok = True
with tempfile.TemporaryDirectory() as tmp:
    a, b = loadable(new, Path(tmp) / 'a.bin'), loadable(old, Path(tmp) / 'b.bin')
same = a == b
ok &= same
print(f"image loadable bytes: {'IDENTICAL' if same else 'DIFFERENT'} ({len(a)} and {len(b)} B)")
def verilog(path: Path) -> str:
    """The Verilog without its comments: what elaborates."""
    text = re.sub(r'/\*.*?\*/', '', path.read_text(errors='replace'), flags=re.S)
    return re.sub(r'//[^\n]*', '', text)


same = verilog(new / 'gateware/sim.v') == verilog(old / 'gateware/sim.v')
ok &= same
print(f"gateware/sim.v: {'identical but its comments' if same else 'DIFFERENT beyond its comments'}")
same = lines(new / 'csr.csv') == lines(old / 'csr.csv')
ok &= same
print(f"csr.csv: {'identical but its date stamp' if same else 'DIFFERENT beyond its date stamp'}")
x, y = (json.loads((d / 'build.json').read_text()) for d in (new, old))
print('executables:', 'identical' if x['executable_sha256'] == y['executable_sha256'] else 'differ (the stamps)')
print('recorded inputs that differ:', sorted(k for k in x['inputs'] if x['inputs'][k] != y['inputs'].get(k)))
print('variant:', x.get('variant'), '/', y.get('variant'))
ok &= x.get('variant') == y.get('variant')
print('RESULT', 'PASS' if ok else 'FAIL')
sys.exit(0 if ok else 1)
