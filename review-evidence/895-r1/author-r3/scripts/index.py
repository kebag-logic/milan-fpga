#!/usr/bin/env python3
"""Scrub host paths from round 3's receipts, then write receipts/INDEX.md from the files present (lane 895 round 3):
each file's size and sha256, grouped by directory, with what each directory holds. The index is written after the
scrub, so every listed hash is the file's final bytes. Refuses a receipt over 200 KB."""
import hashlib
import sys
from pathlib import Path

R = Path('$MANAGEMENT/2026-09-23/895-a775/round3/receipts')
SUBS = [('/data-2/milan/tmp/895-a775/r3', '<scratch>'), ('/data-2/milan/tmp/895-a775', '<scratch>'),
        ('/data-2/milan/tmp/895hw-a779', '<bench-scratch>'), ('$LANES/895-talker', '<tree>'),
        ('$MANAGEMENT', '<mgmt>'), ('$VALIDATION_TOOLS', '<tools>'),
        ('$VALIDATION_STORAGE/scratch', '<tools>'), ('$WORKSPACE_HOME/litex-milan', '<litex>'), ('$WORKSPACE_HOME/br-milan-rv32', '<sdk>'),
        ('$WORKSPACE_HOME', '<home>')]
WHAT = {
    'cap': 'the first cap probe at the sync merge cd6d79b6 (cap_probe.py, RV32 stand-ins)',
    'boot': 'the split boot simulation at 1x1/1if, 8x8/1if and 8x8/2if, at the merge and at the head (clean clones)',
    'plants': 'the five #905 Talker plants at 8x8/2if and 1x1/1if; the control campaign cut to the 80 mutants a '
              'MAAP-adapter or mailbox-driver change reaches',
    'graders': 'load_grade.py and flip_grade.py at the new base 084cf7a8, at fa3f31ee and at the final head, and the '
               'base-against-head diffs',
    'ledger': 'the ROM ledger: plat_ledger.py and the fixture and harness-arm images at the base, the merge, the '
              "superseded design and the final firmware",
    'srptx': "srptx's licence and hold scenarios at the base, the merge and the head; the [SID] check, its capture "
             'plant and its code arm; large captures by sha256 and size (large.sha256)',
    'fw': "the firmware arms on the final head's clean clone, and the full suite; after the ruling, the arms on "
          "cd863d40's firmware, the coverage check that found the names patch's drop at a9fd4415, the coverage "
          "written, and the full suite at cf5b1441",
    'legs': 'the CPU budget harness legs S-* at cf5b1441 (every arm at both points; arm A in parts, merged), and the '
            "a9fd4415 legs that failed (Q-N8, Q-W1) and round 2's R3-W1 for comparison",
    'trace': "the trace analyses: the 8x8/2if MAAP poll's data cache conflict (calls, spans, the loop's lines by "
             'image) and the 1x1/1if build-one pass (its early passes at six commits, its waits, the images\' layout)',
}
over = []
for f in sorted(R.rglob('*')):
    if not f.is_file() or f.name == 'INDEX.md':
        continue
    if f.stat().st_size > 200_000:
        over.append(f)
        continue
    try:
        t = f.read_text()
    except UnicodeDecodeError:
        continue
    u = t
    for a, b in SUBS:
        u = u.replace(a, b)
    if u != t:
        f.write_text(u)
if over:
    sys.exit('REFUSED: over 200 KB: ' + ', '.join(str(p.relative_to(R)) for p in over))
lines = ['# Receipts, lane 895 round 3 ([A775])', '',
         'Generated by round3/scripts/index.py from the files present, after the host-path scrub '
         '(placeholders: ' + ', '.join(sorted({b for _, b in SUBS})) + ').', '']
for d in sorted({p.parent for p in R.rglob('*') if p.is_file() and p.name != 'INDEX.md'}):
    rel = d.relative_to(R).as_posix() if d != R else '.'
    lines += [f'## {rel}', '', WHAT.get(rel, ''), '', '| File | Bytes | sha256 |', '|---|---:|---|']
    for f in sorted(p for p in d.iterdir() if p.is_file() and p.name != 'INDEX.md'):
        lines.append(f'| {f.name} | {f.stat().st_size} | `{hashlib.sha256(f.read_bytes()).hexdigest()}` |')
    lines.append('')
(R / 'INDEX.md').write_text('\n'.join(lines))
print(f"INDEX.md: {sum(1 for p in R.rglob('*') if p.is_file() and p.name != 'INDEX.md')} files")
