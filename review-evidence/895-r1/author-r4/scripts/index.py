#!/usr/bin/env python3
"""Scrub host paths from round 4's receipts, then write receipts/INDEX.md from the files present (lane 895 round 4):
each file's size and sha256, grouped by directory, with what each directory holds. The index is written after the
scrub, so every listed hash is the file's final bytes. Refuses a receipt over 200 KB."""
import hashlib
import sys
from pathlib import Path

R = Path('$MANAGEMENT/2026-09-23/895-a775/round4/receipts')
SUBS = [('/data-2/milan/tmp/895-a775/r4', '<scratch>'), ('/data-2/milan/tmp/895-a775', '<scratch>'),
        ('/data-2/milan/tmp/895hw-a779', '<bench-scratch>'), ('$LANES/895-talker', '<tree>'),
        ('$MANAGEMENT', '<mgmt>'), ('$VALIDATION_TOOLS', '<tools>'),
        ('$VALIDATION_STORAGE/scratch', '<tools>'), ('$WORKSPACE_HOME/litex-milan', '<litex>'), ('$WORKSPACE_HOME/br-milan-rv32', '<sdk>'),
        ('$WORKSPACE_HOME', '<home>')]
WHAT = {
    'merge': "the sync merge's three-way check of load_grade.py's cost tables (base 084cf7a8, this branch, #902) and "
             "the composed tables against #902's; the planted-defect anchor check on the merge (anchors3.py)",
    'ledger': "the ROM ledger: plat_ledger.py and the fixture and harness-arm images at #902's head 5b264bf2 "
              "(ledgerT, a clean clone) and on the composed tree (ledgerM)",
    'graders': "flip_grade.py --check --point 1x1/1if, tier_grid.py and load_grade.py --check at #902's head and on "
               "the composed tree; #902's tree with the composed load_grade.py alone; the scratch check of the "
               "rule's pace (9 ms) with CTRL_LOOP_TX_MS 34",
    'fw': "the firmware arms on the merged worktree (the first run's compile refusal, then PASS), the coverage "
          "written on it, the two ledger units",
    'legs': "the CPU budget harness legs R4-* at the merge a93fceae (clean clone): every arm at 1x1/1if and 8x8/2if, "
            "arm A in five parts a point, merged and regraded as one leg",
    'costs': "the legs' measured costs by round 1's parsers (parts.py, eventcost.py, costs24.py, aecp_kinds.py) at "
             "both points, and the composed tables against them",
}
over = []
for f in sorted(R.rglob('*')):
    if not f.is_file() or f.name == 'INDEX.md':
        continue
    if f.stat().st_size > 200_000:
        over.append(f)
        continue
    try:
        t = f.read_text()
    except UnicodeDecodeError:
        continue
    u = t
    for a, b in SUBS:
        u = u.replace(a, b)
    if u != t:
        f.write_text(u)
if over:
    sys.exit('REFUSED: over 200 KB: ' + ', '.join(str(p.relative_to(R)) for p in over))
lines = ['# Receipts, lane 895 round 4 ([A775])', '',
         'Generated by round4/scripts/index.py from the files present, after the host-path scrub '
         '(placeholders: ' + ', '.join(sorted({b for _, b in SUBS})) + ').', '']
for d in sorted({p.parent for p in R.rglob('*') if p.is_file() and p.name != 'INDEX.md'}):
    rel = d.relative_to(R).as_posix() if d != R else '.'
    lines += [f'## {rel}', '', WHAT.get(rel, WHAT.get(rel.split('/')[0], '')), '', '| File | Bytes | sha256 |', '|---|---:|---|']
    for f in sorted(p for p in d.iterdir() if p.is_file() and p.name != 'INDEX.md'):
        lines.append(f'| {f.name} | {f.stat().st_size} | `{hashlib.sha256(f.read_bytes()).hexdigest()}` |')
    lines.append('')
(R / 'INDEX.md').write_text('\n'.join(lines))
print(f"INDEX.md: {sum(1 for p in R.rglob('*') if p.is_file() and p.name != 'INDEX.md')} files")
