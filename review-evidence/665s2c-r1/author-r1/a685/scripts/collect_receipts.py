#!/usr/bin/env python3
"""Copy the lane's receipts into the evidence packet, host paths replaced, and index what is present.

usage: collect_receipts.py RECEIPTS
Each arm's graded results (table.md, results.json, every group's script and grade; the group logs of
the arms LOG_ARMS names, the others listed by digest), each
build's build.json, the out-of-context and Yosys reports and the driver logs are copied. A file over
200 KB is not copied: MANIFEST.json records its name, size and sha256 instead. Text files have the
checkout, scratch, LiteX and SDK paths replaced by <checkout>, <scratch>, $LITEX and $SDK.
INDEX.md lists every file present with its size and sha256, generated from the directory itself.
"""
import hashlib
import json
import shutil
import sys
from pathlib import Path

R = Path(sys.argv[1])
SCRATCH = Path('$VALIDATION_STORAGE/665s2c-a685')
LIMIT = 200 * 1024
SUBST = (('$LANES/665-s2c-icache', '<checkout>'), ('$LANES/665s2c-a685-shard', '<shard-clone>'),
         (str(SCRATCH), '<scratch>'), ('$WORKSPACE_HOME/.local/share/containers', '$CONTAINERS'),
         ('$WORKSPACE_HOME/litex-milan', '$LITEX'), ('$WORKSPACE_HOME/br-milan-rv32', '$SDK'),
         ('$WORKSPACE_HOME/Xilinx', '$XILINX'), ('$VALIDATION_TOOLS', '$TOOLS'), ('$WORKSPACE_HOME', '~'))
skipped = []
logs_listed = []
#: Arms whose group logs are copied (under 200 KB each); every other arm's logs are listed by digest.
LOG_ARMS = ('P1-64x1', 'P8-64x1', 'C1-asbuilt-64x1', 'C1-slow-64x1', 'C1-shutdown-64x1', 'P1-xip-64x1', 'P8-xip-64x1')


def put(src: Path, dst: Path) -> None:
    data = src.read_bytes()
    try:
        text = data.decode()
        for old, new in SUBST:
            text = text.replace(old, new)
        data = text.encode()
    except UnicodeDecodeError:
        pass
    if len(data) > LIMIT:
        skipped.append(dict(file=str(dst.relative_to(R)), bytes=len(data), sha256=hashlib.sha256(data).hexdigest()))
        return
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_bytes(data)


for build in sorted((SCRATCH / 'builds').iterdir()):
    results = build / 'results'
    if not (build / 'build.json').exists():
        continue
    put(build / 'build.json', R / 'builds' / f'{build.name}.build.json')
    if build.joinpath('soc.json').exists():
        put(build / 'soc.json', R / 'builds' / f'{build.name}.soc.json')
    if results.is_dir():
        for f in sorted(results.iterdir()):
            if f.suffix == '.log' and build.name not in LOG_ARMS:
                data = f.read_bytes()
                logs_listed.append(dict(file=f'runs/{build.name}/{f.name}', bytes=len(data),
                                        sha256=hashlib.sha256(data).hexdigest()))
            elif f.suffix in ('.md', '.json', '.txt', '.log'):
                put(f, R / 'runs' / build.name / f.name)
for log in sorted((SCRATCH / 'logs').glob('*.log')):
    put(log, R / 'drivers' / log.name)
for run_dir in sorted((SCRATCH / 'ooc').glob('*/*')):
    if run_dir.is_dir():
        for name in ('sources.sha256', 'ooc.tcl', 'synth_util.rpt', 'route_util.rpt', 'timing.rpt', 'route.rpt',
                     'synth_hier.rpt', 'rc'):
            if (run_dir / name).exists():
                put(run_dir / name, R / 'ooc' / run_dir.parent.name / run_dir.name / name)
for log in sorted((SCRATCH / 'ooc').glob('*.log')):
    put(log, R / 'ooc' / log.name)
for f in sorted((SCRATCH / 'yosys').glob('*.json')):
    put(f, R / 'yosys' / f.name)
for f in R.rglob('*'):
    # Files copied by hand (gate logs, the export receipts) get the same path replacement.
    if f.is_file() and f.name not in ('INDEX.md', 'MANIFEST.json'):
        try:
            text = f.read_text()
        except UnicodeDecodeError:
            continue
        clean = text
        for old, new in SUBST:
            clean = clean.replace(old, new)
        if clean != text:
            f.write_text(clean)
(R / 'MANIFEST.json').write_text(json.dumps(dict(not_copied_over_200KB=skipped, group_logs_listed=logs_listed),
                                            indent=1) + '\n')
rows = []
for f in sorted(p for p in R.rglob('*') if p.is_file() and p.name != 'INDEX.md'):
    data = f.read_bytes()
    rows.append(f'| `{f.relative_to(R)}` | {len(data):,} | `{hashlib.sha256(data).hexdigest()[:16]}` |')
(R / 'INDEX.md').write_text('# Receipts index\n\nGenerated by `collect_receipts.py` from the files present.\n\n'
                            '| File | Bytes | SHA-256, first 16 |\n|---|---:|---|\n' + '\n'.join(rows) + '\n')
print(f'{len(rows)} files indexed, {len(skipped)} over 200 KB recorded in MANIFEST.json')
