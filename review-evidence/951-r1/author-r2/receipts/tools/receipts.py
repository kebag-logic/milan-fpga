#!/usr/bin/env python3
"""receipts.py OUT: copy, condense and sanitise the round's receipts into OUT/receipts, then write OUT/receipts/INDEX.md
from the files present (path, bytes, sha256 prefix, first line). Host paths are replaced by placeholders (<scratch>,
<lane>, <sdk>, <litex>, <tools>, <mgmt>, <home>, <tmp>), then the management privacy filter (the repository's own scrub
rules and the private supplement) runs over every file. A file over 200 KB is refused: condense it first."""
import hashlib
import re
import shutil
import subprocess
import sys
from pathlib import Path

S = Path('<scratch>')
out = Path(sys.argv[1]).resolve() / 'receipts'
sys.path.insert(0, '<mgmt>/2026-09-23')
import privacy  # noqa: E402

PATHS = [('<scratch>', '<scratch>'), ('<lane>', '<lane>'),
         ('<sdk>', '<sdk>'), ('<litex>', '<litex>'), ('<tools>', '<tools>'),
         ('<tools>', '<tools>'), ('<mgmt>', '<mgmt>'),
         ('<tools>', '<tools>'), ('<lanes>', '<lanes>'), ('<home>', '<home>'),
         ('<tmp>/', '<tmp>/')]


def sanitise(text: str) -> str:
    for a, b in PATHS:
        text = text.replace(a, b)
    return privacy.scrub_redact(text.encode()).decode()


def put(rel: str, text: str) -> None:
    p = out / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(sanitise(text))


def keep(rel: str, src: Path, filt=None) -> None:
    text = src.read_text(errors='replace')
    put(rel, filt(text) if filt else text)


def lines(pattern: str, text: str, head: str = '') -> str:
    rx = re.compile(pattern)
    return head + ''.join(l + '\n' for l in text.splitlines() if rx.search(l))


def run(*a: str, cwd: Path | None = None) -> str:
    return subprocess.run(a, cwd=cwd, capture_output=True, text=True).stdout


if out.exists():
    shutil.rmtree(out)
out.mkdir(parents=True)
L = Path('<lane>')
ROUND = sys.argv[3] if len(sys.argv) > 3 else 'round 1'
SPEC = S / 'bin' / (sys.argv[2] if len(sys.argv) > 2 else 'receipts_spec.py')
exec(SPEC.read_text())  # the round's file list: calls keep/put/lines/run

too_big = [p for p in out.rglob('*') if p.is_file() and p.stat().st_size > 200_000]
assert not too_big, f'over 200 KB: {too_big}'
rows = []
for p in sorted(x for x in out.rglob('*') if x.is_file()):
    data = p.read_bytes()
    first = (data.decode(errors='replace').splitlines() or [''])[0][:110].replace('|', '\\|')
    rows.append(f'| `{p.relative_to(out)}` | {len(data)} | `{hashlib.sha256(data).hexdigest()[:16]}` | {first} |')
(out / 'INDEX.md').write_text(
    f'# Receipts index (#951 {ROUND})\n\nGenerated by receipts.py from the files present, after sanitising (host paths '
    'replaced by `<scratch>`, `<lane>`, `<sdk>`, `<litex>`, `<tools>`, `<mgmt>`, `<home>`, `<tmp>`). Each row: path, '
    'size, sha256 prefix, first line.\n\n| File | Bytes | sha256 | First line |\n|---|---:|---|---|\n' +
    '\n'.join(rows) + '\n')
print(f'{len(rows)} receipts under {out}')
