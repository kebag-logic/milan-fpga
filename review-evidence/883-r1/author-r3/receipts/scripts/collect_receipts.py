#!/usr/bin/env python3
"""collect_receipts.py <out>: copy the lane's receipts into <out>/receipts, every text file with host paths and
account names masked; a file over 200 KB is not copied, and its SHA-256 and size (of the original) go to that
directory's LARGE-FILES.sha256. Then writes <out>/receipts/INDEX.md from the files present (path, bytes, SHA-256
prefix). The sources are fixed below; nothing is generated here except the masks and the index."""
import hashlib
import re
import shutil
import sys
from pathlib import Path

S = Path("<scratch>")
OUT = Path(sys.argv[1]) / "receipts"
LIMIT = 200 * 1024
MASK = (
    ("<scratch>", "<scratch>"), ("<lane>", "<lane>"),
    ("<litex>", "<litex>"), ("<xilinx>", "<xilinx>"),
    ("<mgmt>", "<mgmt>"), ("<tools>", "<tools>"),
    ("<scratch-root>", "<scratch-root>"), ("<lanes>", "<lanes>"), ("<tmp-root>", "<tmp-root>"),
    ("<containers>", "<containers>"), ("<home>", "<home>"),
    ("<vivado-lock>", "<vivado-lock>"), ("<act-slots>", "<act-slots>"),
)
_GIT_USER = "hacker" + "man-kl"          # assembled, so this file never spells an account name
_OWNER = "Mister" + "-M-" + "alt"
PATTERNS = ((re.compile(rf"\b{_GIT_USER}\b"), "<git-user>"), (re.compile(rf"\b{_OWNER}\b(?!/)"), "<owner>"),
            (re.compile(r"\balex\b"), "<user>"))


def mask(text: str) -> str:
    for a, b in MASK:
        text = text.replace(a, b)
    for pat, rep in PATTERNS:
        text = pat.sub(rep, text)
    return text


def put(src: Path, dest_dir: Path, name: str | None = None) -> None:
    dest_dir.mkdir(parents=True, exist_ok=True)
    data = src.read_bytes()
    name = name or src.name
    if len(data) > LIMIT:
        with open(dest_dir / "LARGE-FILES.sha256", "a") as large:
            large.write(f"{hashlib.sha256(data).hexdigest()}  {len(data)}  {name}\n")
        return
    try:
        text = data.decode()
    except UnicodeDecodeError:
        shutil.copyfile(src, dest_dir / name)
        return
    (dest_dir / name).write_text(mask(text))


def tree(src: Path, dest: Path, pattern: str = "*") -> None:
    if src.is_dir():
        for path in sorted(src.glob(pattern)):
            if path.is_file():
                put(path, dest)


def main() -> None:
    shutil.rmtree(OUT, ignore_errors=True)
    OUT.mkdir(parents=True)
    tree(S / "runs", OUT / "legs")
    tree(S / "viv/logs", OUT / "vivado/chain")
    for d in ("w/ax7101/gateware", "w/ax7101-AltSpreadLogic_high", "w/ax7101-ExtraTimingOpt", "w/ax7101-ooc",
              "w8/ax8x8-ooc", "w8/ax8x8-rtl"):
        tree(S / "viv" / d, OUT / "vivado" / d.replace("/", "__"), "*.rpt")
        tree(S / "viv" / d, OUT / "vivado" / d.replace("/", "__"), "baseline.log.rc")
        tree(S / "viv" / d, OUT / "vivado" / d.replace("/", "__"), "*.json")
        tree(S / "viv" / d, OUT / "vivado" / d.replace("/", "__"), "*.tsv")
        if (S / "viv" / d / "baseline.log").exists():
            put(S / "viv" / d / "baseline.log", OUT / "vivado" / d.replace("/", "__"))
    for p in sorted((S / "viv/paths").glob("*")) if (S / "viv/paths").exists() else []:
        tree(p, OUT / "vivado/paths" / p.name)
    tree(S / "gate", OUT / "gate")
    for g in sorted(S.glob("gates-*")):
        tree(g, OUT / g.name)
        tree(g / "runner", OUT / g.name / "runner")
        tree(g / "logs", OUT / g.name / "logs")
        tree(g / "attempt1", OUT / g.name / "attempt1")
    for g in sorted(S.glob("sweep-*")):
        for shard in sorted(g.glob("shard-*")):
            tree(shard, OUT / g.name / shard.name)
            tree(shard / "logs", OUT / g.name / shard.name / "logs")
    for g in sorted(S.glob("legs-*")):
        tree(g, OUT / g.name)
        tree(g / "logs", OUT / g.name / "logs")
    tree(S / "misc", OUT / "misc")
    tree(S / "mutant-cppidiom-f1", OUT / "mutant-cppidiom-f1")
    for f in ("sweep-6c6706e5/tally.log", "sweep-6c6706e5/tally.rc", "sweep-6c6706e5.launch.json", "sweep-spec.json",
              "verify-final.txt", "verify-final.rc"):
        if (S / f).exists():
            put(S / f, OUT / "sweep-6c6706e5" if f.startswith("sweep-6c") else OUT / "misc")
    for f in ("set_measured.py", "sweep_spec.py", "sweep_launcher.py", "gate_launcher.py", "legs_launcher.py",
              "digest_diag.py"):
        if (S / "scripts" / f).exists():
            put(S / "scripts" / f, OUT / "scripts")
    for f in ("run_wf.py", "verify_wf.py", "not_run.json", "wf_all.sh", "unit.sh", "make_clone.sh", "chain1.sh",
              "chain8.sh", "chain_ooc1.sh", "viv.sh", "paths.sh", "export_shape.sh", "dir_prep.py", "cut_rtl.py",
              "collect_receipts.py", "env.sh"):
        if (S / "scripts" / f).exists():
            put(S / "scripts" / f, OUT / "scripts")
    rows = ["# Receipts index (generated by scripts/collect_receipts.py from the files present)", "",
            "| File | Bytes | sha256 |", "|---|---:|---|"]
    for path in sorted(p for p in OUT.rglob("*") if p.is_file() and p.name != "INDEX.md"):
        rows.append(f"| `{path.relative_to(OUT).as_posix()}` | {path.stat().st_size} | "
                    f"`{hashlib.sha256(path.read_bytes()).hexdigest()[:16]}` |")
    (OUT / "INDEX.md").write_text("\n".join(rows) + "\n")
    print(f"index: {len(rows) - 4} files")


if __name__ == "__main__":
    main()
