#!/usr/bin/env python3
"""Copy the sweep's shard logs into receipts/sweep/, recording any file over 200 KB by size and sha256
instead of copying it; replace host paths in every receipt with placeholders (moving any receipt over
200 KB out to the work directory, recorded the same way); then write receipts/INDEX.md from the files
present.  usage: collect_receipts.py"""
import hashlib
from pathlib import Path

OUT = Path('$MANAGEMENT/2026-09-23/665s1-a680l')
WORK = Path('$VALIDATION_STORAGE/scratch/665s1-a680l-work')
RECEIPTS = OUT / 'receipts'
SWEEP = WORK / 'sweep-c3ba2b26'
LIMIT = 200 * 1024
#: Longest first, so a path is replaced by its most specific placeholder.
PLACEHOLDERS = [
    (str(OUT), '<out>'), (str(WORK), '<work>'), ('$MANAGEMENT/2026-09-23', '<management>'),
    ('$LANES/665s1-a680l-shard', '<shard-clone>'), ('$LANES/665-s1-faces', '<checkout>'),
    ('$VALIDATION_STORAGE/scratch', '<scratch>'), ('$WORKSPACE_HOME/litex-milan', '<litex-tree>'),
    ('$WORKSPACE_HOME/br-milan-rv32', '<rv32-sdk>'), ('$VALIDATION_TOOLS', '<tools>'), ('$WORKSPACE_HOME', '<home>'),
]


def redact(text: str) -> str:
    """The text with every host path replaced by its placeholder."""
    for path, name in PLACEHOLDERS:
        text = text.replace(path, name)
    return text


def record(data: bytes, rel: Path, large: list[str]) -> None:
    """One file over the limit, recorded by digest and size."""
    large.append(f'{hashlib.sha256(data).hexdigest()}  {len(data)}  {rel}')


def main() -> int:
    """Copy the sweep, redact every receipt, then write the index."""
    large: list[str] = []
    for src in sorted(x for x in SWEEP.rglob('*') if x.is_file()):
        dst = RECEIPTS / 'sweep' / SWEEP.name / src.relative_to(SWEEP)
        data = src.read_bytes()
        if len(data) > LIMIT:
            record(data, dst.relative_to(RECEIPTS), large)
            continue
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text(redact(data.decode(errors='replace')))
    for f in sorted(p for p in RECEIPTS.rglob('*') if p.is_file() and p.name not in ('INDEX.md', 'large-files.txt')):
        data = f.read_bytes()
        if len(data) > LIMIT:
            record(data, f.relative_to(RECEIPTS), large)
            moved = WORK / 'large-receipts' / f.relative_to(RECEIPTS)
            moved.parent.mkdir(parents=True, exist_ok=True)
            f.rename(moved)
            continue
        text = data.decode(errors='replace')
        if redact(text) != text:
            f.write_text(redact(text))
    (RECEIPTS / 'large-files.txt').write_text('# sha256  bytes  path (not copied: over 200 KB)\n'
                                              + ''.join(f'{line}\n' for line in large))
    rows = [f'| `{f.relative_to(RECEIPTS)}` | {f.stat().st_size} | `{hashlib.sha256(f.read_bytes()).hexdigest()}` |'
            for f in sorted(p for p in RECEIPTS.rglob('*') if p.is_file() and p.name != 'INDEX.md')]
    (RECEIPTS / 'INDEX.md').write_text('# Receipts index (generated by probes/collect_receipts.py from the files '
                                       'present)\n\n| File | Bytes | sha256 |\n|---|---:|---|\n' + '\n'.join(rows) + '\n')
    print(f'{len(rows)} files indexed, {len(large)} recorded as large')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
