#!/usr/bin/env python3
"""Collect the lane's receipts into the output directory and write an index generated from the files present.

usage: collect.py
Copies each receipt (a file at most LIMIT bytes, with the scratch prefix replaced by <tmp>); a larger file is
recorded by its sha256 and size in LARGE.txt instead. INDEX.md lists every file under receipts/ with its size and
sha256, and each log's HEAD and rc lines where it has them.
"""
import hashlib
import shutil
from pathlib import Path

LIMIT = 200 * 1024
TMP = '$VALIDATION_STORAGE/665s5-a702'
HOME = '$WORKSPACE_HOME'
OUT = Path('$MANAGEMENT/2026-09-23/665s5-a702/receipts')
#: The graded runs: the product clock's four at the head (run, then regrade at the final head), and the four
#: 50 MHz runs of History, regraded at 3c514839.
RUNS = {'runs': ('hr-1x1-idle', 'hr-1x1-ans', 'hr-8x8-idle', 'hr-8x8-ans'),
        'history': ('hb-1x1-idle-50', 'hb-1x1-ans-50', 'hb-8x8-idle-50', 'hb-8x8-ans-50')}
GATES = ('gates3', 'gates3/docs')


def scrub(text: str) -> str:
    """The scratch and home prefixes replaced, so no host path is in a receipt."""
    return (text.replace(TMP, '<tmp>').replace('$LANES/665-s5-hooks', '<lane>')
            .replace('$VALIDATION_STORAGE', '<data>').replace(HOME, '<home>'))


def put(src: Path, dest: Path, large: list[str]) -> None:
    """One receipt: copied (scrubbed, when text) if small enough, else recorded by digest."""
    if not src.is_file():
        return
    data = src.read_bytes()
    try:
        text = scrub(data.decode())
        data = text.encode()
    except UnicodeDecodeError:
        pass
    if len(data) > LIMIT:
        large.append(f'{dest.relative_to(OUT)}  {len(data)} B  sha256 {hashlib.sha256(data).hexdigest()}')
        return
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_bytes(data)


def main() -> int:
    shutil.rmtree(OUT, ignore_errors=True)
    OUT.mkdir(parents=True)
    large: list[str] = []
    tmp = Path(TMP)
    for kind, runs in RUNS.items():
        for run in runs:
            name = run.split('-', 1)[1]
            base = OUT / kind / name
            log = 'hr' + name if kind == 'runs' else 'h' + name
            put(tmp / 'logs' / f'{log}.log', base / 'run.log', large)
            put(tmp / 'logs' / f'regrade-{log}.log', base / 'regrade.log', large)
            put(tmp / run / 'results' / 'table.md', base / 'table.md', large)
            put(tmp / run / 'results' / 'results.json', base / 'results.json', large)
            put(tmp / run / 'build.json', base / 'build.json', large)
    for log in sorted((tmp / 's-plants' / 'logs').glob('*.log')):
        put(log, OUT / 'plants' / log.name, large)
    for log in sorted((tmp / 'merge').glob('*.log')):
        put(log, OUT / 'merge' / log.name, large)
    for name in ('table.md', 'results.json'):
        put(tmp / 'hm-1x1-idle' / 'results' / name, OUT / 'merge' / name, large)
    put(tmp / 'hm-1x1-idle' / 'build.json', OUT / 'merge' / 'build.json', large)
    for gates in GATES:
        for log in sorted((tmp / gates).glob('*')):
            put(log, OUT / gates.replace('gates3', 'gates') / log.name, large)
    (OUT / 'LARGE.txt').write_text('Receipts over 200 KB, recorded by digest instead of copied:\n\n'
                                   + '\n'.join(large or ['none']) + '\n')
    rows = ['# Receipts', '', 'Generated by collect.py from the files present. Paths under the scratch directory '
            'read `<tmp>`.', '', '| File | Bytes | sha256 | HEAD | rc |', '|---|---:|---|---|---|']
    for path in sorted(p for p in OUT.rglob('*') if p.is_file() and p.name != 'INDEX.md'):
        data = path.read_bytes()
        text = data.decode(errors='replace')
        head = next((ln.split()[1][:12] for ln in text.splitlines() if ln.startswith('HEAD ')), '')
        rcs = [ln.strip() for ln in text.splitlines() if ln.strip().startswith(('rc=', 'rerun rc=', 'regrade rc='))]
        rows.append(f'| `{path.relative_to(OUT)}` | {len(data)} | `{hashlib.sha256(data).hexdigest()[:16]}` | '
                    f'{head} | {", ".join(rcs)} |')
    (OUT / 'INDEX.md').write_text('\n'.join(rows) + '\n')
    print(f'{len(rows) - 6} receipts, {len(large)} recorded by digest')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
