#!/usr/bin/env python3
"""gen_index.py <dir>: write <dir>/INDEX.md from the files present under <dir>: path,
bytes, sha256, and for gate logs the command, start and rc read from the log itself."""
import hashlib, re, sys
from pathlib import Path
root = Path(sys.argv[1])
rows = []
for p in sorted(x for x in root.rglob("*") if x.is_file() and x.name != "INDEX.md"):
    data = p.read_bytes()
    note = ""
    if p.suffix == ".log":
        text = data.decode(errors="replace")
        cmd = re.search(r"^## cmd (.*)$", text, re.M)
        end = re.search(r"^## end (\S+) rc (\d+)$", text, re.M)
        if cmd:
            note = f"`{cmd.group(1)}`"
        if end:
            note += f"; rc {end.group(2)}, ended {end.group(1)}"
    elif p.suffix == ".rc":
        note = f"rc {data.decode().strip()}"
    rows.append(f"| `{p.relative_to(root)}` | {len(data)} | `{hashlib.sha256(data).hexdigest()}` | {note} |")
out = ["# Round-2 receipts index", "",
       f"Generated by `bin/gen_index.py` from the {len(rows)} files present in this directory.",
       "Host paths in published copies are replaced by `<scratch>`, `<lane>`, `<tools>`, `<home>`.",
       "", "| file | bytes | sha256 | gate command; rc (from the file) |", "|---|---|---|---|"]
(root / "INDEX.md").write_text("\n".join(out + rows) + "\n")
print(f"INDEX.md: {len(rows)} files")
