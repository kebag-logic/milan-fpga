#!/usr/bin/env python3
"""Write RECEIPTS-INDEX.md from the files present under an output directory: path, bytes and SHA-256 each.

Usage: python3 -I make-index.py <output-dir>
"""

import hashlib
import sys
from pathlib import Path


def main() -> int:
    """List every file but the index itself, sorted by path."""
    root = Path(sys.argv[1])
    rows = []
    for path in sorted(p for p in root.rglob("*") if p.is_file() and p.name != "RECEIPTS-INDEX.md"):
        data = path.read_bytes()
        rows.append("| `" + path.relative_to(root).as_posix() + "` | " + str(len(data)) + " | `"
                    + hashlib.sha256(data).hexdigest() + "` |")
    root.joinpath("RECEIPTS-INDEX.md").write_text(
        "# Receipts index\n\nGenerated by `tools/make-index.py` from the files present; "
        + str(len(rows)) + " files.\n\n| file | bytes | sha256 |\n|---|---|---|\n" + "\n".join(rows) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
