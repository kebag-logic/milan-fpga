#!/usr/bin/env python3
"""Read and challenge the exact generated workflow without editing tracked files."""
import copy
import json
from pathlib import Path
import sys
sys.dont_write_bytecode = True
repo = Path(sys.argv[1]).resolve()
sys.path.insert(0, str(repo / "scripts"))
import ci_events as c
import ci_gate_workflows as g
p = c.parse_world(c.read_tree(repo))
base = c.check(p)
assert not base.findings, base.findings
print("baseline", base.checked, "items", len(base.findings), "findings")
for name in g.TEMPLATES:
    assert (repo / ".github/workflows" / (name + ".yml")).read_text() == g.rendered(name, g.load_template(repo, name))
    print("generated bytes match", name)
semantic = c.project_gate_templates(p, c.Contract())
for name, mutate, expected in c._private_interpreter_arms():
    w = copy.deepcopy(semantic)
    mutate(w)
    result = c.check(w)
    hits = [x for x in result.findings if expected in x]
    assert hits, (name, result.findings)
    print("CAUGHT", name, json.dumps(hits))
for jid in ("elaborate-gates-0", "elaborate-gates-1"):
    w = copy.deepcopy(p)
    steps = w[c.ELABORATE]["jobs"][jid]["steps"]
    steps[:] = [s for s in steps if s.get("name") != "Put a job-private Python environment on PATH"]
    result = c.Contract()
    c.check_generated_workflow(w, result, "elaborate")
    assert result.findings
    print("CAUGHT generated leg deletion", jid, json.dumps(result.findings))
print("PASS: three specified semantic mutations and independent deletion in either generated leg are refused")
