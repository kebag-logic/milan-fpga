#!/usr/bin/env python3
"""Scratch (M8a-1 evidence): normalized digests of two shipping exports.

Normalization, and nothing else: the LiteX generation timestamp lines, the
export's own output directory, the Verilog banner's Date line and LiteX's
comment-only hierarchy tree (one /* */ block, whose order varies between
runs). litex.log is a run log and is not compared.
"""
import hashlib
import re
import sys
from pathlib import Path

def normal(path: Path, root: Path) -> bytes:
    data = path.read_bytes()
    if path.suffix in {".init", ".bin"}:
        return data
    text = data.decode()
    text = text.replace(str(root), "<OUT>")
    text = re.sub(r"(?mi)^.*Auto-generated by LiteX.* on \d{4}-\d\d-\d\d .*$", "<STAMP>", text)
    if path.suffix == ".v":
        text, dates = re.subn(r"(?m)^// Date       : .*$", "<DATE>", text)
        text, trees = re.subn(r"(?s)// Hierarchy\n//-+\n\n/\*\n.*?\n\*/\n", "<HIERARCHY>", text)
        assert (dates, trees) == (1, 1), (path, dates, trees)
    return text.encode()

a, b = Path(sys.argv[1]), Path(sys.argv[2])
files = sorted(p.relative_to(a) for p in a.rglob("*") if p.is_file()
               and p.name != "litex.log"
               and (not p.relative_to(a).parts[0] == "software"
                    or p.suffix in {".bin", ".h", ".ld", ".mak"} and "generated" in p.parts or p.name == "bios.bin"))
other = sorted(p.relative_to(b) for p in b.rglob("*") if p.is_file()
               and p.name != "litex.log"
               and (not p.relative_to(b).parts[0] == "software"
                    or p.suffix in {".bin", ".h", ".ld", ".mak"} and "generated" in p.parts or p.name == "bios.bin"))
assert files == other, (set(files) ^ set(other))
bad = 0
for rel in files:
    x, y = normal(a / rel, a), normal(b / rel, b)
    same = x == y
    bad += not same
    print(f"{'same' if same else 'DIFF'}  {hashlib.sha256(x).hexdigest()[:16]}  {hashlib.sha256(y).hexdigest()[:16]}  {rel}")
print(f"{len(files)} files, {bad} differ")
sys.exit(1 if bad else 0)
