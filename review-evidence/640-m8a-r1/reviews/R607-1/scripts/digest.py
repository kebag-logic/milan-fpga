#!/usr/bin/env python3
"""R607-1: compare two export directories file by file.

    digest.py <export-A> <tree-A> <export-B> <tree-B>

Every regular file under each export's gw/ is read; the export directory and
the source tree path are replaced by fixed tokens, and LiteX's dated header
lines ("Auto-generated by LiteX ... on <date>") are blanked. Then the two sets
of files and their sha256 are compared. Prints one line per file and a total;
exit 1 when any file differs or exists on one side only.
"""
import hashlib
import re
import sys
from pathlib import Path

DATE = re.compile(rb"(LiteX \([0-9a-f]+\) on )[0-9-]+ [0-9:]+")


def norm(path: Path, export: Path, tree: Path) -> bytes:
    data = path.read_bytes()
    for real, token in ((str(export / "gw"), b"<EXPORT>"), (str(export), b"<EXPORTROOT>"), (str(tree), b"<TREE>")):
        data = data.replace(real.encode(), token)
    return DATE.sub(rb"\1<DATE>", data)


def files(export: Path, tree: Path) -> dict[str, str]:
    root = export / "gw"
    return {str(p.relative_to(root)): hashlib.sha256(norm(p, export, tree)).hexdigest()
            for p in sorted(root.rglob("*")) if p.is_file() and not p.is_symlink()}


a_exp, a_tree, b_exp, b_tree = (Path(x).resolve() for x in sys.argv[1:5])
a, b = files(a_exp, a_tree), files(b_exp, b_tree)
differ = 0
for name in sorted(set(a) | set(b)):
    if name not in a or name not in b:
        state = "only-" + ("B" if name not in a else "A")
    else:
        state = "same" if a[name] == b[name] else "DIFF"
    differ += state != "same"
    print(f"{state}\t{a.get(name, '-')[:16]}\t{b.get(name, '-')[:16]}\t{name}")
print(f"{len(set(a) | set(b))} files, {differ} differ")
sys.exit(1 if differ else 0)
