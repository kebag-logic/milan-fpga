#!/usr/bin/env python3
"""Compare both all-fabric shipping gateware exports with the merged dev parent.

No software compilation or implementation run; each export has its own clone.
"""
import concurrent.futures
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys

packet = Path(__file__).resolve().parent
if sys.argv[1:2] == ['--child']:
    tree, config, out = map(Path, sys.argv[2:])
    sys.path.insert(0, str(tree / 'sw/builder'))
    import endstation_builder as eb
    cfg = eb.load_config(str(tree / config))
    eb.build(str(tree / config))
    argv = eb.emit_soc_argv(cfg) + ['--entity-gen-dir', str(tree/'configs/generated'/cfg['name']),
                                  '--output-dir', str(out), '--no-compile-software']
    sys.path.insert(0, str(tree / 'sw/litex'))
    import milan_soc
    sys.argv = ['milan_soc.py', *argv]
    milan_soc.main()
    raise SystemExit(0)

source = Path(sys.argv[1]).resolve()
python = sys.argv[2]
scratch = packet / 'scratch/default-exports'
scratch.mkdir(exist_ok=True)
logs = packet / 'receipts'
env = json.loads((packet/'scratch/run-environment.json').read_text())
cases = []
for version, revision in [('dev','ac2c5e77bba1c0ae20ce2f69f711a1d17ead94a5'), ('head','76605880a20005cbc2acad1b23ba2ccebde64ca8')]:
    for shape in ('1x1_tdm8','8x8'):
        label = f'default-{version}-{shape}'
        tree = scratch/label
        if not tree.exists():
            subprocess.run(['git','clone','--quiet','--shared','--no-hardlinks',str(source),str(tree)],check=True)
            subprocess.run(['git','checkout','--quiet','--detach',revision],cwd=tree,check=True)
            for sub in ('protocol-processor','gptp-processor','third_party/verilog-axis'):
                subprocess.run(['git','-c','protocol.file.allow=always','-c',f'submodule.{sub}.url={source/sub}',
                                'submodule','update','--init',sub],cwd=tree,check=True,stdout=subprocess.DEVNULL)
        cases.append((label,tree,Path('configs')/f'endstation_ax7101_{shape}.yaml',tree/'export'))

def run(case):
    label,tree,config,out = case
    with (logs/(label+'.log')).open('w') as log:
        rc = subprocess.run([python,str(Path(__file__).resolve()),'--child',str(tree),str(config),str(out)],
                            cwd=tree/'sw/litex',env=env,stdout=log,stderr=subprocess.STDOUT).returncode
    (logs/(label+'.rc')).write_text(str(rc)+'\n')
    print(label,'rc',rc,flush=True)
    return rc

with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
    results = list(pool.map(run,cases))
if any(results):
    raise SystemExit(1)

def normalize(path,tree):
    data = path.read_bytes()
    if path.suffix in ('.bin','.init'):
        return data
    value = data.decode().replace(str(tree/'export'),'<OUT>').replace(str(tree),'<SOURCE>')
    value = re.sub(r'(?m)^.*Auto-generated by LiteX.* on \d{4}-\d\d-\d\d .*$', '<STAMP>', value)
    if path.suffix == '.v':
        value,n = re.subn(r'(?m)^// Date       : .*$', '<DATE>',value)
        assert n == 1
        value,n = re.subn(r'(?s)// Hierarchy\n//-+\n\n/\*\n.*?\n\*/\n','<HIERARCHY>',value)
        assert n == 1
    return value.encode()

for shape in ('1x1_tdm8','8x8'):
    a,b = (scratch/f'default-{version}-{shape}' for version in ('dev','head'))
    def files(root):
        return {p.relative_to(root/'export') for p in (root/'export').rglob('*')
                if p.is_file() and p.name != 'litex.log'}
    assert files(a) == files(b)
    for rel in sorted(files(a)):
        left,right = normalize(a/'export'/rel,a), normalize(b/'export'/rel,b)
        assert left == right,(shape,str(rel))
        print(shape,rel,hashlib.sha256(left).hexdigest(),'MATCH')
    print('PASS',shape,len(files(a)),'files equal; no software compiled')
