#!/usr/bin/env python3
"""Reviewer digest comparison of two LiteX exports.  Normalises only: each
export's own output directory, each source tree's root, LiteX generation-stamp
lines, the Verilog banner Date line and LiteX's comment-only hierarchy tree.
Every file in the gateware/ tree, csr.*, aem_*, flashboot_layout.json, and
software/include/generated/* and software/bios/bios.bin is compared.
Usage: digest_compare.py OUT_A TREE_A OUT_B TREE_B"""
import hashlib, re, sys
from pathlib import Path
a, ta, b, tb = map(Path, sys.argv[1:5])
def wanted(rel):
    p = rel.parts
    if p[0] != "software":
        return rel.name != "litex.log"
    return (len(p) > 2 and p[1] == "include" and p[2] == "generated") or rel.as_posix() == "software/bios/bios.bin"
def norm(path, out, tree):
    data = path.read_bytes()
    if path.suffix in {".bin", ".init"}:
        return data
    t = data.decode(errors="surrogateescape").replace(str(out), "<OUT>").replace(str(tree), "<TREE>")
    t = re.sub(r"(?m)^.*Auto-generated by LiteX.*\d{4}-\d\d-\d\d.*$", "<STAMP>", t)
    t = re.sub(r"(?m)^// Date\s*: .*$", "<DATE>", t)
    t = re.sub(r"(?s)// Hierarchy\n//-+\n\n/\*\n.*?\n\*/\n", "<HIERARCHY>", t)
    return t.encode(errors="surrogateescape")
fa = sorted(p.relative_to(a) for p in a.rglob("*") if p.is_file() and wanted(p.relative_to(a)))
fb = sorted(p.relative_to(b) for p in b.rglob("*") if p.is_file() and wanted(p.relative_to(b)))
only = set(fa) ^ set(fb)
bad = 0
for rel in sorted(set(fa) & set(fb)):
    x, y = norm(a / rel, a, ta), norm(b / rel, b, tb)
    bad += x != y
    print(f"{'same' if x == y else 'DIFF'}  {hashlib.sha256(x).hexdigest()[:16]}  {hashlib.sha256(y).hexdigest()[:16]}  {rel}")
for rel in sorted(only):
    print(f"ONLY  {'A' if rel in fa else 'B'}  {rel}")
print(f"{len(set(fa) & set(fb))} common files, {bad} differ, {len(only)} present on one side only")
sys.exit(1 if bad or only else 0)
