#!/usr/bin/env python3
"""Compare two gateware exports after normalising only run-specific text.

usage: export_digest.py <export-a> <export-b> [<tree-a> <tree-b>]

Normalised: each export's own directory path, each side's source-tree path (when given), LiteX's generation-timestamp
lines, the Verilog banner's Date line and LiteX's comment-only hierarchy tree
(its order varies between runs). litex.log is a run log and is not compared.
Every other file under gateware/ and software/include/generated/ is compared
byte for byte after that. Exit 0 when every file is equal and both sides list
the same files.
"""
import hashlib
import re
import sys
from pathlib import Path


def listing(root: Path) -> list[Path]:
    keep = []
    for p in sorted(root.rglob("*")):
        rel = p.relative_to(root)
        if not p.is_file() or p.name == "litex.log":
            continue
        if rel.parts[0] == "gateware" or rel.parts[:3] == ("software", "include", "generated"):
            keep.append(rel)
    return keep


def normal(path: Path, root: Path, tree: str | None) -> bytes:
    data = path.read_bytes()
    if path.suffix in {".init", ".bin"}:
        return data
    text = data.decode()
    text = text.replace(str(root), "<OUT>")
    if tree:
        text = text.replace(tree, "<TREE>")
    text = re.sub(r"(?mi)^.*Auto-generated by LiteX.* on \d{4}-\d\d-\d\d .*$", "<STAMP>", text)
    if path.suffix == ".v":
        text = re.sub(r"(?m)^// Date       : .*$", "<DATE>", text)
        text = re.sub(r"(?s)// Hierarchy\n//-+\n\n/\*\n.*?\n\*/\n", "<HIERARCHY>", text)
    return text.encode()


a, b = (Path(x).resolve() for x in sys.argv[1:3])
ta, tb = (str(Path(x).resolve()) for x in sys.argv[3:5]) if len(sys.argv) == 5 else (None, None)
fa, fb = listing(a), listing(b)
bad = 0
if fa != fb:
    print("FILE SETS DIFFER:", sorted(set(map(str, fa)) ^ set(map(str, fb))))
    bad += 1
for rel in sorted(set(fa) & set(fb)):
    x, y = normal(a / rel, a, ta), normal(b / rel, b, tb)
    same = x == y
    bad += not same
    print(f"{'same' if same else 'DIFF'}  {hashlib.sha256(x).hexdigest()[:16]}  "
          f"{hashlib.sha256(y).hexdigest()[:16]}  {rel}")
print(f"{len(set(fa) & set(fb))} common files, {bad} differ")
sys.exit(1 if bad else 0)
