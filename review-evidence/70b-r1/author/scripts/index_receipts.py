#!/usr/bin/env python3
"""Scrub host paths from the lane's receipts and write receipts/INDEX.md from the files present.

usage: python3 -B index_receipts.py OUTDIR

Every text receipt under OUTDIR/receipts has its host paths replaced by
placeholders, in place (the substitutions are listed in the index). The index
lists every file with its size and sha256, after the scrub. A file over 200 KB
is refused: it does not belong in the output directory.
"""
import hashlib
import sys
from pathlib import Path

out = Path(sys.argv[1]).resolve()
receipts = out / "receipts"
#: longest first, so a prefix never pre-empts a longer path
SUBS = [
    (str(out), "<out>"),
    ("$VALIDATION_STORAGE/scratch/70-a704", "<scratch>"),
    ("$LANES/70-boot-report-link", "<lane>"),
    ("$VALIDATION_TOOLS", "<tools>"),
    ("$VALIDATION_STORAGE", "<tmp>"),
    ("$WORKSPACE_HOME", "$HOME"),
    ("/tmp/", "<tmp>/"),
]
LIMIT = 200 * 1024

rows = []
for path in sorted(p for p in receipts.rglob("*") if p.is_file() and p.name != "INDEX.md"):
    data = path.read_bytes()
    try:
        text = data.decode()
    except UnicodeDecodeError:
        text = None
    if text is not None:
        scrubbed = text
        for old, new in SUBS:
            scrubbed = scrubbed.replace(old, new)
        if scrubbed != text:
            path.write_text(scrubbed)
            data = scrubbed.encode()
    if len(data) > LIMIT:
        sys.exit(f"REFUSED: {path.relative_to(out)} is {len(data)} B, over 200 KB")
    rows.append((path.relative_to(receipts).as_posix(), len(data), hashlib.sha256(data).hexdigest()))

lines = ["# Receipts index", "",
         "Generated by `scripts/index_receipts.py` from the files present. Host paths in text",
         "receipts are replaced by placeholders: " + ", ".join(f"`{new}`" for _, new in SUBS) + ".",
         "", "| File | Bytes | sha256 |", "|---|---:|---|"]
lines += [f"| `{name}` | {size} | `{digest}` |" for name, size, digest in rows]
lines += ["", f"{len(rows)} files."]
(receipts / "INDEX.md").write_text("\n".join(lines) + "\n")
print(f"indexed {len(rows)} files")
