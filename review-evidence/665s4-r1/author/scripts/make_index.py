#!/usr/bin/env python3
"""Replace host paths in every receipt by role placeholders, keeping each raw file's sha256, then
write receipts/INDEX.md from the files present: path, size, sha256 and, for a scrubbed file, the
raw sha256. Files over 200 KB are refused (they belong in scratch, by digest).
Usage: make_index.py PACKET_DIR RAW_COPY_DIR ROLES_FILE"""
import hashlib
import shutil
import sys
from pathlib import Path

packet, raw_dir = Path(sys.argv[1]), Path(sys.argv[2])
#: (host prefix, role) pairs, one tab-separated pair a line, from a file kept outside the packet.
ROLES = [tuple(line.split('\t')) for line in Path(sys.argv[3]).read_text().splitlines() if line]
digest = lambda data: hashlib.sha256(data).hexdigest()
rows, scrubbed, large = [], 0, []
for path in sorted(p for p in (packet / 'receipts').rglob('*') if p.is_file() and p.name != 'INDEX.md'):
    data = path.read_bytes()
    raw = digest(data)
    text = data.decode('utf-8', errors='surrogateescape')
    for host, role in ROLES:
        text = text.replace(host, role)
    new = text.encode('utf-8', errors='surrogateescape')
    keep = raw_dir / path.relative_to(packet)
    if new != data:
        keep.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(path, keep)
        path.write_bytes(new)
    if keep.is_file():
        raw = digest(keep.read_bytes())    # scrubbed now or by an earlier run: the raw copy's digest
        scrubbed += 1
    if len(new) > 200_000:
        large.append(str(path.relative_to(packet)))
    rows.append((str(path.relative_to(packet)), len(new), digest(new), raw if keep.is_file() else ''))
lines = ['# Receipts index (generated by scripts/make_index.py from the files present)', '',
         f'{len(rows)} files; {scrubbed} had host paths replaced by role placeholders (raw sha256 given).', '',
         '| File | Bytes | sha256 | Raw sha256 (before the path scrub) |', '|---|---:|---|---|']
lines += [f'| `{name}` | {size} | `{sha}` | {f"`{rawsha}`" if rawsha else "-"} |' for name, size, sha, rawsha in rows]
(packet / 'receipts' / 'INDEX.md').write_text('\n'.join(lines) + '\n')
print(f'{len(rows)} files indexed, {scrubbed} scrubbed, {len(large)} over 200 KB: {large}')
raise SystemExit(1 if large else 0)
