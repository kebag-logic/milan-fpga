#!/usr/bin/env python3
"""Render the per-page sampling ledgers and their summary from the statement ledger and the verdicts.

Usage: python3 -I render_sampling.py <ledger dir> <verdicts dir> <out dir>

Every numeric or normative statement of a release-facing page is one row:
its line, kind, text (shortened), what the mechanical checks covered and the
manual verdict. A statement counts as checked when it carries a verdict that
is not `partial`; the categories are

  code/spec  compared with a named source line, clause or issue state
  mechanical only the mechanical checks (clause or table exists, cited suites
             and paths exist, issue states) back it
  policy     a rule or instruction, checked for agreement with the contract it states
  history    a dated record, checked against what it cites
  finding    contradicted: the D0 finding named
  partial    part of the claim could not be recomputed offline (said why)
  read       read against the code examined, with no per-sentence source line;
             NOT counted as checked
  unchecked  no verdict

Verdicts are keyed by source line, so the sentences of one paragraph share a
verdict. A finding verdict on a line with several statements counts one
statement as the finding and, when the verdict says the rest are ok, the
others as code/spec.
"""
import json
import re
import sys
from collections import Counter
from pathlib import Path

ledger, verdicts_dir, out = (Path(a) for a in sys.argv[1:4])
out.mkdir(parents=True, exist_ok=True)
statements = [json.loads(l) for l in (ledger / "statements.jsonl").read_text().splitlines()]
auto = {(r["page"], r["line"]): r["auto"] for r in map(json.loads, (ledger / "auto.jsonl").read_text().splitlines())}
verdicts: dict = {}
for f in sorted(verdicts_dir.glob("*.json")):
    data = json.loads(f.read_text())
    for entry in data if isinstance(data, list) else [data]:
        verdicts.setdefault(entry["page"], {}).update(entry["v"])


def category(v: str) -> str:
    if v.startswith("F:"):
        return "finding"
    if v.startswith("partial"):
        return "partial"
    if v.startswith("policy"):
        return "policy"
    if v.startswith("read"):
        return "read"
    if v.startswith("hist"):
        return "history"
    if "clause/table exists in the section's standard" in v or v.startswith("mech"):
        return "mechanical"
    return "code/spec"


pages = []
for s in statements:
    if s["page"] not in pages:
        pages.append(s["page"])
summary = []
for page in pages:
    rows = [s for s in statements if s["page"] == page and (s["numeric"] or s["normative"])]
    allrows = [s for s in statements if s["page"] == page]
    v = verdicts.get(page, {})
    counts = Counter()
    body = [f"# Sampling ledger: {page}", "",
            "Every numeric or normative statement, with the mechanical checks and the manual verdict.", "",
            "| Line | Kind | Statement | Mechanical | Verdict |", "|---:|---|---|---|---|"]
    seen_lines: dict = {}
    for s in rows:
        verdict = v.get(str(s["line"]), "")
        cat = category(verdict) if verdict else "unchecked"
        k = seen_lines.get(s["line"], 0)
        seen_lines[s["line"]] = k + 1
        if cat == "finding" and k > 0 and "ok" in verdict:
            cat = "code/spec"
        counts[cat] += 1
        a = auto.get((page, s["line"]), {})
        mech = "; ".join(f"{k} {x.get('n', '')}" for k, x in a.items())
        text = re.sub(r"\s+", " ", s["text"]).replace("|", "\\|").replace("\u2014", "-")
        text = text if len(text) <= 160 else text[:157] + "..."
        verdict_cell = (verdict or "unchecked").replace("|", "\\|").replace("\u2014", "-")
        body.append(f"| {s['line']} | {s['kind']} | {text} | {mech or '-'} | {verdict_cell} |")
    slug = page.replace("/", "_").replace(".md", "")
    (out / f"{slug}.md").write_text("\n".join(body) + "\n", encoding="utf-8")
    checked = len(rows) - counts["unchecked"] - counts["partial"] - counts["read"]
    summary.append((page, len(allrows), len(rows), checked, counts))
cats = ["code/spec", "mechanical", "policy", "history", "finding", "partial", "read", "unchecked"]
lines = ["# Deeper sampling: sentences checked per page", "",
         "Generated by `tools/render_sampling.py` from the statement ledger, the mechanical checks and the",
         "verdict files. A statement is checked when its verdict is code/spec, mechanical, policy, history or",
         "finding; `read` (read against the code, no per-sentence source line) and `partial` are not counted.", "",
         "| Page | Statements | Numeric or normative | Checked | " + " | ".join(cats) + " | Ledger |",
         "|---|---:|---:|---:|" + "---:|" * len(cats) + "---|"]
tot = Counter()
for page, alls, n, checked, counts in summary:
    slug = page.replace("/", "_").replace(".md", "")
    lines.append(f"| `{page}` | {alls} | {n} | {checked} | " + " | ".join(str(counts[c]) for c in cats)
                 + f" | [{slug}.md]({slug}.md) |")
    tot["all"] += alls
    tot["n"] += n
    tot["checked"] += checked
    for c in cats:
        tot[c] += counts[c]
lines.append(f"| **total** | **{tot['all']}** | **{tot['n']}** | **{tot['checked']}** | "
             + " | ".join(f"**{tot[c]}**" for c in cats) + " | |")
(out / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("\n".join(lines[5:]))
