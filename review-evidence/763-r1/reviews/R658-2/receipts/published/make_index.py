#!/usr/bin/env python3
"""Write INDEX.md beside this script from the files present under it."""
import hashlib
from pathlib import Path

HERE = Path(__file__).resolve().parent
rows = []
for path in sorted(p for p in HERE.rglob("*") if p.is_file() and p.name != "INDEX.md"):
    data = path.read_bytes()
    rows.append(f"| `{path.relative_to(HERE).as_posix()}` | {len(data)} | `{hashlib.sha256(data).hexdigest()}` |")
(HERE / "INDEX.md").write_text("# Receipts index\n\nGenerated by `make_index.py` from the files present.\n\n"
                               "| File | Bytes | sha256 |\n|---|---|---|\n" + "\n".join(rows) + "\n")
