#!/usr/bin/env python3
"""Write receipts/INDEX.md from the files present: one row per file, its size and its first line.

usage: receipts_index.py <receipts dir>
"""
import sys
from pathlib import Path

root = Path(sys.argv[1])
rows = []
for f in sorted(p for p in root.rglob("*") if p.is_file() and p.name != "INDEX.md"):
    try:
        first = f.read_text(errors="replace").splitlines()[0][:120] if f.stat().st_size else ""
    except IndexError:
        first = ""
    first = first.replace("|", "/")
    rows.append(f"| `{f.relative_to(root)}` | {f.stat().st_size} | {first} |")
(root / "INDEX.md").write_text("# Receipts\n\nGenerated by `scripts/receipts_index.py` from the files present.\n\n"
                               "| File | Bytes | First line |\n|---|---|---|\n" + "\n".join(rows) + "\n")
print(f"{len(rows)} files indexed")
