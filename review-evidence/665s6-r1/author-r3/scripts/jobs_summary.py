#!/usr/bin/env python3
"""Summarise verify_jobs.py's --json table: every step that ran, and per job the steps not run by reason.

usage: jobs_summary.py <jobs-table.json> <out.md>
"""
import json
import sys
from collections import Counter, defaultdict

rows = json.load(open(sys.argv[1]))
rows = rows["rows"] if isinstance(rows, dict) else rows
ran = [r for r in rows if r["result"] != "NOT RUN"]
skipped = defaultdict(Counter)
for r in rows:
    if r["result"] == "NOT RUN":
        skipped[(r["workflow"], r["job"])][r["detail"]] += 1
out = ["# Replay summary", "", "Generated by `scripts/jobs_summary.py` from `verify_jobs.py --json`.", "",
       f"{len(ran)} steps ran, {sum(r['result'].startswith('BAD') or r['result'] == 'MISSING' for r in rows)} bad; "
       f"{sum(sum(c.values()) for c in skipped.values())} not run with a reason.", "",
       "## Every step that ran", "", "| Workflow | Job | Step | Name | Result |", "|---|---|---|---|---|"]
out += [f"| {r['workflow']} | {r['job']} | {r['step']} | {r['name']} | {r['result']} |" for r in ran]
out += ["", "## Steps not run, by job and reason", "", "| Workflow | Job | Steps | Reason |", "|---|---|---|---|"]
for (wf, job), c in sorted(skipped.items()):
    for reason, n in c.items():
        out.append(f"| {wf} | {job} | {n} | {reason.replace('|', '/')[:300]} |")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
print(f"{len(ran)} ran, {len(skipped)} jobs with steps not run")
