#!/usr/bin/env python3
"""Generate receipts/INDEX.md and receipts/rc.txt from the files present.

Usage: python3 -I make_index.py <output dir>

INDEX.md lists every file under receipts/ and scripts/, subdirectories
included, with its size and SHA-256; rc.txt lists every *.rc under
receipts/ with its recorded return code. Both are regenerated from the
directory, never edited by hand.
"""
import hashlib
import sys
from pathlib import Path

out = Path(sys.argv[1])
receipts = out / "receipts"
rcs = sorted(receipts.rglob("*.rc"))
(receipts / "rc.txt").write_text("".join(f"{p.relative_to(receipts).with_suffix('')} {p.read_text().strip()}\n"
                                         for p in rcs))
rows = []
for folder in ("receipts", "scripts"):
    for path in sorted((out / folder).rglob("*")):
        if path.is_file() and path.name != "INDEX.md":
            rows.append(f"| `{path.relative_to(out)}` | {path.stat().st_size} | "
                        f"`{hashlib.sha256(path.read_bytes()).hexdigest()}` |")
(receipts / "INDEX.md").write_text(
    "# Receipts index, #396 part A round 6\n\n"
    "Generated by `scripts/make_index.py` from the files present.\n\n"
    "| File | Bytes | SHA-256 |\n|---|---|---|\n" + "\n".join(rows) + "\n")
print(f"{len(rows)} files indexed; {len(rcs)} return codes")
