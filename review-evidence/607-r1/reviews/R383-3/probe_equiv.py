#!/usr/bin/env python3
"""[R383] Item (2): does the head probe's Builder override (with_bios=False
include step) change anything the real generated build reads?

On an interpreter that HAS the firmware data packages, run for each shipping
config/port both
  head  = the committed sw/builder/test_shipping_clock_constraints.py, and
  prior = the f3bd6b66 version of that file (no guard, no override),
each with --output-dir kept, then compare every file under the two output
trees. The .tcl/.xdc/.v are compared after normalizing output dir, tree root
and LiteX date stamps (and, in the .v, whole-line // comments incl. the
unordered hierarchy summary); every other file drops LiteX
date-stamp lines and litex.log (a wall-clock log) is skipped. Every other file is listed as only-in-head,
only-in-prior, or differing.
Usage: probe_equiv.py <tree> <scratch dir> <python with firmware packages>"""
import hashlib, os, re, subprocess, sys
from pathlib import Path
tree, scratch, py = Path(sys.argv[1]).resolve(), Path(sys.argv[2]).resolve(), sys.argv[3]
prior = tree / "sw/builder/_r383_prior_shipping_probe.py"
prior.write_text(subprocess.run(["git", "-C", str(tree), "show",
    "f3bd6b6694ab61b8f70b7f13f1049a14a6fb3461:sw/builder/test_shipping_clock_constraints.py"],
    capture_output=True, text=True, check=True).stdout)
STAMP = re.compile(r"^(// Date\s+:|//\s+Auto-Generated by LiteX|# Auto-Generated by LiteX).*$", re.M | re.I)
def norm(p, root):
    t = p.read_text(errors="replace").replace(str(root), "<OUT>").replace(str(tree), "<ROOT>")
    t = STAMP.sub("<STAMP>", t)
    if p.suffix == ".v":
        t = "\n".join(l for l in t.splitlines() if not l.lstrip().startswith("//")
                      and not any(g in l for g in "│├└"))
    return t
bad = 0
try:
    for config in ("ax7101_1x1_tdm8", "ax7101_8x8"):
        for port in ("e1", "e2"):
            outs = {}
            for label, f in (("head", tree / "sw/builder/test_shipping_clock_constraints.py"), ("prior", prior)):
                out = scratch / f"equiv-{label}-{config}-{port}"
                subprocess.run(["rm", "-rf", str(out)], check=True)
                r = subprocess.run([py, "-B", str(f), "--config", config, "--port", port, "--output-dir", str(out)],
                                   cwd=tree / "sw/litex", capture_output=True, text=True, timeout=900,
                                   env=dict(os.environ, PYTHONHASHSEED="0"))
                mark = [l for l in r.stdout.splitlines() if l.startswith("[constraints] shipping")]
                print(f"{config} {port} {label}: rc={r.returncode} marker={'PASS' if mark and mark[0].endswith('PASS') else 'none'}")
                if r.returncode:
                    print("   ", (r.stdout + r.stderr).strip().splitlines()[-1][:200]); bad += 1
                outs[label] = out
            files = {k: {p.relative_to(v) for p in v.rglob("*") if p.is_file()} for k, v in outs.items()}
            only_h, only_p = sorted(files["head"] - files["prior"]), sorted(files["prior"] - files["head"])
            diff = []
            for rel in sorted(files["head"] & files["prior"]):
                if rel.name == "litex.log":  # wall-clock build log, not a build input
                    continue
                a, b = norm(outs["head"] / rel, outs["head"]), norm(outs["prior"] / rel, outs["prior"])
                if a != b:
                    diff.append(str(rel))
            for name in ("alinx_ax7101.tcl", "alinx_ax7101.xdc", "alinx_ax7101.v"):
                rel = Path("gateware") / name
                a, b = norm(outs["head"] / rel, outs["head"]), norm(outs["prior"] / rel, outs["prior"])
                same = a == b
                bad += not same
                print(f"   {name}: head vs prior {'IDENTICAL' if same else 'DIFFERENT'} sha256={hashlib.sha256(a.encode()).hexdigest()[:16]}")
            print(f"   files: head={len(files['head'])} prior={len(files['prior'])}")
            print(f"   only in prior: {[str(p) for p in only_p]}")
            print(f"   only in head: {[str(p) for p in only_h]}")
            print(f"   differing after normalization: {diff}")
finally:
    prior.unlink()
print(f"gateware differences={bad}")
sys.exit(1 if bad else 0)
