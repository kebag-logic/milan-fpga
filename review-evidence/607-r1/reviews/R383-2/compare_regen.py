#!/usr/bin/env python3
"""[R383] Compare head vs 350af5dc regenerated build inputs (same flags, no vendor
run). Normalizes tree root, output dir and LiteX date-stamp lines; in the .v it
also drops whole-line // comments (LiteX header: date and an unordered hierarchy
summary tree whose box-drawing lines are also dropped), so only non-comment netlist text is compared.
Usage: compare_regen.py <regen dir> <head tree> <base tree>"""
import hashlib, re, sys
from pathlib import Path
regen, head, base = Path(sys.argv[1]).resolve(), Path(sys.argv[2]).resolve(), Path(sys.argv[3]).resolve()
STAMP = re.compile(r"^(// Date\s+:|//\s+Auto-Generated by LiteX on|# Auto-Generated by LiteX on).*$", re.M)
bad = 0
for seed in ("asl", "eto", "eppo"):
    for name in ("alinx_ax7101.tcl", "alinx_ax7101.xdc", "alinx_ax7101.v"):
        texts = []
        for label, tree in (("head", head), ("base350", base)):
            d = regen / f"{label}-{seed}"
            t = (d / "gateware" / name).read_text().replace(str(d), "<OUT>").replace(str(tree), "<ROOT>")
            t = STAMP.sub("<STAMP>", t)
            if name.endswith(".v"):
                t = "\n".join(l for l in t.splitlines() if not l.lstrip().startswith("//")
                              and not any(g in l for g in "\u2502\u251c\u2514"))
            texts.append(t)
        same = texts[0] == texts[1]
        bad += not same
        print(f"{seed} {name}: head vs 350af5dc {'IDENTICAL' if same else 'DIFFERENT'} "
              f"sha256={hashlib.sha256(texts[0].encode()).hexdigest()[:16]}")
print(f"differences={bad}")
sys.exit(1 if bad else 0)
