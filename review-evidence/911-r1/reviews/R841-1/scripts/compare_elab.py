#!/usr/bin/env python3
"""Reviewer probe (#911): compare two elaboration trees file by file.

usage: compare_elab.py <tree A> <tree B>
Prints the file counts and every file whose bytes differ; for a differing
text file it also says whether the difference survives removing the lines
that change between any two elaborations (LiteX's generated-on timestamp
and the Verilog hierarchy comment block). litex.log is skipped; only SCOPE is compared, with each tree's own path normalised.
"""
import hashlib
import re
import sys
from pathlib import Path

A, B = Path(sys.argv[1]), Path(sys.argv[2])
VOLATILE = re.compile(rb"(generated on|Auto-generated by LiteX|^// Date|^# Date|timestamp)", re.I)


SCOPE = ("gateware/", "software/include/generated/", "aem_desc", "csr.", "flashboot_layout.json",
         "software/bios/bios.bin")


def files(root: Path) -> dict[str, bytes]:
    """The build inputs and headers under `root`, its own path replaced by <OUT>."""
    out = {}
    for p in sorted(root.rglob("*")):
        rel = str(p.relative_to(root))
        if p.is_file() and p.name != "litex.log" and rel.startswith(SCOPE):
            out[rel] = p.read_bytes().replace(str(root).encode(), b"<OUT>")
    return out


def normal(data: bytes) -> bytes:
    """Drop volatile lines and the Verilog hierarchy comment (/* ... */ header)."""
    out, in_hier = [], False
    for line in data.splitlines():
        if line.startswith(b"/*") and b"Hierarchy" in data[:4096]:
            in_hier = True
        if in_hier:
            if b"*/" in line:
                in_hier = False
            continue
        if VOLATILE.search(line):
            continue
        out.append(line)
    return b"\n".join(out)


fa, fb = files(A), files(B)
print(f"files: {len(fa)} in A, {len(fb)} in B")
for name in sorted(set(fa) ^ set(fb)):
    print(f"only in {'A' if name in fa else 'B'}: {name}")
same = 0
for name in sorted(set(fa) & set(fb)):
    if fa[name] == fb[name]:
        same += 1
        continue
    survives = normal(fa[name]) != normal(fb[name])
    print(f"differs: {name}  A {hashlib.sha256(fa[name]).hexdigest()[:16]}  "
          f"B {hashlib.sha256(fb[name]).hexdigest()[:16]}  "
          f"{'SUBSTANTIVE' if survives else 'volatile lines only'}")
print(f"byte-identical: {same}")
