"""gen_index.py <output-dir>: INDEX.md listing every file present under the output directory (path, bytes,
SHA-256), generated from the files themselves; INDEX.md itself is excluded. Refuses a file over 200 KB."""
import hashlib
import sys
from pathlib import Path

root = Path(sys.argv[1])
rows, big = [], []
for path in sorted(p for p in root.rglob('*') if p.is_file() and p.name != 'INDEX.md'):
    data = path.read_bytes()
    if len(data) > 200 * 1024:
        big.append(f'{path.relative_to(root)} ({len(data)} bytes)')
    rows.append(f'| `{path.relative_to(root)}` | {len(data):,} | `{hashlib.sha256(data).hexdigest()}` |')
if big:
    sys.exit('over 200 KB: ' + ', '.join(big))
(root / 'INDEX.md').write_text('# Index of the #814 [A703] output directory\n\nGenerated by `scripts/gen_index.py` from the files '
                               'present.\n\n| File | Bytes | SHA-256 |\n|---|---:|---|\n' + '\n'.join(rows) + '\n')
print(f'{len(rows)} files indexed')
