#!/usr/bin/env python3
"""Write INDEX.md for this output directory from the files present: path, bytes, sha256, one row each.

usage: python3 gen_index.py <output-dir>
INDEX.md itself is left out (it cannot hold its own digest). Refuses a file over 200 KB, which belongs outside
the directory with its digest and size recorded instead.
"""
import hashlib
import sys
from pathlib import Path

root = Path(sys.argv[1]).resolve()
rows, big = [], []
for path in sorted(p for p in root.rglob('*') if p.is_file()):
    rel = path.relative_to(root).as_posix()
    if rel == 'INDEX.md' or '__pycache__' in rel:
        continue
    data = path.read_bytes()
    if len(data) > 200_000:
        big.append(rel)
    rows.append(f'| `{rel}` | {len(data)} | `{hashlib.sha256(data).hexdigest()}` |')
if big:
    sys.exit('over 200 KB: ' + ', '.join(big))
text = ['# Receipts index, [A670] on #780', '',
        f'Generated by `scripts/gen_index.py` from the {len(rows)} files present in this directory '
        '(path, bytes, sha256).', '',
        '| Path | Bytes | sha256 |', '|---|---:|---|', *rows, '']
(root / 'INDEX.md').write_text('\n'.join(text))
print(f'INDEX.md: {len(rows)} files')
