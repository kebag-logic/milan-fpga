"""Write INDEX.md: every file present in this output directory, with its size and SHA-256, generated from the files.

Refuses a file over 200 KB (the output directory holds receipts, not trees or builds) and a file naming a host path.
usage: python3 make_index.py
"""
from pathlib import Path
import hashlib
import re

root = Path(__file__).resolve().parent
HOST = re.compile(rb"/home/[a-z]+/|$VALIDATION_STORAGE/")
lines = ["# Receipt and artifact index", "", "Generated by `make_index.py` from the files present.", "",
         "| Relative file | Bytes | SHA-256 |", "|---|---:|---|"]
bad = []
for path in sorted(root.rglob("*")):
    if not path.is_file() or path.name == "INDEX.md" or "__pycache__" in path.parts:
        continue
    data = path.read_bytes()
    rel = path.relative_to(root)
    if len(data) > 200_000:
        bad.append(f"{rel}: {len(data)} bytes, over 200 KB")
    if HOST.search(data) and path.name != "make_index.py":
        bad.append(f"{rel}: names a host path")
    lines.append(f"| {rel} | {len(data)} | `{hashlib.sha256(data).hexdigest()}` |")
if bad:
    raise SystemExit("REFUSED:\n" + "\n".join(bad))
(root / "INDEX.md").write_text("\n".join(lines) + "\n")
print(f"Indexed {len(lines) - 6} files; each below 200 KB, none naming a host path.")
