#!/usr/bin/env python3
"""Focused, read-only source checks and disposable parent patch application."""
import ast
import concurrent.futures
import hashlib
import json
import pathlib
import re
import shutil
import subprocess
import sys

P = pathlib.Path(__file__).resolve().parent
SRC = pathlib.Path(sys.argv[1]).resolve()
HEAD = '2022d363fc622f6bbf4c312239fc3db741b4d29a'
OLD = '53ac2e9d75ceb381c2d2b04854e760304d9ae43f'
SCRATCH = P / 'scratch' / 'checks'
SCRATCH.mkdir(parents=True, exist_ok=True)

def run(args, cwd=SRC):
    return subprocess.check_output(args, cwd=cwd, stderr=subprocess.STDOUT)

assert run(['git', 'rev-parse', 'HEAD']).decode().strip() == HEAD
assert run(['git', 'rev-parse', 'HEAD^{tree}']).decode().strip() == '249bdbe6209bbc7ec17a816c26823ad97bb6d748'
delta = run(['git', 'diff', OLD, HEAD])
(P / 'round2.diff').write_bytes(delta)
(P / 'source.diff').write_bytes(run(['git', 'diff', '43acfbcc', HEAD]))
assert not run(['git', 'diff', OLD, HEAD, '--', '*.sv', '*.hex'])

def normalized_ast(data):
    tree = ast.parse(data)
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            if node.body and isinstance(node.body[0], ast.Expr) and isinstance(node.body[0].value, ast.Constant) and isinstance(node.body[0].value.value, str):
                node.body.pop(0)
    return ast.dump(tree, include_attributes=False)

gen = 'hdl/ucode/gen_gptp_ucode.py'
assert normalized_ast(run(['git', 'show', f'{OLD}:{gen}'])) == normalized_ast((SRC / gen).read_bytes())
def cpp_tokens(data):
    tokens = re.findall(r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/|\S', data)
    return [x for x in tokens if not x.startswith(('//', '/*'))]
cpp = 'tb/verilator/engine/sim_main.cpp'
assert cpp_tokens(run(['git', 'show', f'{OLD}:{cpp}']).decode()) == cpp_tokens((SRC / cpp).read_text())
rtl = 'hdl/top/KL_gptp_engine.sv'
for rev in ['43acfbcc', OLD]:
    old = run(['git', 'show', f'{rev}:{rtl}']).decode().split(');', 1)[0]
    new = (SRC / rtl).read_text().split(');', 1)[0]
    assert cpp_tokens(old) == cpp_tokens(new)
print('PASS: exact head/tree; unchanged RTL, four images, Python executable AST, C++ executable tokens, and public module declaration.')

recipes = [('engine', 'tb/verilator/engine/gptp_ucode.hex', ['--clk-hz','2000000','--cease-ms','3000']),
           ('ucpu', 'tb/verilator/ucpu/gptp_ucode.hex', []),
           ('tsngen', 'tb/tsngen/gptp_ucode.hex', ['--clk-hz','2000000']),
           ('ooc', 'syn/ooc/work/gptp_ucode.hex', [])]
def image_check(recipe):
    name, tracked, args = recipe
    out = SCRATCH / (name + '.hex')
    log = run([sys.executable, str(SRC / gen), *args, '-o', str(out)])
    assert b'1015 real (99.1%)' in log
    assert out.read_bytes() == (SRC / tracked).read_bytes()
    return f'PASS: {name}: 1015/1024, nine free; regenerated bytes match {tracked}; sha256={hashlib.sha256(out.read_bytes()).hexdigest()}'
with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
    for result in pool.map(image_check, recipes): print(result)

pub = P / 'public-evidence' / 'author-r2'
receipts = pub / 'receipts'
rows = re.findall(r'^\| `([^`]+)` \| (\d+) \| `([0-9a-f]+)` \|$', (receipts / 'INDEX.md').read_text(), re.M)
actual = {x.relative_to(receipts).as_posix() for x in receipts.rglob('*') if x.is_file() and x.name != 'INDEX.md'}
assert {x[0] for x in rows} == actual
for name, size, digest in rows:
    data = (receipts / name).read_bytes()
    assert len(data) == int(size) and hashlib.sha256(data).hexdigest().startswith(digest), name
print(f'PASS: receipt index exactly matches all {len(rows)} files, sizes and hash prefixes.')

parent = SCRATCH / 'parent'
for rel in ['tb/verilator/gptp_shadow/sim_main.cpp', 'tb/verilator/milan_dp/sim_gptp.cpp', 'tb/verilator/milan_dp/sim_ax1x1gptp.cpp']:
    dest = parent / rel
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(P / 'public-authorities' / pathlib.Path(rel).name, dest)
patches = ['gptp_shadow-85', 'milan_dp-85', 'milan_dp-82', 'milan_dp_gptp-84']
for name in patches:
    patch = pub / ('parent-adoption-' + name + '.patch')
    run(['git', 'apply', '--check', str(patch)], parent)
    run(['git', 'apply', str(patch)], parent)
    print(f'PASS: parent companion applies in order: {patch.name}')
print('PASS: no source checkout file was changed; disposable patch tree is under scratch/.')

tree = {}
for row in run(['git','ls-tree','-rz',HEAD]).split(b'\0'):
    if not row: continue
    meta, path = row.split(b'\t',1)
    mode, kind, oid = meta.split()
    tree[path] = (mode, oid)
    if mode == b'160000': continue
    f = SRC / path.decode()
    assert f.is_file() and not f.is_symlink(), path
    data = f.read_bytes()
    actual_oid = hashlib.sha1(b'blob ' + str(len(data)).encode() + b'\0' + data).hexdigest().encode()
    assert actual_oid == oid, path
    assert bool(f.stat().st_mode & 0o111) == (mode == b'100755'), path
index = {}
for row in run(['git','ls-files','--stage','-z']).split(b'\0'):
    if not row: continue
    meta, path = row.split(b'\t',1)
    mode, oid, stage = meta.split()
    assert stage == b'0'
    index[path] = (mode,oid)
assert index == tree
assert not run(['git','status','--porcelain=v1','--untracked-files=all'])
print(f'PASS: {len(tree)} tracked blob bytes/modes and all index entries match HEAD; gitlinks={[p.decode() for p,(m,o) in tree.items() if m == b"160000"]}; worktree clean.')
